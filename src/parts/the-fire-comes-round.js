    + mix(.5, fcrN3(vec3(fcrM3*p.xz*(1./2.9), 1.)), (1. - smoothstep(1.4, 4., fw)))*.17 + mix(.5, fcrN3(vec3(fcrM1*p.xz*(1./.93), 5.)), (1. - smoothstep(.45, 1.3, fw)))*.11;
