  // THE TEST CHOOSES THE PLACE (rule 16: nothing is thinned or hidden by where the lens is): steam and mist are
  // born only where their whole rise and lean, at their size there (with all their forms), keep NEAR.steam metres
  // of the world from the route's line, spray only where it keeps NEAR.spray: so nothing of them can ever cross
  // the lens, and no shader fades them by its distance. clearAir proves it with the same figures.
  const fq = FK.steam, wd = env.wind, lk = wd.kind === 'upright' ? 0.25 : 1, away = [(wd.x * cst.ax + wd.z * cst.az) * lk, (wd.x * cst.rx + wd.z * cst.rz) * lk];   // the lean: down the visit's wind, as the smoke leans (in the castle's frame)
