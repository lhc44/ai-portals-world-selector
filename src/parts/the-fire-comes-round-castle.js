  const rf = []; for (const q of routePts) { const dx = q.x - cst.x, dz = q.z - cst.z, a = (dx * cst.ax + dz * cst.az) / K; if (a > -330) rf.push([a, (q.y + 4) / K - 4, (dx * cst.rx + dz * cst.rz) / K]); }
