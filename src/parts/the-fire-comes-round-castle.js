    if (kind === 0) {                                                        // one soft column (its foot a little off the place, its own breadth)
      const an = fq.range(0, 6.2832), l = fq.range(0, 1); forms.push([...d, Math.cos(an) * l, fq(), Math.sin(an) * l, fq.range(0.75, 1)]);
    } else forms.push([...d, 0, 0, 0, 1]);
