  // drum y metres round it; on the hoop y 1 on its inner lip; in a window y its lamp, z, w the place from the lamp
  // (m); on a gallery's wall y the place along it in bays, z metres over its floor, w a bay's breadth (m).
  // aO: x the shade of the place (corners and recesses darken: 1 open, less shut in), y the lamps' light on the
  // stone there (in a window: how far out from its back, 0..1)
  const MAXV = 300000, P = new Float32Array(MAXV * 3), Nn = new Float32Array(MAXV * 3), Lc = new Float32Array(MAXV * 3), Mt = new Float32Array(MAXV * 4), Ao = new Float32Array(MAXV * 2), I = new Uint32Array(MAXV * 3);
  const G = { nv: 0, ni: 0 };
  await pause();
