// a mass of steam against a place (the castle's frame): along its whole rise and lean, at its size there
function steamReach(u, a, qy, c) {
  if (hyp(a - u.a, c - u.c) > u.lean + 2.4 * u.size * u.ext + 40) return Infinity;
  let m = Infinity;
  for (let f = 0; f <= 1.001; f += 0.125) {
    const up = 1 - (1 - f) * (1 - f), ca = u.a + u.la * f * f, cc = u.c + u.lc * f * f, cy = u.y + u.rise * up;
    m = Math.min(m, hyp3(a - ca, qy - cy, c - cc) - u.ext * u.size * (0.42 + 0.95 * f));
  }
  return m;
}

