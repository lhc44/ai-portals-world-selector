// ---- THE GREAT DOME'S PLACE, BY THE CITY'S OWN PLAN (the lead's ruling, the sixth mend). The city is laid out on the
// wall's own bay lines: the axes of its buttresses and wall towers, one every WALL.butt (36 m) outward from the gate's
// bastions. THE RULE: the Great Dome stands in the plan's open plot EAST of the gate's axis, between the Lesser Dome's
