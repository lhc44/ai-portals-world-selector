// a plan outline (a closed convex list of [x, z]) moved outward by d (mitred corners)
function offsetPlan(pts, d) {
  const n = pts.length, out = []; let area = 0;
  for (let i = 0; i < n; i++) { const p = pts[i], q = pts[(i + 1) % n]; area += p[0] * q[1] - q[0] * p[1]; }
  const sg = area > 0 ? 1 : -1;
  for (let i = 0; i < n; i++) {
    const a = pts[(i + n - 1) % n], b = pts[i], c = pts[(i + 1) % n];
    let e1x = b[0] - a[0], e1z = b[1] - a[1], e2x = c[0] - b[0], e2z = c[1] - b[1]; const l1 = Math.hypot(e1x, e1z), l2 = Math.hypot(e2x, e2z);
    e1x /= l1; e1z /= l1; e2x /= l2; e2z /= l2;
    const n1x = e1z * sg, n1z = -e1x * sg, n2x = e2z * sg, n2z = -e2x * sg, k = 1 + n1x * n2x + n1z * n2z;
    out.push([b[0] + (n1x + n2x) * d / k, b[1] + (n1z + n2z) * d / k]);
  }
  return out;
}
// a low hipped copper roof over a plan outline: eaves 1 m out, a fascia, a shaded soffit, slopes to a short level ridge
function hipRoof(K, plan, yEave, ra, rb, yTop, over = 1) {
  const eave = offsetPlan(plan, over), n = plan.length, R = (p) => (Math.hypot(p[0] - ra[0], p[1] - ra[1]) <= Math.hypot(p[0] - rb[0], p[1] - rb[1]) ? ra : rb);
  for (let i = 0; i < n; i++) {
    const p = eave[i], q = eave[(i + 1) % n], pi = plan[i], qi = plan[(i + 1) % n], rp = R(p), rq = R(q);
    const mx = (p[0] + q[0]) / 2 - (pi[0] + qi[0]) / 2, mz = (p[1] + q[1]) / 2 - (pi[1] + qi[1]) / 2, o = [mx, 0, mz];
    K.face(p[0], p[1], q[0], q[1], yEave - 0.25, yEave, o, T.roofShade, T.roof);
    K.quad([p[0], yEave - 0.25, p[1]], [q[0], yEave - 0.25, q[1]], [qi[0], yEave - 0.25, qi[1]], [pi[0], yEave - 0.25, pi[1]], [0, -1, 0], T.soffit);
    const ps = [[p[0], yEave, p[1]], [q[0], yEave, q[1]], [rq[0], yTop, rq[1]]]; if (rp !== rq) ps.push([rp[0], yTop, rp[1]]);
    K.poly(ps, [mx, 3, mz], T.roof);
  }
}
// A CAP OF OUR OWN over a plan outline (C4): eaves `over` out with a fascia and a shaded soffit, a steep copper skirt
// rising `rise` to an outline `inset` within the walls (steep, so it is seen from the road below), a bright roll round
// its head and a level deck within
function capRoof(K, plan, yEave, rise, over, inset) {
  const eave = offsetPlan(plan, over), head = offsetPlan(plan, -inset), n = plan.length, yT = yEave + rise;
  for (let i = 0; i < n; i++) {
    const j = (i + 1) % n, p = eave[i], q = eave[j], pi = plan[i], qi = plan[j], hp = head[i], hq = head[j];
    const o = [(p[0] + q[0] - pi[0] - qi[0]) / 2, 0, (p[1] + q[1] - pi[1] - qi[1]) / 2];
    K.face(p[0], p[1], q[0], q[1], yEave - 0.3, yEave, o, T.roofShade, T.roof);
    K.quad([p[0], yEave - 0.3, p[1]], [q[0], yEave - 0.3, q[1]], [qi[0], yEave - 0.3, qi[1]], [pi[0], yEave - 0.3, pi[1]], [0, -1, 0], T.soffit);
    K.quad([p[0], yEave, p[1]], [q[0], yEave, q[1]], [hq[0], yT, hq[1]], [hp[0], yT, hp[1]], [o[0], 1, o[2]], [T.roofShade, T.roofShade, T.roof, T.roof]);
    K.face(hp[0], hp[1], hq[0], hq[1], yT, yT + 0.35, o, T.rib);
  }
  K.poly(head.map((p) => [p[0], yT + 0.35, p[1]]), [0, 1, 0], T.roof);
}
