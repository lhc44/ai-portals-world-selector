  // bead and no white dot), with a faint emissive of its own far under the bloom's threshold (under a tenth of
  // white: glass is never quite dark). No light, nothing switched.
  const lampGlass = new THREE.MeshStandardMaterial({ color: new THREE.Color(0.34, 0.66, 0.44), roughness: 0.16, metalness: 0, emissive: new THREE.Color(0.04, 0.09, 0.05) });
  const all = [stone, copper, tile, gem, paving, leafage, lampGlass];
