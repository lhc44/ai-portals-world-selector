const mix3 = (a, b, t) => [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t, a[2] + (b[2] - a[2]) * t];

// the gate's own opening, offset outward by d metres: the right half as [x, y] from the foot of the jamb to the middle of
// the head (two straight slopes meeting at a blunt apex: neither a round arch nor a horseshoe); the left half mirrors it
function gateHalf(d, half = GATE.half, spring = GATE.spring, apex = GATE.apex, blunt = GATE.blunt) {
  const sx = blunt - half, sy = apex - spring, l = Math.hypot(sx, sy), nx = sy / l, ny = -sx / l;      // the slope's outward normal
  const t0 = (d - nx * d) / sx, t1 = (apex + d - spring - ny * d) / sy;
  return [[half + d, 0], [half + d, spring + ny * d + sy * t0], [half + nx * d + sx * t1, apex + d], [0, apex + d]];
}

// a row of openings of the gate's own shape along the upright face from (ax, az) to (bx, bz): thick piers, reveals that go
// dark inward, a sill, and behind them the gallery's floor, back and ceiling in baked shade (the roof and the piers keep
// the sun off them at every height the design deals)
function arcade(S, ax, az, bx, bz, out, y0, ys, ya, y1, bay, open, deep, gal) {
  const len = Math.hypot(bx - ax, bz - az), n = Math.max(1, Math.round(len / bay)), bw = len / n, ux = (bx - ax) / len, uz = (bz - az) / len;
  const ix = -out[0], iz = -out[2], P = (s, y, d) => [ax + ux * s + ix * d, y, az + uz * s + iz * d];
  const lit = T.body, rim = [0.74, 0.78, 0.74], inn = T.dim, U = [ux, 0, uz], Um = [-ux, 0, -uz];
  for (let k = 0; k < n; k++) {
    const s0 = k * bw, s1 = s0 + bw, sl = s0 + (bw - open) / 2, sr = sl + open, sc = (sl + sr) / 2, b = open * 0.13;
    S.quad(P(s0, y0, 0), P(sl, y0, 0), P(sl, y1, 0), P(s0, y1, 0), out, lit); S.quad(P(sr, y0, 0), P(s1, y0, 0), P(s1, y1, 0), P(sr, y1, 0), out, lit);
    S.quad(P(sl, ys, 0), P(sc - b, ya, 0), P(sc - b, y1, 0), P(sl, y1, 0), out, lit); S.quad(P(sc - b, ya, 0), P(sc + b, ya, 0), P(sc + b, y1, 0), P(sc - b, y1, 0), out, lit);
    S.quad(P(sc + b, ya, 0), P(sr, ys, 0), P(sr, y1, 0), P(sc + b, y1, 0), out, lit);
    if (deep <= 0) continue;
    const cc = [rim, inn, inn, rim];
    S.quad(P(sl, y0, 0), P(sl, y0, deep), P(sl, ys, deep), P(sl, ys, 0), U, cc); S.quad(P(sr, y0, 0), P(sr, y0, deep), P(sr, ys, deep), P(sr, ys, 0), Um, cc);
    S.quad(P(sl, ys, 0), P(sl, ys, deep), P(sc - b, ya, deep), P(sc - b, ya, 0), [ux * 0.5, -1, uz * 0.5], cc);
    S.quad(P(sr, ys, 0), P(sr, ys, deep), P(sc + b, ya, deep), P(sc + b, ya, 0), [-ux * 0.5, -1, -uz * 0.5], cc);
    S.quad(P(sc - b, ya, 0), P(sc - b, ya, deep), P(sc + b, ya, deep), P(sc + b, ya, 0), [0, -1, 0], cc);
  }
  S.quad(P(0, y0, 0), P(len, y0, 0), P(len, y0, gal), P(0, y0, gal), [0, 1, 0], [T.cap, T.cap, T.dark, T.dark]);
  S.quad(P(0, y0, gal), P(len, y0, gal), P(len, y1, gal), P(0, y1, gal), out, [T.dim, T.dim, T.dark, T.dark]);
  S.quad(P(0, y1, Math.max(0, deep)), P(len, y1, Math.max(0, deep)), P(len, y1, gal), P(0, y1, gal), [0, -1, 0], T.dark);
}

// a moulded band standing proud of an upright face from (ax, az) to (bx, bz): a splayed underside, a face, a weathered top
// cast: THE SHADOW LINE under it on the face below (the wall's and the bastions' courses): the sun's own shadow of the
// course's lip, as deep as the sun's height over its bearing onto the face makes it (none on a face turned from the
// sun), and under that the soft shade of a ledge that hides the sky, one and a half times its own projection deep.
// Baked, 0.05 m proud of the face: the world's shadow map does not reach the wall from far off.
const LIGHT = { sun: [0.45, 0.64, -0.62] };                                    // (toward the sun: buildCity writes the world's own here before anything is built)
function course(S, ax, az, bx, bz, out, y0, y1, proud, c = T.band, drop = 0.3, rise = 0.35, cast = false) {
  const jx = out[0] * proud, jz = out[2] * proud, dn = [out[0], -1, out[2]], up = [out[0], 1, out[2]];
  if (cast) {
    const t = out[0] * LIGHT.sun[0] + out[2] * LIGHT.sun[2], e = 0.05, ex = out[0] * e, ez = out[2] * e, top = y0 - drop;
    const sun = t > 0.05 ? Math.max(0, Math.min(3 * proud, proud * LIGHT.sun[1] / t) - drop) : 0, mid = top - sun;
    if (sun > 0.02) S.face(ax + ex, az + ez, bx + ex, bz + ez, mid, top, out, T.cast);
    S.face(ax + ex, az + ez, bx + ex, bz + ez, mid - 1.5 * proud, mid, out, T.body, sun > 0.02 ? T.shade : T.cast);
  }
  S.quad([ax, y0 - drop, az], [bx, y0 - drop, bz], [bx + jx, y0, bz + jz], [ax + jx, y0, az + jz], dn, T.soffit);
  S.face(ax + jx, az + jz, bx + jx, bz + jz, y0, y1, out, c);
  S.quad([ax + jx, y1, az + jz], [bx + jx, y1, bz + jz], [bx, y1 + rise, bz], [ax, y1 + rise, az], up, c);
}

