// THE APRON'S BRICK (the lead's ruling M4: a clean, sharp apron of the road's own brick, well laid): 5 m by 5 m, the
// road's own bond and tones (bricks a quarter of a metre long in courses an eighth wide, each course shifted half a
// brick; straw, honey and ochre, a few darker, a few paler), joints of earth; every 2.5 m a course of darker brick on edge
// THE FORECOURT before the gate (the fifth mend, P1; the lead's ruling M4 gave its plan: 41 m wide, the reveal's own
// mouth, from 27 m before the wall): THE COURT IS THE ROAD WIDENED. It is laid with THE ROAD'S OWN BRICK, the field
// part's own built sheet (handed in as opts.brick: its bond of four courses across and one lengthwise, its bricks, colours and
// wear), read by the road's own metres (across from the road's edge, along by the road's metre), so the road's courses
// run on into the court unbroken. Every fifth lengthwise course of that bond is a darker HEADER COURSE right across
// the court; along each kerb runs a BORDER COURSE: one whole period of the bond turned to run with the kerb, darker
// and damper. The brick is paler down the road's own width where the wear comes in and deeper toward the kerbs.
// A LOW KERB OF GREEN STONE either side with a squat stone URN on a pedestal at each of its ends, each carrying a low
// clipped green plant, and two round stone BOLLARDS between, and TWO BROAD SHALLOW STEPS of green stone nosings and
// brick treads up to the threshold: the first on the bastions' front line, the second midway to the reveal's mouth.
// Kerbs, urns, bollards and nosings are of the wall's stone and cast their shadows on the brick. Nothing here stands
// over 2 m (design R9): the plants' heads are at 1.96 m.
// bond: the road's bond repeats every 10/13 m along it (the field part lays 13 such periods to its sheet's 10 m);
// bay: a header course at every fifth period (3.85 m); road: the road's width, which is its sheet's width too.
const COURT = { half: 20.5, front: -27, y: 0.1, rise: 0.17, kerb: 0.55, kerbTop: 0.42, bond: 10 / 13, bay: 5, road: 5 };
function forecourt(A, S, rng, Fl) {
  const c = COURT, x1 = c.half, zf = c.front, y = c.y, zs1 = GATE.bastion.front, zs2 = (GATE.bastion.front + GATE.z0 - (GATE.orders - 1) * GATE.deep) / 2;
  const m0 = layRoad().L - GATE.ring[2], P = c.bond, bd = c.bond;         // (the road's own metre at the wall's face: its last knot is the ring's place; the border is one period of the bond broad)
  const up = [0, 1, 0], N4 = [up, up, up, up];
  // a level oblong of the road's brick by the road's own metres; turned: the bond runs with the kerb, a whole period from the border's inner edge
  const pave = (xa, xb, za, zb, yy, cs, turned = false) => {
    const uv = (x, z) => (turned ? [z + m0, Math.abs(x) - (x1 - bd)] : [x + c.road / 2, z + m0]);
    A.smooth([[xa, yy, za], [xb, yy, za], [xb, yy, zb], [xa, yy, zb]], N4, [uv(xa, za), uv(xb, za), uv(xb, zb), uv(xa, zb)], cs);
  };
  // wear: paler over the road's own width and half as much again either hand, deeper over the last road's width by each kerb (every tint keeps under the marks)
  const tone = (x) => { const t = 0.88 + rng() * 0.1 + 0.07 * Math.max(0, 1 - Math.abs(x) / (1.5 * c.road)) - 0.12 * Math.max(0, (Math.abs(x) - (x1 - c.road)) / c.road); return [t, t * (0.98 + rng() * 0.03), t * (0.95 + rng() * 0.05)]; };
  const xs = [-(x1 - bd)]; for (let k = -3.5; k <= 3.5; k++) xs.push(k * c.road); xs.push(x1 - bd);      // (the road's two edges and every road's width beyond them)
  const strips = []; let z = zf;                                           // the bays between header courses, and the header courses on the bond's own lengthwise course
  for (let p = Math.ceil((zf + m0) / P / c.bay) * c.bay; ; p += c.bay) {
    const h0 = (p + 4 / 6) * P - m0, h1 = (p + 1) * P - m0;
    if (h1 > zs1) break;
    if (h0 > z) strips.push([z, h0, 0]);
    strips.push([Math.max(z, h0), h1, 1]); z = h1;
  }
  if (z < zs1) strips.push([z, zs1, 0]);
  const dim = (t) => [t[0] * 0.5, t[1] * 0.46, t[2] * 0.42];
  let prev = xs.map(tone);
  for (const [za, zb, hd] of strips) {
    const next = hd ? prev : xs.map(tone), q = hd ? dim : (t) => t;
    for (let i = 0; i + 1 < xs.length; i++) pave(xs[i], xs[i + 1], za, zb, y, [q(prev[i]), q(prev[i + 1]), q(next[i + 1]), q(next[i])]);
    prev = next;
  }
  const dkb = [0.7, 0.63, 0.56], dkb2 = [0.52, 0.47, 0.42];
  // THE COURT'S EDGE TO THE COUNTRY IS A KERB COURSE (the seventh mend): where the road's splay comes in, a course of
  // the wall's green stone lies across the court's whole front, level with its brick and as broad as the side
  // kerbs (COURT.kerb), and falls away to the country by a batter of one in two down to the kerbs' own foot (0.4 m
  // under the level): the land meets the stone along its own line on that slope; no upright edge of brick stands
  // over the grass and no gap is left under the court.
  {
    const kz = zf - c.kerb, run = 2 * (y + 0.4);
    S.quad([-x1, y, kz], [x1, y, kz], [x1, y, zf], [-x1, y, zf], up, T.cap);
    S.quad([-x1, -0.4, kz - run], [x1, -0.4, kz - run], [x1, y, kz], [-x1, y, kz], [0, 2, -1], [T.foot, T.foot, T.cap, T.cap]);
  }
  for (const sx of [-1, 1]) {
    if (sx > 0) pave(x1 - bd, x1, zf, zs1, y, [dkb, dkb2, dkb2, dkb], true); else pave(-x1, -x1 + bd, zf, zs1, y, [dkb2, dkb, dkb, dkb2], true);
    const k0 = sx * x1, k1 = sx * (x1 + c.kerb), xa = Math.min(k0, k1), xb = Math.max(k0, k1), xm = (k0 + k1) / 2;
    S.box(xa, xb, -0.4, c.kerbTop, zf - 0.3, zs1, T.foot, '-y+z', T.cap);                                   // the low kerb of green stone
    for (const [zu, urn] of [[zf + 0.25, 1], [zf + (zs1 - zf) / 3, 0], [zf + (zs1 - zf) * 2 / 3, 0], [zs1 - 0.9, 1]]) {
      if (urn) {
        S.box(xm - 0.6, xm + 0.6, -0.4, 0.78, zu - 0.6, zu + 0.6, T.plinth, '-y', T.cap);
        S.lathe(xm, zu, [[0.3, 0.78], [0.36, 0.86], [0.2, 0.94], [0.4, 1.12], [0.58, 1.36], [0.56, 1.48], [0.5, 1.52]], 12, 0, Math.PI * 2, [T.shade, T.body, T.shade, T.body, T.body, T.cap, T.cap]);
        // a low clipped plant in the urn: a round head of dark box, lighter on top
        Fl.lathe(xm, zu, [[0.46, 1.5], [0.66, 1.62], [0.6, 1.8], [0.34, 1.92], [0.03, 1.96]], 9, 0, Math.PI * 2, [[0.03, 0.07, 0.03], [0.06, 0.13, 0.05], [0.1, 0.2, 0.07], [0.14, 0.26, 0.09], [0.15, 0.27, 0.1]]);
      } else S.lathe(xm, zu, [[0.3, c.kerbTop], [0.3, 0.95], [0.24, 1.02], [0.27, 1.1], [0.2, 1.2], [0.03, 1.24]], 10, 0, Math.PI * 2, [T.foot, T.body, T.shade, T.cap, T.cap, T.cap]);
    }
  }
  // the two steps: a nosing of green stone (its lit riser, a dark line under its lip) and a tread of the court's brick
  const cant = (zz) => GATE.bastion.in + (GATE.z0 - (GATE.orders - 1) * GATE.deep - zz);                      // (the bastions' inner cants close the steps' ends)
  [[zs1, y + c.rise], [zs2, y + 2 * c.rise]].forEach(([zz, yt], i) => {
    const xe = cant(zz) + 0.4, zt = zz + 0.42, zn = i ? GATE.z0 : zs2;
    S.face(-xe, zz - 0.07, xe, zz - 0.07, yt - c.rise + 0.045, yt, [0, 0, -1], T.cap); S.quad([-xe, yt - c.rise + 0.045, zz - 0.07], [xe, yt - c.rise + 0.045, zz - 0.07], [xe, yt - c.rise + 0.045, zz], [-xe, yt - c.rise + 0.045, zz], [0, -1, 0], T.dark);
    S.face(-xe, zz, xe, zz, yt - c.rise - 0.02, yt - c.rise + 0.045, [0, 0, -1], T.dark);
    S.quad([-xe, yt, zz - 0.07], [xe, yt, zz - 0.07], [xe, yt, zt], [-xe, yt, zt], [0, 1, 0], T.cap);
    const ta = tone(-xe), tb = tone(xe); pave(-xe, xe, zt, zn, yt, [ta, tb, tb, ta]);
  });
  pave(-x1, x1, GATE.z0, GATE.back, y + 2 * c.rise, [T.body, T.body, T.dim, T.dim]);   // the passage's floor, into the dark
  // A THRESHOLD OF THE WALL'S GREEN STONE AT THE RING'S FOOT (the lead's late point for the seventh mend: a band about
  // the ring's foot in a second stone, worn lighter down the middle): one slab across the innermost opening (GATE.half
  // less the leaves' clearance), as broad either side of the opening's line as two of the side kerbs (COURT.kerb), a
  // nosing's height (0.045 m) proud of the tread, paler over the road's own width where the wear comes in.
  {
    const yt = y + 2 * c.rise, th = 0.045, tw = 2 * c.kerb, xe = GATE.half - 0.1, xr = c.road / 2, worn = [1.05, 1.05, 1.02], za = GATE.z0 - tw, zb = GATE.z0 + tw;
    for (const [xa, xb, ca, cb] of [[-xe, -xr, T.cap, worn], [-xr, xr, worn, worn], [xr, xe, worn, T.cap]]) S.quad([xa, yt + th, za], [xb, yt + th, za], [xb, yt + th, zb], [xa, yt + th, zb], up, [ca, cb, cb, ca]);
    S.face(-xe, za, xe, za, yt, yt + th, [0, 0, -1], T.cap);
  }
}
// three smooth fields of tone in one small repeating sheet (the shader reads it at 3 m, 12 m and 60 m: no scale is flat)
async function toneField(ctx, rng) {
  const n = 256, d = new Uint8Array(n * n * 4);
  for (let ch = 0; ch < 3; ch++) {
    const L = [16, 32], lat = L.map((m) => { const a = new Float32Array(m * m); for (let i = 0; i < a.length; i++) a[i] = rng(); return a; });
    for (let y = 0; y < n; y++) for (let x = 0; x < n; x++) {
      let v = 0;
      for (let o = 0; o < 2; o++) {
        const m = L[o], fx = x / n * m, fy = y / n * m, x0 = Math.floor(fx), y0 = Math.floor(fy), tx = fx - x0, ty = fy - y0, sx = tx * tx * (3 - 2 * tx), sy = ty * ty * (3 - 2 * ty), a = lat[o];
        const v00 = a[(y0 % m) * m + (x0 % m)], v10 = a[(y0 % m) * m + ((x0 + 1) % m)], v01 = a[((y0 + 1) % m) * m + (x0 % m)], v11 = a[((y0 + 1) % m) * m + ((x0 + 1) % m)];
        v += (v00 + (v10 - v00) * sx + (v01 + (v11 - v01) * sx - v00 - (v10 - v00) * sx) * sy) * (o ? 0.35 : 0.65);
      }
      d[(y * n + x) * 4 + ch] = Math.max(0, Math.min(255, Math.round(v * 255)));
    }
    await ctx.yield();
  }
  for (let i = 3; i < d.length; i += 4) d[i] = 255;
  return { d, n };
}
