// ---- a small writer of triangles: positions, normals, uv in METRES and a colour to each corner
function makeWriter() {
  // THE LISTS ARE TYPED AND GROW BY DOUBLING (the seventh mend: the build's time): a corner is written straight into
  // the lists the meshes are made of (the same 32-bit numbers a copy at the end gave), so no list of numbers is
  // pushed to, grown and then copied whole; lists() hands out each list cut to its length.
  let cap = 6144, nv = 0, pos = new Float32Array(cap * 3), nor = new Float32Array(cap * 3), uvs = new Float32Array(cap * 2), col = new Float32Array(cap * 3), mk = new Float32Array(cap * 4);
  const more = (a, n) => { const b = new Float32Array(cap * n); b.set(a); return b; };
  const grow = () => { cap *= 2; pos = more(pos, 3); nor = more(nor, 3); uvs = more(uvs, 2); col = more(col, 3); mk = more(mk, 4); };
  const W = { count: 0, swap: null, tone: 0, lists: () => [['position', pos.slice(0, nv * 3), 3], ['normal', nor.slice(0, nv * 3), 3], ['uv', uvs.slice(0, nv * 2), 2], ['color', col.slice(0, nv * 3), 3], ['gateMark', mk.slice(0, nv * 4), 4]] }; // swap: a tint to stand for another (set while the city's masses are written); tone: the mass's own tone (0: not of the city; else 2 + t, t from -1 deep bottle green through 0 jade to 1 pale celadon), written to every corner as the mark's fourth channel: one value over a whole mass
  // THE MARK (the reader's point C-2): what KIND of thing a corner is (pale dressed stone or a gilt band; the city's
  // paler jade; a bright rib or old bronze) is written beside its tint as three channels, one to a kind, so that
  // between two unlike corners a kind only fades out: it never passes through another kind on the way (the tint
  // alone did: a stripe of jade and a line of thick glints ran along every moulding)
  const put = (p, n, u, v, c0) => {
    if (nv === cap) grow();
    const c = W.swap ? W.swap(c0) : c0, r = c[0], bronze = c === T.bronze, i3 = nv * 3, i2 = nv * 2, i4 = nv * 4;
    pos[i3] = p[0]; pos[i3 + 1] = p[1]; pos[i3 + 2] = p[2]; nor[i3] = n[0]; nor[i3 + 1] = n[1]; nor[i3 + 2] = n[2]; uvs[i2] = u; uvs[i2 + 1] = v; col[i3] = c[0]; col[i3 + 1] = c[1]; col[i3 + 2] = c[2];
    mk[i4] = r >= 1.25 ? 1 : 0; mk[i4 + 1] = r >= 1.13 && r < 1.25 ? 1 : 0; mk[i4 + 2] = (r >= 1.08 && r < 1.13) || bronze ? 1 : 0; mk[i4 + 3] = W.tone;
    nv++;
  };
  // a flat convex polygon; out is any vector on its outer side (the winding is set from it); c is one colour or one to a corner
  W.poly = (ps, out, c, uo = 0, vo = 0) => {
    const a = ps[0]; let nx = 0, ny = 0, nz = 0;
    for (let i = 1; i + 1 < ps.length; i++) {
      const b = ps[i], d = ps[i + 1], ux = b[0] - a[0], uy = b[1] - a[1], uz = b[2] - a[2], vx = d[0] - a[0], vy = d[1] - a[1], vz = d[2] - a[2];
      nx += uy * vz - uz * vy; ny += uz * vx - ux * vz; nz += ux * vy - uy * vx;
    }
    let l = Math.sqrt(nx * nx + ny * ny + nz * nz); if (l < 1e-9) return; nx /= l; ny /= l; nz /= l;
    const flip = nx * out[0] + ny * out[1] + nz * out[2] < 0; if (flip) { nx = -nx; ny = -ny; nz = -nz; }
    let tx = nz, tz = -nx, tl = Math.sqrt(tx * tx + tz * tz); if (tl < 0.05) { tx = 1; tz = 0; tl = 1; } tx /= tl; tz /= tl;      // the face's level direction
    const bx = ny * tz, by = nz * tx - nx * tz, bz = -ny * tx, n = [nx, ny, nz], per = Array.isArray(c[0]);            // and its direction up the face
    const ua = a[0] * tx + a[2] * tz + uo, va = a[0] * bx + a[1] * by + a[2] * bz + vo, ca = per ? c[0] : c;
    for (let i = 1; i + 1 < ps.length; i++) {
      const i1 = flip ? i + 1 : i, i2 = flip ? i : i + 1, p = ps[i1], q = ps[i2];
      put(a, n, ua, va, ca); put(p, n, p[0] * tx + p[2] * tz + uo, p[0] * bx + p[1] * by + p[2] * bz + vo, per ? c[i1] : c); put(q, n, q[0] * tx + q[2] * tz + uo, q[0] * bx + q[1] * by + q[2] * bz + vo, per ? c[i2] : c);
      W.count++;
    }
  };
  W.quad = (a, b, c2, d, out, c, uo, vo) => W.poly([a, b, c2, d], out, c, uo, vo);
  // an upright face from the plan point (ax, az) to (bx, bz), from y0 to y1; cb and ct colour its foot and its head
  W.face = (ax, az, bx, bz, y0, y1, out, cb, ct = cb, uo = 0) => W.poly([[ax, y0, az], [bx, y0, bz], [bx, y1, bz], [ax, y1, az]], out, [cb, cb, ct, ct], uo, 0);
  // a box, any faces left out by name ('-x', '+x', '-y', '+y', '-z', '+z')
  W.box = (x0, x1, y0, y1, z0, z1, c, skip = '', ct = c) => {
    if (!skip.includes('-z')) W.face(x0, z0, x1, z0, y0, y1, [0, 0, -1], c, ct);
    if (!skip.includes('+z')) W.face(x0, z1, x1, z1, y0, y1, [0, 0, 1], c, ct);
    if (!skip.includes('-x')) W.face(x0, z0, x0, z1, y0, y1, [-1, 0, 0], c, ct);
    if (!skip.includes('+x')) W.face(x1, z0, x1, z1, y0, y1, [1, 0, 0], c, ct);
    if (!skip.includes('+y')) W.quad([x0, y1, z0], [x1, y1, z0], [x1, y1, z1], [x0, y1, z1], [0, 1, 0], ct);
    if (!skip.includes('-y')) W.quad([x0, y0, z0], [x1, y0, z0], [x1, y0, z1], [x0, y0, z1], [0, -1, 0], c);
  };
  // a round body with smooth normals: prof is a list of [radius, y] from foot to head; a0 to a1 the bearings it covers
  // (radians, 0 = toward +x, a quarter turn = toward +z); cs is one colour or one to each ring; squash flattens it in z
  W.lathe = (cx, cz, prof, sides, a0, a1, cs, uPer = 1, squash = 1) => {
    const per = Array.isArray(cs[0]), rings = prof.length, PN = [];
    for (let j = 0; j < rings; j++) {                                    // the profile's own outward normal at each ring
      const p = prof[Math.max(0, j - 1)], q = prof[Math.min(rings - 1, j + 1)], dr = q[0] - p[0], dy = q[1] - p[1], l = Math.hypot(dr, dy) || 1;
      PN.push([dy / l, -dr / l]);
    }
    let vArc = prof[0][1]; const VA = [vArc]; for (let j = 1; j < rings; j++) { vArc += Math.hypot(prof[j][0] - prof[j - 1][0], prof[j][1] - prof[j - 1][1]); VA.push(vArc); }
    const rRef = prof.reduce((m, p) => Math.max(m, p[0]), 0) * uPer;
    for (let i = 0; i < sides; i++) {
      const b0 = a0 + (a1 - a0) * i / sides, b1 = a0 + (a1 - a0) * (i + 1) / sides, c0 = Math.cos(b0), s0 = Math.sin(b0), c1 = Math.cos(b1), s1 = Math.sin(b1);
      for (let j = 0; j + 1 < rings; j++) {
        const [ra, ya] = prof[j], [rb, yb] = prof[j + 1], na = PN[j], nb = PN[j + 1], ca = per ? cs[j] : cs, cb = per ? cs[j + 1] : cs;
        const P = (r, y, c, s) => [cx + r * c, y, cz + r * s * squash], Nn = (n, c, s) => [n[0] * c, n[1], n[0] * s];
        const p00 = P(ra, ya, c0, s0), p10 = P(ra, ya, c1, s1), p01 = P(rb, yb, c0, s0), p11 = P(rb, yb, c1, s1);
        const u0 = b0 * rRef, u1 = b1 * rRef;
        if (ra > 1e-6) { put(p00, Nn(na, c0, s0), u0, VA[j], ca); put(p11, Nn(nb, c1, s1), u1, VA[j + 1], cb); put(p10, Nn(na, c1, s1), u1, VA[j], ca); W.count++; }
        if (rb > 1e-6) { put(p00, Nn(na, c0, s0), u0, VA[j], ca); put(p01, Nn(nb, c0, s0), u0, VA[j + 1], cb); put(p11, Nn(nb, c1, s1), u1, VA[j + 1], cb); W.count++; }
      }
    }
  };
  // a quad with a normal, a uv and a colour to each corner (round work that is not a lathe)
  W.smooth = (ps, ns, uv, c) => {
    const a = ps[0], b = ps[1], d = ps[2], ux = b[0] - a[0], uy = b[1] - a[1], uz = b[2] - a[2], vx = d[0] - a[0], vy = d[1] - a[1], vz = d[2] - a[2];
    const flip = (uy * vz - uz * vy) * ns[0][0] + (uz * vx - ux * vz) * ns[0][1] + (ux * vy - uy * vx) * ns[0][2] < 0, per = Array.isArray(c[0]);
    for (const i of flip ? [0, 2, 1, 0, 3, 2] : [0, 1, 2, 0, 2, 3]) put(ps[i], ns[i], uv[i][0], uv[i][1], per ? c[i] : c);
    W.count += 2;
  };
  return W;
}
