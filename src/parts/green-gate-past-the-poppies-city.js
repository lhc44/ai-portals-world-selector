// BAUM'S GEMS IN OUR PATTERN (design 14, R10): an emerald STUD of 0.1 to 0.2 m, rough-cut (six faces to a point off its
// middle), set in a copper bezel that is a small lozenge boss; the studs stand in BANDS, so that from the road they read
// as green-gold bands. c: the seat on the face; ex, ey: the face's own directions; en: its normal
function stud(Kw, G, c, ex, ey, en, a, h, p, tint, size, rng) {
  const P = (u, v, d) => [c[0] + ex[0] * u + ey[0] * v + en[0] * d, c[1] + ex[1] * u + ey[1] * v + en[1] * d, c[2] + ex[2] * u + ey[2] * v + en[2] * d];
  const E = P(a, 0, 0), N = P(0, h, 0), Wt = P(-a, 0, 0), So = P(0, -h, 0), top = P(0, 0, p), lit = mix3(tint, [1.25, 1.2, 1.0], 0.4);
  const O = (u, v) => [ex[0] * u + ey[0] * v + en[0] * 2, ex[1] * u + ey[1] * v + en[1] * 2, ex[2] * u + ey[2] * v + en[2] * 2];
  Kw.poly([E, N, top], O(1, 1), [tint, tint, lit]); Kw.poly([N, Wt, top], O(-1, 1), [tint, tint, lit]);
  Kw.poly([Wt, So, top], O(-1, -1), [tint, tint, lit]); Kw.poly([So, E, top], O(1, -1), [tint, tint, lit]);
  const r = size / 2, tone = 0.75 + rng() * 0.5, tg = [0.7 * tone, tone, (0.74 + rng() * 0.22) * tone], turn = rng() * 6.283, tip = P((rng() - 0.5) * r * 0.5, (rng() - 0.5) * r * 0.5, p * 0.85 + size * (0.45 + rng() * 0.2)), rim = [];
  for (let i = 0; i < 6; i++) { const q = turn + i * 1.0472, rr = r * (0.8 + rng() * 0.4); rim.push(P(Math.cos(q) * rr, Math.sin(q) * rr, p * 0.8)); }
  for (let i = 0; i < 6; i++) { const j = (i + 1) % 6, k = 0.8 + rng() * 0.4; G.poly([rim[i], rim[j], tip], [(rim[i][0] + rim[j][0]) / 2 - c[0] + en[0] * r, (rim[i][1] + rim[j][1]) / 2 - c[1] + en[1] * r, (rim[i][2] + rim[j][2]) / 2 - c[2] + en[2] * r], [tg[0] * k, tg[1] * k, tg[2] * k]); }
}
// a BAND of studs along the straight run from a to b on a face (o: its normal): a raised copper fillet 0.56 m wide and a
// stud at every 0.8 m of it
const GOLD = [1.34, 1.14, 0.62], GOLD_DIM = [1.27, 1.1, 0.66];      // (over 1.25: on copper the mark of a band of studs, where the glints stand thick)
function studBand(Kw, G, a, b, o, rng, clip) {
  const dx = b[0] - a[0], dy = b[1] - a[1], dz = b[2] - a[2], l = Math.hypot(dx, dy, dz); if (l < 0.5) return;
  const ex = [dx / l, dy / l, dz / l], ey = [o[1] * ex[2] - o[2] * ex[1], o[2] * ex[0] - o[0] * ex[2], o[0] * ex[1] - o[1] * ex[0]], w = 0.28, d = 0.05;
  const Q = (t, v) => [a[0] + ex[0] * t + ey[0] * v + o[0] * d, a[1] + ex[1] * t + ey[1] * v + o[1] * d, a[2] + ex[2] * t + ey[2] * v + o[2] * d];
  Kw.quad(Q(0, -w), Q(l, -w), Q(l, w), Q(0, w), o, GOLD_DIM);
  const n = Math.max(1, Math.round(l / 0.8));
  for (let j = 0; j < n; j++) { const c = Q((j + 0.5) * l / n, 0); if (clip && !clip(c)) continue; stud(Kw, G, c, ex, ey, o, 0.3, 0.2, 0.09, GOLD, 0.1 + rng() * 0.1, rng); }
}
// THE GATE'S COURSED STONE (the fifth mend, P2): real rusticated ashlar. h: a course's height, the inner opening's
// spring (14 m) in 23 courses, 0.61 m; every coursed face of the gate keeps its bed joints on the multiples of it, so
// the joints run level from the towers' lower stage into the reveal. gap, deep: a bed joint is cut back as a V 0.1 m
// broad and 0.08 m deep, dark within. pillow: a block's head and foot turn so far up and down from the face (a
// cushioned face), so every course takes the side light on its own edges and its own share of the sheen: no
// highlight runs across a whole face. tone: four firings of the one stone, course after course.
const COURSE = { h: GATE.spring / 23, gap: 0.05, deep: 0.08, pillow: 0.16, tone: [1, 0.93, 0.97, 0.9] };
// one course on a flat face: a0, a1 its foot (inner end, outer end), b1, b0 its head; out: a vector on the face's
// outer side; k: its number (which of the built sheet's sixteen courses it shows, and its own slight turn along the
// bed, by the golden section: no chance); ci, co: the baked tints of its two ends; org: where the bed's metres start
function stoneCourse(S, a0, a1, b1, b0, out, k, ci, co, org) {
  const sub = (p, q) => [p[0] - q[0], p[1] - q[1], p[2] - q[2]], unit = (v) => { const l = Math.hypot(v[0], v[1], v[2]) || 1; return [v[0] / l, v[1] / l, v[2] / l]; };
  const eu = unit(sub(a1, a0)), e0 = unit(sub(b0, a0)), e1 = unit(sub(b1, a1)), d1 = sub(b1, a0), d2 = sub(b0, a1);
  let n = unit([d1[1] * d2[2] - d1[2] * d2[1], d1[2] * d2[0] - d1[0] * d2[2], d1[0] * d2[1] - d1[1] * d2[0]]);
  if (n[0] * out[0] + n[1] * out[1] + n[2] * out[2] < 0) n = [-n[0], -n[1], -n[2]];
  const g = COURSE.gap, dp = COURSE.deep, pl = COURSE.pillow, yaw = ((k * 0.618) % 1 - 0.5) * 0.08, tk = COURSE.tone[k % 4];
  const mv = (p, e, s, dn) => [p[0] + e[0] * s - n[0] * dn, p[1] + e[1] * s - n[1] * dn, p[2] + e[2] * s - n[2] * dn];
  const A0 = mv(a0, e0, g, 0), A1 = mv(a1, e1, g, 0), B0 = mv(b0, e0, -g, 0), B1 = mv(b1, e1, -g, 0);
  const lo = [n[0] - e0[0] * pl + eu[0] * yaw, n[1] - e0[1] * pl + eu[1] * yaw, n[2] - e0[2] * pl + eu[2] * yaw], hi = [n[0] + e0[0] * pl + eu[0] * yaw, n[1] + e0[1] * pl + eu[1] * yaw, n[2] + e0[2] * pl + eu[2] * yaw];
  const U = (p) => (p[0] - org[0]) * eu[0] + (p[1] - org[1]) * eu[1] + (p[2] - org[2]) * eu[2], v0 = (k % 16) * 0.9 + 0.07, v1 = (k % 16) * 0.9 + 0.83;      // (the sheet's own courses are 0.9 m: one to a course here, its fine joint left in the cut)
  const ti = [ci[0] * tk, ci[1] * tk, ci[2] * tk], to = [co[0] * tk, co[1] * tk, co[2] * tk];
  S.smooth([A0, A1, B1, B0], [lo, lo, hi, hi], [[U(A0), v0], [U(A1), v0], [U(B1), v1], [U(B0), v1]], [ti, to, to, ti]);
  S.quad(mv(a0, e0, 0, dp), mv(a1, e1, 0, dp), A1, A0, n, [T.dark, T.dark, to, ti]);
  S.quad(B0, B1, mv(b1, e1, 0, dp), mv(b0, e0, 0, dp), n, [ti, to, T.dark, T.dark]);
}
// a carved roll (a round bead of the wall's own green stone, never pale, never gilt) along an arris from a to b
function roll(S, a, b, r, c = T.cap, sides = 6) {
  const t = [b[0] - a[0], b[1] - a[1], b[2] - a[2]], l = Math.hypot(t[0], t[1], t[2]); if (l < 0.01) return;
  t[0] /= l; t[1] /= l; t[2] /= l;
  const h = Math.abs(t[1]) < 0.9 ? [0, 1, 0] : [1, 0, 0], c1 = [t[1] * h[2] - t[2] * h[1], t[2] * h[0] - t[0] * h[2], t[0] * h[1] - t[1] * h[0]], l1 = Math.hypot(c1[0], c1[1], c1[2]);
  const e1 = [c1[0] / l1, c1[1] / l1, c1[2] / l1], e2 = [t[1] * e1[2] - t[2] * e1[1], t[2] * e1[0] - t[0] * e1[2], t[0] * e1[1] - t[1] * e1[0]];
  for (let i = 0; i < sides; i++) {
    const p0 = i / sides * Math.PI * 2, p1 = (i + 1) / sides * Math.PI * 2, N = (p) => [e1[0] * Math.cos(p) + e2[0] * Math.sin(p), e1[1] * Math.cos(p) + e2[1] * Math.sin(p), e1[2] * Math.cos(p) + e2[2] * Math.sin(p)];
    const n0 = N(p0), n1 = N(p1), P = (q, n) => [q[0] + n[0] * r, q[1] + n[1] * r, q[2] + n[2] * r];
    S.smooth([P(a, n0), P(b, n0), P(b, n1), P(a, n1)], [n0, n0, n1, n1], [[0, p0 * r], [l, p0 * r], [l, p1 * r], [0, p1 * r]], c);
  }
}
// the gatehouse between the bastions: one deep plain splayed reveal (3 m wider either hand for every 3 m outward, so
