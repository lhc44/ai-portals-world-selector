// a copper barrel roof along x with ribs standing on it: a segment of a circle from eave to eave
function barrel(K, x0, x1, zc, half, yEave, yRidge, ribEvery) {
  const h = yRidge - yEave, R = (half * half + h * h) / (2 * h), phi = Math.asin(half / R), cy = yRidge - R, n = 28;
  const strip = (xa, xb, rr, cs, nn) => {
    for (let i = 0; i < nn; i++) {
      const a0 = -phi + 2 * phi * i / nn, a1 = -phi + 2 * phi * (i + 1) / nn, s0 = Math.sin(a0), c0 = Math.cos(a0), s1 = Math.sin(a1), c1 = Math.cos(a1);
      K.smooth([[xa, cy + rr * c0, zc + rr * s0], [xb, cy + rr * c0, zc + rr * s0], [xb, cy + rr * c1, zc + rr * s1], [xa, cy + rr * c1, zc + rr * s1]],
        [[0, c0, s0], [0, c0, s0], [0, c1, s1], [0, c1, s1]], [[xa, a0 * R], [xb, a0 * R], [xb, a1 * R], [xa, a1 * R]], cs);
    }
  };
  strip(x0, x1, R, T.roof, n);
  const nr = Math.max(2, Math.round((x1 - x0) / ribEvery));
  for (let k = 0; k <= nr; k++) {
    const xc = x0 + (x1 - x0) * k / nr, xa = Math.max(x0, xc - 0.55), xb = Math.min(x1, xc + 0.55), rr = R + 0.7, nn = 18;
    strip(xa, xb, rr, T.rib, nn);
    for (let i = 0; i < nn; i++) {
      const a0 = -phi + 2 * phi * i / nn, a1 = -phi + 2 * phi * (i + 1) / nn, P = (x, a, q) => [x, cy + q * Math.cos(a), zc + q * Math.sin(a)];
      K.quad(P(xa, a0, R), P(xa, a1, R), P(xa, a1, rr), P(xa, a0, rr), [-1, 0, 0], T.roofShade); K.quad(P(xb, a0, R), P(xb, a1, R), P(xb, a1, rr), P(xb, a0, rr), [1, 0, 0], T.roofShade);
    }
  }
  return { R, phi, cy };
}
// a low dome: a cap of a sphere over a round eave, rising by `rise`; an optional flat cap of radius `flat` at its crown
function domeProfile(rEave, yEave, rise, rings, flat = 0) {
  const R = (rEave * rEave + rise * rise) / (2 * rise), cy = yEave + rise - R, th0 = Math.asin(Math.min(1, rEave / R)), th1 = flat > 0 ? Math.asin(flat / R) : 0, out = [];
  for (let j = 0; j <= rings; j++) { const th = th0 + (th1 - th0) * j / rings; out.push([R * Math.sin(th), cy + R * Math.cos(th)]); }
  return out;
}
// a storey of openings along a face, with plain stone for `margin` metres at each end (a solid corner)
function storey(S, ax, az, bx, bz, out, margin, y0, ys, ya, y1, bay, open, deep, gal) {
  const l = Math.hypot(bx - ax, bz - az), ux = (bx - ax) / l, uz = (bz - az) / l, cx = ax + ux * margin, cz = az + uz * margin, dx = bx - ux * margin, dz = bz - uz * margin;
  S.face(ax, az, cx, cz, y0, y1, out, T.body); S.face(dx, dz, bx, bz, y0, y1, out, T.body);
  arcade(S, cx, cz, dx, dz, out, y0, ys, ya, y1, bay, open, deep, gal);
}
// a ring of openings round a drum: one to each chord
function ring(S, cx, cz, r, n, y0, ys, ya, y1, open, deep, gal, a0 = 0, a1 = Math.PI * 2) {
  for (let k = 0; k < n; k++) {
    const b0 = a0 + (a1 - a0) * k / n, b1 = a0 + (a1 - a0) * (k + 1) / n, bm = (b0 + b1) / 2;
    arcade(S, cx + r * Math.cos(b0), cz + r * Math.sin(b0), cx + r * Math.cos(b1), cz + r * Math.sin(b1), [Math.cos(bm), 0, Math.sin(bm)], y0, ys, ya, y1, 999, open, deep, gal);
  }
}
// ribs standing on a dome: narrow gores of the same profile, a little proud
function ribs(Wr, cx, cz, prof, count, width, proud, c) {
  const pr = prof.map((p) => [p[0] + proud * 0.7, p[1] + proud * 0.7]), rMax = prof[0][0];
  for (let k = 0; k < count; k++) { const a = (k + 0.5) / count * Math.PI * 2, da = width / 2 / rMax; Wr.lathe(cx, cz, pr, 1, a - da, a + da, c); }
}
// A STEPPED MASS (H2): stages [half x, half z, foot, head], each SET BACK from the one below, pale corner piers to every
// stage, a cornice at every set-back; the lower stages carry three ordered bays of tall recessed lights (dark glass in
// a pale surround) with broad blank wall between; the top stage is a LOGGIA of great openings under the crowning
// cornice and a copper cap of our own. THE BROAD TOWER is the greatest of them (three stages, set back 4 m each)
function steppedMass(S, K, cx, cz, ST, yTop) {
  ST.forEach(([hx, hz, y0, y1], i) => {
    const x0 = cx - hx, x1 = cx + hx, z0 = cz - hz, z1 = cz + hz, last = i === ST.length - 1, yc = y1 - (last ? 4.2 : 3);
    for (const [ax, az, bx, bz, o, rich] of [[x0, z0, x1, z0, [0, 0, -1], 1], [x1, z0, x1, z1, [1, 0, 0], 1], [x0, z0, x0, z1, [-1, 0, 0], 1], [x0, z1, x1, z1, [0, 0, 1], 0]]) {
      if (!rich) { S.face(ax, az, bx, bz, y0, y1, o, T.shade); continue; }
      const len = Math.hypot(bx - ax, bz - az), ux = (bx - ax) / len, uz = (bz - az) / len, mx = (ax + bx) / 2, mz = (az + bz) / 2;
      if (!last) {
        S.face(ax, az, bx, bz, y0, yc, o, T.body);
        const ya = y0 + (i ? 6 : 9), yb = yc - 5, two = yb - ya > 34, h = two ? (yb - ya - 6) / 2 : yb - ya;
        for (const k of [-1, 0, 1]) {
          const px = mx + ux * k * len * 0.2, pz = mz + uz * k * len * 0.2;
          slit(S, px, pz, o, ya, 4.3, h, 1.0, 0.6, T.glass); if (two) slit(S, px, pz, o, ya + h + 6, 4.3, h, 1.0, 0.6, T.glass);
        }
        course(S, ax, az, bx, bz, o, ya - 3.6, ya - 2.5, 0.6);                                               // a sill course under the lights
      } else {
        const sill = y0 + 3.6, head = yc - 2.2;
        S.face(ax, az, bx, bz, y0, sill, o, T.body);
        storey(S, ax, az, bx, bz, o, 4.5, sill, head - 5, head - 1.4, head, 7, 4.7, 2.6, Math.min(7, hz * 0.6));
        S.face(ax, az, bx, bz, head, yc, o, T.body);
      }
      course(S, ax, az, bx, bz, o, yc, y1, last ? 1.9 : 1.3, T.band, 0.6, 0);                              // the cornice at the stage's head
    }
    S.quad([x0, y1, z0], [x1, y1, z0], [x1, y1, z1], [x0, y1, z1], [0, 1, 0], T.cap);                       // the set-back's weathered top
    const pw = Math.max(1.7, Math.min(hx, hz) * 0.11 - i * 0.4);
    for (const [px, pz] of [[x0, z0], [x1, z0], [x0, z1], [x1, z1]]) S.box(px - pw, px + pw, y0, yc, pz - pw, pz + pw, T.band, '-y+y');      // corner piers of pale stone
  });
  const [hx, hz, , yE] = ST[ST.length - 1], tp = [[cx - hx, cz - hz], [cx + hx, cz - hz], [cx + hx, cz + hz], [cx - hx, cz + hz]], ins = Math.min(5, Math.min(hx, hz) * 0.23), rh = Math.max(hx, hz) - Math.min(hx, hz) + Math.min(hx, hz) * 0.32;
  capRoof(K, tp, yE + 0.25, ins, ins * 0.6, ins);
  hipRoof(K, offsetPlan(tp, -ins), yE + 0.6 + ins, hx >= hz ? [cx - rh, cz] : [cx, cz - rh], hx >= hz ? [cx + rh, cz] : [cx, cz + rh], yTop, 0.2);
}
