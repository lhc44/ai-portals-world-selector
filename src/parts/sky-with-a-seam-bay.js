// the paint's materials: the things, their image in the sea (MIRROR: drawn after the sea, over it), their shades
function bayMaterials(look, sky, ocean, boats, wind) {
  const P = PAINTS[look], LL = LAMP_LIGHT[look], ou = ocean.uniforms, bd = dirOf(boats), fog = () => THREE.UniformsUtils.clone(THREE.UniformsLib.fog);
  // (uPix here is only its first value: update() writes it at every draw from the true drawing buffer's height)
  const U = {
    ...fog(), uTime: ou.uTime, uCentre: ou.uCentre, uLamp: sky.shadow.uLamp, uBoat: sky.shadow.uBoat,
    uClock: { value: 0 }, uPix: { value: 2 / 720 }, uShipPh: { value: 0 }, uRip: { value: new THREE.Vector2() }, uPlane: { value: 0.24 }, uRay: { value: new THREE.Vector4(0, 0, 0, 0) }, uProj: { value: new THREE.Vector2(-1, -0.6) },
    uBoatDir: { value: new THREE.Vector3(bd.x, 0, bd.z) }, uWind: { value: new THREE.Vector3(wind[0], 0, wind[1]) },
    uLampCol: { value: new THREE.Color().setRGB(LL.color[0], LL.color[1], LL.color[2]) }, uFillCol: { value: new THREE.Color(P.fill) }, uKey: { value: LL.key }, uFill: { value: LL.fill },
    uSkyCol: { value: new THREE.Color(P.mid) }, uHazeCol: { value: new THREE.Color(P.haze) }, uBounce: { value: new THREE.Color(look ? '#3a2c22' : '#2e2e2a') },
    uGlowCol: { value: new THREE.Color(look ? '#ffd9a0' : '#fff2d2') },
  };
  U.uCoat = { value: 0 };
  const base = { uniforms: U, vertexShader: BAY_VERT, fragmentShader: BAY_FRAG, fog: true, side: THREE.DoubleSide };
  const paint = new THREE.ShaderMaterial(base);
  const image = new THREE.ShaderMaterial({ ...base, defines: { MIRROR: 1 }, transparent: true, premultipliedAlpha: true, depthWrite: true });
  // THE THIN COAT (the paint's own remark at its end): the same paint and the same uniforms by reference, its coat
  // told as 1; blended and writing no depth, for the thin members where they are drawn wider than they are, and
  // the same once more for their image
  // A ROUND MEMBER'S COVER IS LAID ONCE: a coat that writes no depth would lay both halves of a round member on
  // the same pixels, and its cover twice. So this coat draws the half that faces the eye alone. Every thin member
  // is wound one way, its triangles' own winding toward its axis (the proof counts them on every seed), so the
  // half that faces the eye is the one whose triangles show their backs: BackSide; and FrontSide for the image,
  // whose winding the mirror turns. (Every material here is drawn in ONE pass: a ShaderMaterial of this three is
  // forceSinglePass as it is made, also where it is see-through and two-sided, as the images are.)
  const UT = { ...U, uCoat: { value: 1 } };
  const thin = new THREE.ShaderMaterial({ ...base, uniforms: UT, side: THREE.BackSide, transparent: true, depthWrite: false });
  const thinImage = new THREE.ShaderMaterial({ ...base, uniforms: UT, side: THREE.FrontSide, defines: { MIRROR: 1 }, transparent: true, premultipliedAlpha: true, depthWrite: false });
  // the shades' layer: THE SEA'S OWN LIGHT, by reference (its deep, its lamp's and its dome's colours and parts), so
  // that what the layer takes off is what the sea gave; it is laid by taking away (the frame keeps what is there,
  // less what the layer gives), never by a dark coat
  const SU = { ...fog(), uTime: ou.uTime, uCentre: ou.uCentre, uLamp: sky.shadow.uLamp, uBoat: sky.shadow.uBoat, uClock: U.uClock, uRip: U.uRip,
    uShadeMap: { value: null }, uShadeBox: { value: new THREE.Vector3() }, uDeep: ou.uDeep || { value: new THREE.Color(0) },
    uLampCol: ou.uLampCol || U.uLampCol, uKey: ou.uKey || U.uKey, uFillCol: ou.uFillCol || U.uFillCol, uFill: ou.uFill || U.uFill };
  const shade = new THREE.ShaderMaterial({ uniforms: SU, vertexShader: SHADE_VERT, fragmentShader: SHADE_FRAG, fog: true, transparent: true, depthWrite: false, side: THREE.DoubleSide,
    polygonOffset: true, polygonOffsetFactor: -2, polygonOffsetUnits: -2, blending: THREE.CustomBlending, blendEquation: THREE.ReverseSubtractEquation, blendSrc: THREE.OneFactor, blendDst: THREE.OneFactor,
    blendEquationAlpha: THREE.AddEquation, blendSrcAlpha: THREE.ZeroFactor, blendDstAlpha: THREE.OneFactor });
  // as an image is drawn: the pixel's ray in the view's own axes, from the view's matrix and the drawn rectangle
  const vp = new THREE.Vector4();
  const aim = (renderer, scene, camera) => { const e = camera.projectionMatrix.elements; renderer.getCurrentViewport(vp);
    U.uRay.value.set(2 / (vp.z * e[0]), 2 / (vp.w * e[5]), (e[8] - 1 - 2 * vp.x / vp.z) / e[0], (e[9] - 1 - 2 * vp.y / vp.w) / e[5]); U.uProj.value.set(e[10], e[14]); image.uniformsNeedUpdate = thinImage.uniformsNeedUpdate = true; };
  return { U, SU, paint, image, thin, thinImage, shade, aim };
}
// THE IMAGE'S OWN ORDER OF DRAWING (as the town's): an image is laid over the water in one coat, so its triangles
// are put in order nearest the flown line first, a trim before its wall (what is drawn behind a drawn thing fails
// the depth test). P, M: the chunk's places and paint (BayPaint.rows); line: the flown line, a place every 5 m.
// The order is that of their metres, triangles of one measure in their own order (what a sort that keeps the order
// of equals gives): the triangles are dealt by their metres into as many bins as there are of them, each bin's in
// their own order, and then every triangle is moved back past those that measure more. (A crowded bin: the plain
// sort, which gives the same order.) Every round of it is a short one, a stretch of BAY.order.stretch triangles,
// asked many times: see THE BUILD'S PACE at makeBay.
function imageOrder(P, M, line) {
  const n = P.length / 9, W = BAY.order.stretch, key = new Float64Array(n), near = new Int32Array(line.length / 2), span = new Float64Array([Infinity, -Infinity]);
  const start = new Uint32Array(n + 1), order = new Uint32Array(n), index = new Uint32Array(n * 3); let most = 0;
  for (let t = 0; t < n; t += W) orderKeys(P, M, line, key, near, span, t, Math.min(t + W, n));
  const k0 = span[0], scale = span[1] > k0 ? (n - 1) / (span[1] - k0) : 0;
  for (let t = 0; t < n; t += W) orderBins(key, start, k0, scale, t, Math.min(t + W, n));
  for (let b = 0; b < n; b += W) most = Math.max(most, orderStarts(start, b, Math.min(b + W, n)));
  for (let t = 0; t < n; t += W) orderDeal(key, start, order, k0, scale, t, Math.min(t + W, n));
  if (most > BAY.order.crowd) order.set(Array.from(order).sort((p, q) => key[p] - key[q])); else for (let i = 0; i < n; i += W) orderRight(key, order, i, Math.min(i + W, n));
  for (let i = 0; i < n; i += W) orderIndex(order, index, i, Math.min(i + W, n));
  return index;
}
// the metres of the triangles t0 to t1 from the flown line (the least over the line's places), less the trim;
// span: the least and the most of all the metres so far.
// (Asked of those places alone that can be the nearest to anything in the stretch's own box: the same least.)
function orderKeys(P, M, line, key, near, span, t0, t1) {
  let x0 = Infinity, x1 = -Infinity, z0 = Infinity, z1 = -Infinity, best = Infinity, m = 0, k0 = span[0], k1 = span[1];
  for (let v = t0 * 9; v < t1 * 9; v += 3) { const x = P[v], z = P[v + 2]; if (x < x0) x0 = x; if (x > x1) x1 = x; if (z < z0) z0 = z; if (z > z1) z1 = z; }
  const cx = (x0 + x1) / 2, cz = (z0 + z1) / 2, r = Math.hypot(x1 - x0, z1 - z0) / 2;
  for (let i = 0; i < line.length; i += 2) { const dx = cx - line[i], dz = cz - line[i + 1], d = dx * dx + dz * dz; if (d < best) best = d; }
  const reach = Math.sqrt(best) + 2 * r + 1e-6;
  for (let i = 0; i < line.length; i += 2) { const dx = cx - line[i], dz = cz - line[i + 1]; if (dx * dx + dz * dz <= reach * reach) near[m++] = i; }
  for (let t = t0; t < t1; t++) { const v = t * 9, x = (P[v] + P[v + 3] + P[v + 6]) / 3, z = (P[v + 2] + P[v + 5] + P[v + 8]) / 3; let b = Infinity;
    for (let j = 0; j < m; j++) { const i = near[j], dx = x - line[i], dz = z - line[i + 1], d = dx * dx + dz * dz; if (d < b) b = d; }
    const k = Math.sqrt(b) - 0.08 * Math.floor((M[t * 12] + 0.5) / 16); key[t] = k; if (k < k0) k0 = k; if (k > k1) k1 = k; }
  span[0] = k0; span[1] = k1;
}
// the bins counted (a triangle's bin: its metres over the least, by the scale; start[bin + 1] takes the count)
function orderBins(key, start, k0, scale, t0, t1) {
  for (let t = t0; t < t1; t++) start[(((key[t] - k0) * scale) | 0) + 1]++;
}
// the counts of the bins b0 to b1 made into the places their triangles begin at; gives the fullest bin's count
function orderStarts(start, b0, b1) {
  let most = 0; for (let b = b0; b < b1; b++) { const c = start[b + 1]; if (c > most) most = c; start[b + 1] = c + start[b]; }
  return most;
}
// the triangles t0 to t1 dealt to their bins, each bin's in their own order
function orderDeal(key, start, order, k0, scale, t0, t1) {
  for (let t = t0; t < t1; t++) order[start[((key[t] - k0) * scale) | 0]++] = t;
}
// the places i0 to i1 of the order put right: each triangle moved back past those that measure more
function orderRight(key, order, i0, i1) {
  for (let i = i0 > 1 ? i0 : 1; i < i1; i++) { const t = order[i], k = key[t]; let j = i - 1; while (j >= 0 && key[order[j]] > k) { order[j + 1] = order[j]; j--; } order[j + 1] = t; }
}
// the corners of the triangles in that order
function orderIndex(a, index, t0, t1) {
  for (let i = t0; i < t1; i++) { const v = a[i] * 3; index[i * 3] = v; index[i * 3 + 1] = v + 1; index[i * 3 + 2] = v + 2; }
}
// A PIECE'S BOUNDS: the middle of its box and the farthest of its corners from that (the very numbers the
// renderer's own reckoning of a sphere gives), and so many metres more (pos: its places, three numbers each)
function boundsOf(pos, more) {
  let x0 = Infinity, y0 = Infinity, z0 = Infinity, x1 = -Infinity, y1 = -Infinity, z1 = -Infinity, r2 = 0;
  for (let i = 0; i < pos.length; i += 3) { const x = pos[i], y = pos[i + 1], z = pos[i + 2]; if (x < x0) x0 = x; if (x > x1) x1 = x; if (y < y0) y0 = y; if (y > y1) y1 = y; if (z < z0) z0 = z; if (z > z1) z1 = z; }
  const cx = (x0 + x1) * 0.5, cy = (y0 + y1) * 0.5, cz = (z0 + z1) * 0.5;
  for (let i = 0; i < pos.length; i += 3) { const dx = cx - pos[i], dy = cy - pos[i + 1], dz = cz - pos[i + 2], d = dx * dx + dy * dy + dz * dz; if (d > r2) r2 = d; }
  return new THREE.Sphere(new THREE.Vector3(cx, cy, cz), Math.sqrt(r2) + more);
}
// THE THIN COAT'S ROWS. A thin member's triangles are those whose corners carry an axis (a round member's every
// corner carries one, so the first tells it). thinRoom: rows with room for so many triangles (made anew, twice
// as long, if the bay's thin members ever outgrow them: old's are kept); thinRows: the thin triangles of a
// piece's rows R copied whole after the T.n that the coat's rows T hold, and the rows handed back. (They come
// in runs, a member's triangles after one another, and a run is copied at one stroke.)
function thinRoom(tris, old) {
  const T = { n: old ? old.n : 0, tris, P: new Float32Array(tris * 9), N: new Float32Array(tris * 9), C: new Float32Array(tris * 9), M: new Float32Array(tris * 12), A: new Float32Array(tris * 12), V: new Float32Array(tris * 12) };
  if (old) for (const k of ['P', 'N', 'C', 'M', 'A', 'V']) T[k].set(old[k]);
  return T;
}
function thinRows(R, T) {
  const A = R.A, nt = A.length / 12;
  for (let t = 0; t < nt; t++) { if (!(A[t * 12 + 3] > 0)) continue;
    let e = t + 1; while (e < nt && A[e * 12 + 3] > 0) e++;
    if (T.n + e - t > T.tris) T = thinRoom(Math.max(T.tris * 2, T.n + e - t), T);
    const o = T.n * 9, q = T.n * 12;
    T.P.set(R.P.subarray(t * 9, e * 9), o); T.N.set(R.N.subarray(t * 9, e * 9), o); T.C.set(R.C.subarray(t * 9, e * 9), o);
    T.M.set(R.M.subarray(t * 12, e * 12), q); T.A.set(A.subarray(t * 12, e * 12), q); T.V.set(R.V.subarray(t * 12, e * 12), q);
    T.n += e - t; t = e; }
  return T;
}
