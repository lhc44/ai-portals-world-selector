// THE LAYER THAT LAYS IT: cells of the water's own face (they ride its swell), drawn straight after the sea and
// before every image laid on it. A fragment TAKES OFF what the sea's own paint gave the body there: of the lamp's
// part (the sea's uLampCol * uKey * SEA_BODY.key) the share the map holds, less where our boat's own shade has
// taken it already (the hero's law); of the dome's part (uFillCol * uFill) the foot's share; both through the tank's
// own deep (uDeep) and thinned by the mirror's own law (looked along, the water is all mirror: SEA_BODY.straight).
// WHAT THIS LAYER READS OF THE EYE, all of it to draw: that bearing on the water's face; the pixel's footprint, by
// which the ripples' shift, the swell's slope and our boat's shade are filtered; the swell eased by the eye's
// place as the sea's sheet eases it (uCentre: the layer's cells ride the sheet and take its facing); and the
// scene's haze. The map is read at the place the ripples shift (BAY.shade.broken), so every edge is broken by the
// water's unrest; where a pixel holds many ripples the shift is none (its own mean: it goes as often one way as
// the other).
const SHADE_VERT = /* glsl */`
varying vec3 vW;
${GLSL_SEA}
#include <fog_pars_vertex>
void main(){
  vec3 wp = vec3(position.x, .04, position.z) + seaWave(position.xz); vW = wp;
  vec4 mvPosition = viewMatrix * vec4(wp, 1.); gl_Position = projectionMatrix * mvPosition;
  #include <fog_vertex>
}`;
const SHADE_FRAG = /* glsl */`
${GLSL_SHADOW}
uniform sampler2D uShadeMap; uniform vec3 uShadeBox, uDeep, uLampCol, uFillCol; uniform float uKey, uFill, uClock, uTime; uniform vec2 uRip, uCentre;
varying vec3 vW;
#include <fog_pars_fragment>
float hash1(vec2 p){ vec3 p3 = fract(vec3(p.xyx) * .1031); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.x + p3.y) * p3.z); }   // (the kit's own hash12, of src/kit/fx.js: no sine in it)
float vnoise(vec2 p){ vec2 i = floor(p), f = fract(p); f = f * f * (3. - 2. * f);
  return mix(mix(hash1(i), hash1(i + vec2(1., 0.)), f.x), mix(hash1(i + vec2(0., 1.)), hash1(i + vec2(1., 1.)), f.x), f.y); }
// the bay's own ripples (the field its images are broken by)
float rip(vec2 p){ return vnoise(p * vec2(.55, .55) + uClock * vec2(.1, .16) + uRip.xy) * .55 + vnoise(p * 1.9 - uClock * vec2(.27, .12) + uRip.yx) * .45; }
void main(){
  vec2 xz = vW.xz; float fw = max(length(fwidth(xz)), 1e-3);
  vec2 rise = vec2(rip(xz + vec2(.3, 0.)) - rip(xz - vec2(.3, 0.)), rip(xz + vec2(0., .3)) - rip(xz - vec2(0., .3))) * (1. - smoothstep(1.2, 6., fw));
  vec2 q = xz + rise * ${fl(BAY.shade.broken)};
  vec2 m = texture2D(uShadeMap, (q - uShadeBox.xy) * uShadeBox.z).rg;
  // how much of the body the eye has there (the sea's own law): the water's facing is the swell's own slope, as
  // the sea's paint takes it (filtered by the pixel's footprint); the mirror takes the rest
  float sk = ${fl(SW.k)} * dot(xz, vec2(${fl(SW.x)}, ${fl(SW.z)})), sl = ${fl(SW.a * SW.k)} * cos(sk - ${fl(SW.w)} * uTime) * (1. - smoothstep(150., 360., length(xz - uCentre))) * (1. - smoothstep(.9, 2.6, fwidth(sk)));
  vec3 N = normalize(vec3(-sl * ${fl(SW.x)}, 1., -sl * ${fl(SW.z)})), V = normalize(cameraPosition - vW);
  float cv = clamp(dot(N, V), 0., 1.), fr = ${fl(SEA_BODY.straight)} + ${fl(1 - SEA_BODY.straight)} * pow(max(1. - cv, 1e-4), 3.);
  float ours = boatShadeOn(vec3(q.x, 0., q.y), vec3(0., 1., 0.), min(fw, 2.));
  vec3 take = uDeep * (uLampCol * uKey * ${fl(SEA_BODY.key)} * m.r * (1. - ours) + uFillCol * uFill * m.g) * (1. - fr);
  take *= 1. - smoothstep(${fl(SHELL.R - 4)}, ${fl(SHELL.R - 1)}, length(xz));                       // (the water ends at the painted wall)
  #ifdef USE_FOG
    take *= exp(-fogDensity * fogDensity * vFogDepth * vFogDepth);
  #endif
  gl_FragColor = vec4(take, 0.);
}`;
// THE SAME LIGHT LAW IN JS (for the proof): the water where a thing of the bay takes `lamp` of the lamp's part and
// `foot` of the dome's part off its body, against the same water beside it (luminance), d metres from the eye's
// foot, where it mirrors a paint of the sky (a hex). The lamp's part is the hero's own count (waterInShade); the
// dome's part stands to it as the two parts of the body's light stand to one another, which the hero's count tells
// where the water mirrors nothing (there it is the dome's part over the whole body).
export function bayWaterInShade(look, d, paint, lamp, foot) {
  const key = 1 - waterInShade(look, d, paint), dome = waterInShade(look, d, '#000000');
  return 1 - key * (lamp + foot * dome / Math.max(1 - dome, 1e-9));
}
