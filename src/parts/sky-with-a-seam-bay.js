// ONE THING'S OWN SHADE AT A PLACE (x, z): the share of the lamp's round its slabs hide there (ly: the lamp's
// height; soft: metres added to the half-shade across the light, half a texel when a map is filled, else none).
// The place lies a metres along the light from the thing's middle and s across it. A slab that stands toward the
// lamp (throw t = a - its own depth) hides, ACROSS the light, the stretch of the round it covers (the round reaches
// pa = ka * t either way of the place's own line: u from -1 to 1), and IN HEIGHT the share under its top (the
// round stands from y - pv to y + pv at the slab, y the height at which the lamp's middle is seen over it,
// pv = kv * t: all of it under a slab taller than y + pv, none over one lower than y - pv), times its fill; a
// slab on a foot hides only what stands over its foot. Where slabs stand before one another the round is hidden
// once: in every stretch of it the tallest cover of the slabs that stand from the water, and on that what the
// slabs on a foot add.
// The law in its two halves, so that the map's bake and the proof ask the same lines. shadeRows: ALONG the light.
// For every place a metres along it the slabs that stand toward the lamp are the same, each with the same reach
// of the round across (pa) and the same share of its height hidden (w): kept on the thing's slate (g.R, eight
// numbers a slab: s0, s1, pa, w, on a foot, one over pa, and the stretch across in which it hides anything, from
// and to; g.n numbers in all; g.most: the widest reach of any).
function shadeRows(g, ly, a, soft) {
  const Dp = g.D0 + a, k = Dp / g.D0, q = shadeRates(Math.hypot(Dp, ly), ly), ka = q.ka, kv = q.kv, Q = g.Q, R = g.R; let n = 0;
  for (let i = 0, end = Q.length; i < end; i += 6) { const t = a - Q[i + 2]; if (t <= 0) continue;
    const pv = kv * t + 0.03, y = ly * t / Dp, base = Q[i + 5]; let w = smooth((Q[i + 3] - y + pv) / (2 * pv)); if (base > 0) w -= smooth((base - y + pv) / (2 * pv));
    w *= Q[i + 4]; if (w <= 0) continue;
    const pa = (ka * t + soft) / k; R[n] = Q[i]; R[n + 1] = Q[i + 1]; R[n + 2] = pa; R[n + 3] = w; R[n + 4] = base > 0 ? 1 : 0; R[n + 5] = 1 / pa; R[n + 6] = Q[i] - pa; R[n + 7] = Q[i + 1] + pa; n += 8; }
  g.n = n; g.most = (ka * (a - g.aMin) + soft) / k;
}
// shadeOf: ACROSS the light. The share of the round those slabs hide from the place s across (shadeRows first).
// (A slab that hides the round's whole width is kept by itself, not among the stretches: full, the tallest cover of
// such slabs from the water; fullAdd, what such slabs on a foot add. The sum is the same. Both begin as a nought
// read from a row of numbers, NOUGHT: a fraction from the first, as every share is.)
const NOUGHT = new Float64Array(1);
function shadeOf(g, s) {
  const R = g.R, E = g.E, P = g.P, end = g.n; let n = 0, m = 0, full = NOUGHT[0], fullAdd = NOUGHT[0];
  for (let i = 0; i < end; i += 8) { if (s <= R[i + 6] || s >= R[i + 7]) continue;
    let u0 = (R[i] - s) * R[i + 5], u1 = (R[i + 1] - s) * R[i + 5]; if (u0 < -1) u0 = -1; if (u1 > 1) u1 = 1; if (u1 <= u0) continue;
    if (u0 === -1 && u1 === 1) { if (R[i + 4]) fullAdd += R[i + 3]; else if (R[i + 3] > full) full = R[i + 3]; if (full + fullAdd >= 1) return 1; continue; }
    E[n] = u0; E[n + 1] = u1; E[n + 2] = R[i + 3]; E[n + 3] = R[i + 4]; n += 4;
    let j = m++; while (j > 0 && P[j - 1] > u0) { P[j] = P[j - 1]; j--; } P[j] = u0;
    j = m++; while (j > 0 && P[j - 1] > u1) { P[j] = P[j - 1]; j--; } P[j] = u1; }
  const under = Math.min(full + fullAdd, 1); if (!n) return under;
  if (n === 4 && !under) return Math.min(E[2], 1) * (E[1] - E[0]) / 2;
  let sum = under * (P[0] + 1 + 1 - P[m - 1]);
  for (let j = 0; j + 1 < m; j++) { const ua = P[j], ub = P[j + 1]; if (ub - ua < 1e-9) continue; const mid = (ua + ub) / 2; let top = full, add = fullAdd;
    for (let i = 0; i < n; i += 4) if (E[i] <= mid && mid <= E[i + 1]) { if (E[i + 3]) add += E[i + 2]; else if (E[i + 2] > top) top = E[i + 2]; }
    sum += Math.min(top + add, 1) * (ub - ua); }
  return sum / 2;
}
// shadeOne: the same share where one slab alone is counted (shadeOf's own lines for it, written out: most rings of
// the bake hold one slab)
function shadeOne(g, s) {
  const R = g.R; if (s <= R[6] || s >= R[7]) return 0;
  let u0 = (R[0] - s) * R[5], u1 = (R[1] - s) * R[5]; if (u0 < -1) u0 = -1; if (u1 > 1) u1 = 1;
  return u1 <= u0 ? 0 : Math.min(R[3], 1) * (u1 - u0) / 2;
}
export function shadeShare(g, ly, x, z, soft = 0) {
  const rx = x - g.x, rz = z - g.z, a = rx * g.ux + rz * g.uz; if (a <= g.aMin || a > g.aFar) return 0;
  const k = (g.D0 + a) / g.D0, s = (rx * g.px + rz * g.pz) / k; shadeRows(g, ly, a, soft);
  return s + g.most <= g.lo || s - g.most >= g.hi ? 0 : shadeOf(g, s);
}
// ONE THING'S SHADE INTO THE MAP, by the law, asked where it changes and no oftener. Along the light the law is
// asked on RINGS (lines across the light, a metres along it). Its share changes at once only where a slab stands
// (there the slab begins to hide): so one ring stands AT every slab's own place (the slab not yet counted) and one
// BAY.shade.grain.edge past it (counted); between those a ring every BAY.shade.grain.deep texels through the
// thing's own depth, and past it one every BAY.shade.grain.along of the throw (the shade changes no faster: its
// half-shade and its dying both grow with the throw). On a ring a sample every BAY.shade.grain.fine texel across, or every
// BAY.shade.grain.across-th part of the narrowest half-shade there once that is wider. A place takes its share
// from the two rings it lies between, straight between their samples (shadeRing). Every texel of the thing's fan
// inside the dome is asked so, row by row of the map; but where the narrowest half-shade is
// BAY.shade.grain.block[1] texels or wider the map is filled in blocks of BAY.shade.grain.block[0] texels,
// straight between the blocks' corners. The map keeps the most any thing hides (as it is laid: a byte,
// BAY.shade.least taken off). shadeThrow is a generator: it rests whenever the slate's count of work is full, so
// no build step is long.
// the slate, one for the whole bake: G, the rings of the thing in hand, sixteen numbers a ring (SR: its place
// along the light; one over the metres to the next; the stretch across in which it or the next holds more than the
// least, from and to; its first sample's place across; one over the samples' step; where its samples lie in V; how
// many; its own stretch that holds more than the least); V, the samples; RI, for every texel of throw the ring
// before it; and the fan's four corners, the rows' ends, the blocks' corners
const SR = { A: 0, IA: 1, P0: 2, P1: 3, S0: 4, IS: 5, O: 6, C: 7, X0: 8, X1: 9, size: 16 };
const shadeSlate = (N) => ({ G: new Float64Array(256 * SR.size), V: new Float32Array(1 << 15), RI: new Int32Array(1024), nr: 0, nv: 0, last: -1, a0: 0, aEnd: 0, itx: 1, work: 0, quad: new Float64Array(8),
  ends: new Int32Array(8), lat: [new Float32Array(N + 3), new Float32Array(N + 3)], stamp: [new Int32Array(N + 3).fill(-1), new Int32Array(N + 3).fill(-1)] });
// one ring of g onto the slate, a metres along the light
function shadeRingAt(M, g, T, a) {
  const S = BAY.shade, tx = M.texel, least = S.least, R = g.R, Z = SR.size;
  if ((T.nr + 2) * Z > T.G.length) { const G = new Float64Array(T.G.length * 2); G.set(T.G); T.G = G; }
  shadeRows(g, M.lamp.y, a, 0.5 * tx);
  const G = T.G, o = T.nr * Z, nv = T.nv; let sA = Infinity, sB = -Infinity, pm = Infinity;
  for (let i = 0; i < g.n; i += 8) { if (R[i + 6] < sA) sA = R[i + 6]; if (R[i + 7] > sB) sB = R[i + 7]; if (R[i + 2] < pm) pm = R[i + 2]; }
  G[o + SR.A] = a; G[o + SR.O] = nv; G[o + SR.C] = 0; G[o + SR.X0] = Infinity; G[o + SR.X1] = -Infinity;
  if (g.n) { const k = (g.D0 + a) / g.D0, ds = Math.max(S.grain.fine * tx / k, pm / S.grain.across), J = Math.ceil((sB - sA) / ds) + 1; let j0 = -1, j1 = -1;
    if (nv + J > T.V.length) { const V = new Float32Array(Math.max(T.V.length * 2, nv + J)); V.set(T.V); T.V = V; }
    const V = T.V;
    if (g.n === 8) for (let j = 0; j < J; j++) { const w = shadeOne(g, sA + j * ds); V[nv + j] = w; if (w > least) { if (j0 < 0) j0 = j; j1 = j; } }
    else for (let j = 0; j < J; j++) { const w = shadeOf(g, sA + j * ds); V[nv + j] = w; if (w > least) { if (j0 < 0) j0 = j; j1 = j; } }
    G[o + SR.S0] = sA; G[o + SR.IS] = 1 / ds; G[o + SR.C] = J; if (j0 >= 0) { G[o + SR.X0] = sA + (j0 - 1) * ds; G[o + SR.X1] = sA + (j1 + 1) * ds; T.last = T.nr; }
    T.nv = nv + J; T.work += J * (2 + g.n / 8); }
  T.nr++;
}
// the rings of g onto the slate; gives how many of them the fan needs (past the last that holds more than the least there is nothing to lay)
function shadeRings(M, g) {
  const S = BAY.shade, tx = M.texel, deps = g.deps, edge = S.grain.edge, T = M.slate || (M.slate = shadeSlate(M.N)), Z = SR.size; T.nr = 0; T.nv = 0; T.last = -1;
  for (let a = g.aMin + edge, di = 1; ; ) {
    shadeRingAt(M, g, T, a); if (a >= g.aFar) break;
    while (di < deps.length && deps[di] <= a) di++;
    // the next ring (never nearer than a texel, but for a slab's own); a slab that stands before it: one ring at its place, the next just past it
    let next = a + Math.max(tx * (a < g.aMax ? S.grain.deep : 1), (a - g.aMax) * S.grain.along); if (g.aFar - next < tx) next = g.aFar;
    if (di < deps.length && deps[di] < next && deps[di] + edge < g.aFar) { shadeRingAt(M, g, T, deps[di]); next = deps[di] + edge; di++; }
    a = next;
  }
  const G = T.G, nr = Math.min(T.last + 2, T.nr); if (T.last < 0 || nr < 2) return (T.nr = 0);
  T.nr = nr; T.a0 = G[0]; T.aEnd = G[(nr - 1) * Z]; T.itx = 1 / tx;
  for (let i = 0; i + 1 < nr; i++) { const o = i * Z; G[o + SR.IA] = 1 / (G[o + Z] - G[o]); G[o + SR.P0] = Math.min(G[o + SR.X0], G[o + Z + SR.X0]); G[o + SR.P1] = Math.max(G[o + SR.X1], G[o + Z + SR.X1]); }
  const bins = Math.ceil((T.aEnd - T.a0) / tx) + 2; if (bins > T.RI.length) T.RI = new Int32Array(bins * 2);
  for (let q = 0, i = 0; q < bins; q++) { const a = T.a0 + q * tx; while (i + 2 < nr && G[(i + 1) * Z] <= a) i++; T.RI[q] = i; }
  return nr;
}
// the share the slate's rings give the place a metres along the light and s across it (a past the thing's first slab and not past the last ring)
function shadeRing(T, a, s) {
  const G = T.G; let o = T.RI[((a - T.a0) * T.itx) | 0] << 4; while (a > G[o + 16]) o += 16;
  if (s <= G[o + 2] || s >= G[o + 3]) return 0;
  let w0 = 0, w1 = 0, n = G[o + 7];
  if (n) { const f = (s - G[o + 4]) * G[o + 5]; if (f > 0 && f < n - 1) { const j = f | 0, p = G[o + 6] + j, V = T.V; w0 = V[p] + (V[p + 1] - V[p]) * (f - j); } }
  n = G[o + 23];
  if (n) { const f = (s - G[o + 20]) * G[o + 21]; if (f > 0 && f < n - 1) { const j = f | 0, p = G[o + 22] + j, V = T.V; w1 = V[p] + (V[p + 1] - V[p]) * (f - j); } }
  return w0 + (w1 - w0) * (a - G[o]) * G[o + 1];
}
function* shadeThrow(M, g) {
  const S = BAY.shade, rest = S.grain.rest, B = S.grain.block[0], nr = shadeRings(M, g), T = M.slate; if (!nr) return;
  if (T.work > rest) { T.work = 0; yield; }
  // the fan's own four-cornered piece of the map: across the light a shade widens no faster than the round's
  // widest reach (SHADOW.core over the lamp's height, for a metre of throw)
  const Qd = T.quad, tx = M.texel, ly = M.lamp.y, kw = SHADOW.core / ly; let z0 = Infinity, z1 = -Infinity;
  for (let c = 0; c < 4; c++) { const a = c === 0 || c === 1 ? g.aMin : T.aEnd, k = (g.D0 + a) / g.D0, pad = kw * (a - g.aMin) + 1.5 * tx, s = c === 0 || c === 3 ? g.lo * k - pad : g.hi * k + pad;
    Qd[c * 2] = (g.x + g.ux * a + g.px * s - M.x0) / tx; const z = Qd[c * 2 + 1] = (g.z + g.uz * a + g.pz * s - M.z0) / tx; if (z < z0) z0 = z; if (z > z1) z1 = z; }
  // from where on the map is filled in blocks: where the narrowest half-shade (the last slab's, at the fan's far end's rate) is as wide as the blocks ask
  const aB = g.aMax + (S.grain.block[1] * tx - 0.5 * tx) / shadeRates(Math.hypot(g.D0 + T.aEnd, ly), ly).ka, vB = Math.min(M.N - 1, Math.ceil(z1 - 0.5));
  T.stamp[0].fill(-1); T.stamp[1].fill(-1);
  for (let v = Math.floor(Math.max(0, Math.floor(z0 - 0.5)) / B) * B; v <= vB; v += B) { shadeBand(M, g, v, aB); if (T.work > rest) { T.work = 0; yield; } }
}
// the ends of one row of the map in the fan (its four corners on the slate) and in the dome: T.ends[2r], T.ends[2r + 1] (none: the first past the second)
function shadeEnds(M, T, v, r) {
  const Qd = T.quad, N = M.N, tx = M.texel, R2 = (SHELL.R - 1) * (SHELL.R - 1), zc = v + 0.5, wz = M.z0 + zc * tx, r2 = R2 - wz * wz; let x0 = Infinity, x1 = -Infinity; T.ends[2 * r] = 1; T.ends[2 * r + 1] = 0;
  if (v < 0 || v >= N || r2 <= 0) return;
  for (let c = 0; c < 4; c++) { const d = ((c + 1) & 3) * 2, za = Qd[c * 2 + 1], zb = Qd[d + 1]; if ((za <= zc) === (zb <= zc)) continue;
    const x = Qd[c * 2] + (zc - za) * (Qd[d] - Qd[c * 2]) / (zb - za); if (x < x0) x0 = x; if (x > x1) x1 = x; }
  if (x0 > x1) return;
  const rr = Math.sqrt(r2), dA = Math.ceil((-rr - M.x0) / tx - 0.5), dB = Math.floor((rr - M.x0) / tx - 0.5); let uA = Math.ceil(x0 - 0.5), uB = Math.floor(x1 - 0.5);
  if (uA < dA) uA = dA; if (uA < 0) uA = 0; if (uB > dB) uB = dB; if (uB > N - 1) uB = N - 1; T.ends[2 * r] = uA; T.ends[2 * r + 1] = uB;
}
// the share at the corner of a block (texel u of row v, which may lie off the map: a corner is only a place), asked once and kept (which: the upper or the lower row of corners)
function shadeCorner(M, g, T, which, u, v) {
  const j = u / BAY.shade.grain.block[0] + 1, st = T.stamp[which]; if (st[j] === v) return T.lat[which][j];
  const tx = M.texel, rx = M.x0 + (u + 0.5) * tx - g.x, rz = M.z0 + (v + 0.5) * tx - g.z, a = rx * g.ux + rz * g.uz;
  const w = a <= g.aMin || a > T.aEnd ? 0 : shadeRing(T, a, (rx * g.px + rz * g.pz) * g.D0 / (g.D0 + a)); st[j] = v; return (T.lat[which][j] = w);
}
// one band of the map (rows v to v + block - 1) in the fan of g: the blocks that lie whole past aB along the light (and not past the last ring) are filled between their corners, the rest texel by texel
function shadeBand(M, g, v, aB) {
  const S = BAY.shade, T = M.slate, N = M.N, tx = M.texel, B = S.grain.block[0], D = M.data, least = S.least, sc = 255 / (1 - least); let uMin = N, uMax = -1;
  for (let r = 0; r < B; r++) { shadeEnds(M, T, v + r, r); if (T.ends[2 * r] <= T.ends[2 * r + 1]) { if (T.ends[2 * r] < uMin) uMin = T.ends[2 * r]; if (T.ends[2 * r + 1] > uMax) uMax = T.ends[2 * r + 1]; } }
  if (uMax < uMin) return;
  // (a block's least and most metres along the light are at its corners, and both go one way along the band: the blocks filled so are one run of it, or none)
  const b0 = Math.floor(uMin / B), b1 = Math.floor(uMax / B), da = g.ux * tx * B, dz = g.uz * tx * B, aAt = (M.x0 + (b0 * B + 0.5) * tx - g.x) * g.ux + (M.z0 + (v + 0.5) * tx - g.z) * g.uz;
  const aLo = aAt + Math.min(0, da) + Math.min(0, dz), aHi = aAt + Math.max(0, da) + Math.max(0, dz), aEnd = T.aEnd; let c0 = b0, c1 = b1;
  if (da > 1e-9) { c0 = Math.max(b0, b0 + Math.ceil((aB - aLo) / da)); c1 = Math.min(b1, b0 + Math.floor((aEnd - aHi) / da)); }
  else if (da < -1e-9) { c1 = Math.min(b1, b0 + Math.floor((aB - aLo) / da)); c0 = Math.max(b0, b0 + Math.ceil((aEnd - aHi) / da)); }
  else if (aLo < aB || aHi > aEnd) c1 = b0 - 1;
  if (c1 >= c0) {
    // (the corner rows swap: this band's lower corners are the next band's upper)
    const wt = (v / B) & 1, top = T.lat[wt], bot = T.lat[wt ^ 1];
    for (let b = c0; b <= c1 + 1; b++) { shadeCorner(M, g, T, wt, b * B, v); shadeCorner(M, g, T, wt ^ 1, b * B, v + B); }
    for (let r = 0; r < B; r++) { const eA = T.ends[2 * r], eB = T.ends[2 * r + 1]; if (eA > eB) continue; const fr = r / B, row = (v + r) * N * 2; let from = M.from[v + r], to = M.to[v + r];
      for (let b = c0; b <= c1; b++) { const w00 = top[b + 1], w10 = top[b + 2], w01 = bot[b + 1], w11 = bot[b + 2]; if (w00 <= least && w10 <= least && w01 <= least && w11 <= least) continue;
        const u = b * B, uA = u > eA ? u : eA, uB = u + B - 1 < eB ? u + B - 1 : eB, wl = w00 + (w01 - w00) * fr, dw = (w10 + (w11 - w10) * fr - wl) / B;
        for (let i = uA, k = row + uA * 2; i <= uB; i++, k += 2) { const w = wl + dw * (i - u); if (!(w > least)) continue; const q = ((w - least) * sc + 0.5) | 0; if (q > D[k]) { D[k] = q; if (i < from) from = i; if (i > to) to = i; } } }
      M.from[v + r] = from; M.to[v + r] = to; }
    T.work += (c1 - c0 + 1) * (B * B + 20); }
  // the rest of the band, texel by texel: before that run and after it
  const f1 = c1 >= c0 ? c0 * B - 1 : uMax, f2 = c1 >= c0 ? (c1 + 1) * B : uMax + 1;
  for (let r = 0; r < B; r++) { const eA = T.ends[2 * r], eB = T.ends[2 * r + 1]; if (eA > eB) continue;
    const uB = f1 < eB ? f1 : eB, uA = f2 > eA ? f2 : eA;
    if (eA <= uB) { shadeRow(M, g, T, v + r, eA, uB); T.work += (uB - eA + 1) * 4; }
    if (uA <= eB) { shadeRow(M, g, T, v + r, uA, eB); T.work += (eB - uA + 1) * 4; } }
}
// one row of the map, from texel uA to uB, in the fan of g, texel by texel (shadeRing's own lines, written out here:
// this is the bake's innermost round; the numbers of the two rings a texel lies between are kept in hand as long
// as the texels that follow lie between the same two)
function shadeRow(M, g, T, v, uA, uB) {
  const tx = M.texel, D = M.data, G = T.G, V = T.V, RI = T.RI, a0 = T.a0, itx = T.itx, least = BAY.shade.least, sc = 255 / (1 - least), D0 = g.D0, aMin = g.aMin, aEnd = T.aEnd;
  const rz = M.z0 + (v + 0.5) * tx - g.z, rx = M.x0 + (uA + 0.5) * tx - g.x, da = g.ux * tx, dc = g.px * tx; let a = rx * g.ux + rz * g.uz, c = rx * g.px + rz * g.pz, from = M.from[v], to = M.to[v];
  let aLo = Infinity, aHi = -Infinity, A = 0, IA = 0, P0 = 0, P1 = 0, s0 = 0, i0 = 0, o0 = 0, n0 = 0, s1 = 0, i1 = 0, o1 = 0, n1 = 0;
  for (let u = uA, k = (v * M.N + uA) * 2; u <= uB; u++, k += 2, a += da, c += dc) {
    if (a <= aMin || a > aEnd) continue;
    if (!(a > aLo && a <= aHi)) { let o = RI[((a - a0) * itx) | 0] << 4; while (a > G[o + 16]) o += 16;
      aLo = G[o]; aHi = G[o + 16]; A = aLo; IA = G[o + 1]; P0 = G[o + 2]; P1 = G[o + 3]; s0 = G[o + 4]; i0 = G[o + 5]; o0 = G[o + 6]; n0 = G[o + 7] - 1; s1 = G[o + 20]; i1 = G[o + 21]; o1 = G[o + 22]; n1 = G[o + 23] - 1; }
    const s = c * D0 / (D0 + a); if (s <= P0 || s >= P1) continue;
    let w0 = 0, w1 = 0; const f0 = (s - s0) * i0, f1 = (s - s1) * i1;
    if (f0 > 0 && f0 < n0) { const j = f0 | 0, p = o0 + j; w0 = V[p] + (V[p + 1] - V[p]) * (f0 - j); }
    if (f1 > 0 && f1 < n1) { const j = f1 | 0, p = o1 + j; w1 = V[p] + (V[p + 1] - V[p]) * (f1 - j); }
    const w = w0 + (w1 - w0) * (a - A) * IA; if (!(w > least)) continue;
    const q = ((w - least) * sc + 0.5) | 0; if (q > D[k]) { D[k] = q; if (u < from) from = u; if (u > to) to = u; }
  }
  M.from[v] = from; M.to[v] = to;
}
// THE FOOT: close under a skin that stands in the water the body loses its whole light. Every texel takes the
// nearest standing skin (two sweeps of the map, each texel asking its neighbours' nearest), and the share
// 1 - d / hypot(d, h) of the law (BAY.shade.foot), h the tallest skin within a texel of that place. The sweeps keep
// to the TILES of the map (sixteen texels a side, the skins' own) within the metres at which the foot of the
// tallest skin standing in a tile is still BAY.shade.least: past them no foot is laid; and a run of a row is
// asked only where there is something to ask (a skin of its own in the row, or a nearest in the row the sweep
// comes from). A row is final when the second sweep has passed it: there and then its foot is laid into the map,
// and the layer's cells that the row reaches are marked (the throws have laid the lamp's part before). A
// generator (it rests as the throw does).
// (src: for every texel its nearest standing skin, as the texels to it along and down the map, each with 128
// added, in one number; 0: none yet. own: the rows in which a skin stands. held: for every row, the runs of it
// that hold a nearest, a bit a run.)
function* shadeFoot(M) {
  const S = BAY.shade, N = M.N, nt = M.nt, rest = S.grain.rest, src = new Uint16Array(N * N), tall = new Float32Array(nt * nt), mark = new Uint8Array(nt * nt), own = new Uint8Array(N), held = new Int32Array(N);
  for (let t = 0; t < nt * nt; t++) if (M.wet[t]) footSkin(M, src, tall, own, t);
  yield;
  // the tiles the sweeps keep to, and of every row of tiles the runs of them (first texel, last texel)
  const far = (1 - S.least) / Math.sqrt(1 - (1 - S.least) * (1 - S.least)) / M.texel, runs = [];
  for (let tv = 0; tv < nt; tv++) for (let tu = 0; tu < nt; tu++) { const h = tall[tv * nt + tu]; if (h > 0) footReach(mark, nt, tu, tv, Math.ceil(h * far) + 1); }
  for (let tv = 0; tv < nt; tv++) { const row = []; for (let tu = 0; tu < nt; tu++) { if (!mark[tv * nt + tu]) continue; let e = tu; while (e + 1 < nt && mark[tv * nt + e + 1]) e++; row.push(tu * 16, Math.min(e * 16 + 15, N - 1)); tu = e; } runs.push(row); }
  // (a bit a run; where a row of tiles has more runs than bits the last bit is theirs together)
  const bit = (i) => 1 << Math.min(i >> 1, 30); let work = 0;
  for (let v = 0; v < N; v++) { const row = runs[v >> 4], first = (v & 15) === 0, up = v > 0 ? held[v - 1] : 0;
    for (let i = 0; i < row.length; i += 2) { const b = bit(i); if (!(own[v] || (first ? up : up & b))) continue;
      if (footFore(src, N, v, row[i], row[i + 1], 1)) { footBack(src, N, v, row[i], row[i + 1], 1); held[v] |= b; } work += 4 * (row[i + 1] - row[i]); }
    if (work > rest) { work = 0; yield; } }
  for (let v = N - 1; v >= 0; v--) { const row = runs[v >> 4], first = (v & 15) === 15, up = v < N - 1 ? held[v + 1] : 0;
    for (let i = 0; i < row.length; i += 2) { const b = bit(i);
      if ((first ? up : up & b) && footFore(src, N, v, row[i], row[i + 1], -1)) { footBack(src, N, v, row[i], row[i + 1], -1); held[v] |= b; work += 4 * (row[i + 1] - row[i]); }
      if (held[v] & b) { footLay(M, src, v, row[i], row[i + 1]); work += 2 * (row[i + 1] - row[i]); } }
    if (M.to[v] >= M.from[v]) { shadeCells(M, v); work += M.to[v] - M.from[v] + 1; }
    if (work > rest) { work = 0; yield; } }
}
// one tile of the map in which a skin stands: where it stands the foot is whole (laid at once), and the skin is
// one the sweeps go out from, as tall as the tallest skin within a texel of it (kept in M.stand; tall: the tallest
// of the tile). (A member thinner than a texel, marked 0.02 tall, is no skin to be near: its foot is its own texel.)
function footSkin(M, src, tall, own, t) {
  const N = M.N, nt = M.nt, stand = M.stand, high = M.high, data = M.data, tu = (t % nt) * 16, tv = Math.floor(t / nt) * 16;
  for (let lv = 0; lv < 16 && tv + lv < N; lv++) { const v = tv + lv; let from = M.from[v], to = M.to[v];
    for (let lu = 0; lu < 16 && tu + lu < N; lu++) { const i = (t << 8) | (lv << 4) | lu; if (!(stand[i] > 0)) continue; const u = tu + lu, k = v * N + u;
      data[k * 2] = data[k * 2 + 1] = 255; if (u < from) from = u; if (u > to) to = u;
      if (!(stand[i] > 0.05)) continue; let h = stand[i];
      for (let dv = -1; dv <= 1; dv++) for (let du = -1; du <= 1; du++) { const uu = u + du, vv = v + dv; if (uu < 0 || vv < 0 || uu >= N || vv >= N) continue; const hh = high[tileAt(uu, vv, nt)]; if (hh > h) h = hh; }
      src[k] = 0x8080; own[v] = 1; stand[i] = h; if (h > tall[t]) tall[t] = h; }
    M.from[v] = from; M.to[v] = to; }
}
// the tiles within r texels of the tile (tu, tv): marked
function footReach(mark, nt, tu, tv, r) {
  const n = Math.ceil(r / 16), b0 = tv - n < 0 ? 0 : tv - n, b1 = tv + n > nt - 1 ? nt - 1 : tv + n, a0 = tu - n < 0 ? 0 : tu - n, a1 = tu + n > nt - 1 ? nt - 1 : tu + n;
  for (let b = b0; b <= b1; b++) { const j = b > tv ? b - tv : tv - b, dy = j ? (j - 1) * 16 + 1 : 0;
    for (let a = a0; a <= a1; a++) { const i = a > tu ? a - tu : tu - a, dx = i ? (i - 1) * 16 + 1 : 0; if (dx * dx + dy * dy <= r * r) mark[b * nt + a] = 1; } }
}
// one run of one row, the sweep's way along it (texels ua to ub; dir 1: the first sweep, the row before asked, left
// to right; dir -1: the second, the row after, right to left): a texel keeps the nearest of its own, of the texel
// before it in the row and of the three next to it in the other row. Gives whether the run holds any nearest.
function footFore(src, N, v, ua, ub, dir) {
  const row = v * N, o = -dir * N, has = v - dir >= 0 && v - dir < N; let u = dir > 0 ? ua : ub, any = 0;
  for (let c = ub - ua; c >= 0; c--, u += dir) { const k = row + u, back = u - dir >= 0 && u - dir < N, fore = u + dir >= 0 && u + dir < N; let best = src[k], bd = 16129, p, du, dv, d;
    if (best) { du = (best >> 8) - 128; dv = (best & 255) - 128; bd = du * du + dv * dv; }
    if (back) { p = src[k - dir]; if (p) { du = (p >> 8) - 128 - dir; dv = (p & 255) - 128; d = du * du + dv * dv; if (d < bd) { bd = d; best = ((du + 128) << 8) | (dv + 128); } } }
    if (has) { p = src[k + o]; if (p) { du = (p >> 8) - 128; dv = (p & 255) - 128 - dir; d = du * du + dv * dv; if (d < bd) { bd = d; best = ((du + 128) << 8) | (dv + 128); } }
      if (back) { p = src[k + o - dir]; if (p) { du = (p >> 8) - 128 - dir; dv = (p & 255) - 128 - dir; d = du * du + dv * dv; if (d < bd) { bd = d; best = ((du + 128) << 8) | (dv + 128); } } }
      if (fore) { p = src[k + o + dir]; if (p) { du = (p >> 8) - 128 + dir; dv = (p & 255) - 128 - dir; d = du * du + dv * dv; if (d < bd) { bd = d; best = ((du + 128) << 8) | (dv + 128); } } } }
    if (best) { src[k] = best; any = 1; } }
  return any;
}
// the same run, back along the row: a texel asks the one it has not asked yet
function footBack(src, N, v, ua, ub, dir) {
  const row = v * N; let u = dir > 0 ? ub - 1 : ua + 1;
  for (let c = ub - ua - 1; c >= 0; c--, u -= dir) { const k = row + u, p = src[k + dir]; if (!p) continue; const du = (p >> 8) - 128 + dir, dv = (p & 255) - 128, d = du * du + dv * dv, q = src[k]; if (d >= 16129) continue;
    if (!q || d < ((q >> 8) - 128) * ((q >> 8) - 128) + ((q & 255) - 128) * ((q & 255) - 128)) src[k] = ((du + 128) << 8) | (dv + 128); }
}
// one run of one row laid: the foot's share by the law at every texel that has a skin near, into the map as laid
function footLay(M, src, v, ua, ub) {
  const N = M.N, nt = M.nt, tx = M.texel, stand = M.stand, data = M.data, least = BAY.shade.least; let from = M.from[v], to = M.to[v];
  for (let u = ua, k = v * N + ua; u <= ub; u++, k++) { const p = src[k]; if (!p) continue; const du = (p >> 8) - 128, dv = (p & 255) - 128, d2 = du * du + dv * dv; if (!d2) continue;
    const d = Math.sqrt(d2) * tx, h = stand[tileAt(u + du, v + dv, nt)], f = 1 - d / Math.sqrt(d * d + h * h); if (!(f > least)) continue; const b = Math.round((f - least) / (1 - least) * 255); if (!b) continue;
    if (b > data[k * 2 + 1]) data[k * 2 + 1] = b; if (b > data[k * 2]) data[k * 2] = b; if (u < from) from = u; if (u > to) to = u; }
  M.from[v] = from; M.to[v] = to;
}
// THE MAP AS IT IS LAID: two bytes a texel (the lamp's part of the body's light taken there: the shade or the
// foot, whichever is more; the dome's part: the foot), BAY.shade.least taken off every share; and the cells of
// the layer that carries it, wherever a texel of the map holds anything. at(x, z): the two shares at a place.
// (A generator as the others: the throws have laid the lamp's part; here the foot and the cells' marks, then the
// cells themselves; it gives the laid map when it is done.)
function* shadeLaid(M) {
  const S = BAY.shade, N = M.N, data = M.data, on = M.on, nc = M.nc;
  yield* shadeFoot(M);
  yield;
  // (the cells: two triangles each, their corners shared; seen: the corner's number, one more than it is, or none yet)
  const pos = [], idx = [], seen = new Int32Array((nc + 1) * (nc + 1));
  for (let j = 0; j < nc; j++) for (let i = 0; i < nc; i++) { if (!on[j * nc + i]) continue; const q = [0, 0, 0, 0];
    for (let c = 0; c < 4; c++) { const ci = i + (c & 1), cj = j + (c >> 1), k = cj * (nc + 1) + ci; if (!seen[k]) { pos.push(M.x0 + ci * S.cell, 0, M.z0 + cj * S.cell); seen[k] = pos.length / 3; } q[c] = seen[k] - 1; }
    idx.push(q[0], q[2], q[1], q[1], q[2], q[3]); }
  const at = (x, z) => { const fu = (x - M.x0) / M.texel - 0.5, fv = (z - M.z0) / M.texel - 0.5, u = Math.floor(fu), v = Math.floor(fv), a = fu - u, b = fv - v;
    const get = (uu, vv, c) => (uu < 0 || vv < 0 || uu >= N || vv >= N ? 0 : data[(vv * N + uu) * 2 + c] / 255), mix = (c) => (get(u, v, c) * (1 - a) + get(u + 1, v, c) * a) * (1 - b) + (get(u, v + 1, c) * (1 - a) + get(u + 1, v + 1, c) * a) * b;
    return [mix(0), mix(1)]; };
  // (near: the two shares the map itself holds at the texel a place lies in)
  const near = (x, z) => { const u = Math.floor((x - M.x0) / M.texel), v = Math.floor((z - M.z0) / M.texel); return u < 0 || v < 0 || u >= N || v >= N ? [0, 0] : [data[(v * N + u) * 2] / 255, data[(v * N + u) * 2 + 1] / 255]; };
  return { data, pos, idx, at, near, cells: idx.length / 6 };
}
// the layer's cells that one row of the laid map reaches (the texels of the row that hold anything; where one
// does, the texels after it that reach the same cells are passed over)
function shadeCells(M, v) {
  const D = M.data, on = M.on, nc = M.nc, c0 = M.c0, c1 = M.c1, past = M.past, z0 = c0[v] * nc, z1 = c1[v] * nc, row = v * M.N * 2;
  for (let u = M.from[v], ub = M.to[v]; u <= ub; u++) { if (!D[row + u * 2]) continue; for (let cz = z0; cz <= z1; cz += nc) for (let cx = c0[u]; cx <= c1[u]; cx++) on[cz + cx] = 1; u = past[u] - 1; }
}
