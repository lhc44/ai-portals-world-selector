// THE RAFTS, dealt last (every other thing stands already): BAY.raft tells the rule. route.mouth, route.turn: the
// crossing's two marks (metres of route); deal: the rafts' own stream. A raft's own frame: b away from the line,
// a along it, so its middle's distance from the line keeps every seat inside the band.
function dealRafts(route, deal, out, atM, marks) {
  const R = BAY.raft, C = R.clear, L = BAY.lane, third = (route.turn - route.mouth) / 3, seats = K.raftSeats(R.n);
  const dLo = R.band[0] - Math.min(...seats.map((q) => q[1])) + 0.1, dHi = R.band[1] - Math.max(...seats.map((q) => q[1])) - 0.1;
  const inRun = (m, runs) => runs.some((r) => m >= marks[r.from] + r.a + R.run && m <= marks[r.from] + r.b - R.run);
  const clearAt = (x, z) => {
    for (const T of out) {
      if (T.kind === 'net') { if (T.pts.some((q) => Math.hypot(q[0] - x, q[1] - z) < C.float)) return false; continue; }
      if (T.kind === 'skerry' || T.kind === 'jetty') {
        const f = K.frameAt(T.x, T.z, T.bearing), dx = x - T.x, dz = z - T.z, a = dx * f.sx + dz * f.sz, b = dx * f.fx + dz * f.fz;
        if (T.kind === 'jetty') { if (a > BAY.jetty.head - C.jetty && a < BAY.jetty.root + C.jetty && Math.abs(b) < C.jetty + 2) return false; continue; }
        const k = T.round ? C.round : C.skerry; if ((a / (T.spec.ra + k)) ** 2 + (b / (T.spec.rb + k)) ** 2 < 1) return false; continue; }
      const need = C[T.kind]; if (need && Math.hypot(T.x - x, T.z - z) < need) return false;
    }
    return true; };
  const seat = (m, port, d) => { if (!inRun(m, port ? L.port : L.starboard)) return null; const q = atM(m, port ? -d : d); return clearAt(q.x, q.z) ? { ...q, port } : null; };
  for (let i = 0; i < 3; i++) {
    const lo = route.mouth + i * third + R.inset, hi = route.mouth + (i + 1) * third - R.inset, dice = [];
    for (let k = 0; k < R.tries; k++) dice.push([deal(), deal(), deal()]);                    // all dice before any test
    let got = null, throws = 0;
    for (const [a, b, c] of dice) { throws++; got = seat(lo + a * (hi - lo), b < 0.5, dLo + c * (dHi - dLo)); if (got) break; }
    if (!got) throws = 0;                                                                     // (0: found by the sweep, or left out)
    // (the most is thrown: one sweep of the third, metre by metre, with the last dice's distance, either hand)
    if (!got) { const [, b, c] = dice[dice.length - 1], d = dLo + c * (dHi - dLo); for (let m = lo; m <= hi && !got; m++) got = seat(m, b < 0.5, d) || seat(m, b >= 0.5, d); }
    if (got) out.push({ kind: 'raft', name: 'raft ' + i, x: got.x, z: got.z, s: got.s, d: got.d, heading: got.heading, bearing: got.heading + (got.port ? -90 : 90), third: i, port: got.port, throws });
  }
}
