// ---- THE SHADES ON THE WATER: SHADOWS ON A MIRROR, by the hero's own law (SHADOW, SEA_BODY, WATER_SHADE). The
// mirror's picture is never shaded: the layer TAKES LIGHT OFF THE WATER'S BODY alone (the lamp's part where a thing
// stands between the lamp and the water, the dome's part too close under a thing), exactly the light the hero's
// sea gives that body, so no dark sheet lies on the water and the mirrored painting, the images and the lamp's own
// image keep their whole light. BAKED ONCE, at the build, into one map of the bay's water (BAY.shade), for the lamp
// at the middle of its creep (the creep moves a shade by a share of its own half-shade: shadeCreep tells it).
// THE LAW OF A THING'S SHADE (shadeGroup, shadeShare): a thing is its blades, upright slabs across the light (place,
// half width, height: the makers' cast). The lamp is a drum, not a point: seen from a place of the water its round
// stands SHADOW.core wide across the light and SHADOW.drum tall along its run (shadeRates: metres of half-shade
// for a metre of throw); the shade there is THE SHARE OF THAT ROUND THE THING'S SLABS HIDE, each slab seen from
// the place at its own throw. So the half-shade grows with the throw, a thin member's shade is only a share and
// dies in a few metres, and a long throw dissolves along its length: a thing lower than the lamp's lower rim
// throws no shade past the place from which that rim is seen clear over it; one as tall as the lamp (the great
// ship, a light's tower) is thinned by the throw and ended only by the painted wall. No typed fade, no hard edge.
// the half-shade's rates at a place T metres from the lamp, the lamp ly m over the water: nd, the light's fall;
// ka, metres of half-shade across the light for a metre of throw; kv, the same in height
export const shadeRates = (T, ly) => { const nd = ly / T, m = (1 - nd) * (1 - nd);
  return { nd, ka: SHADOW.core / T / Math.max(nd, SHADOW.slantFloor), kv: (SHADOW.core + (SHADOW.drum - SHADOW.core) * m) / T }; };
// how far the lamp's creep moves a shade, as a share of that shade's own half-shade across the light (the same at
// every throw): the lamp's reach along its rail over the half-shade's rate times the lamp's distance
export const shadeCreep = (T, ly, reach) => (reach / T) / shadeRates(T, ly).ka;
const smooth = (v) => (v <= 0 ? 0 : v >= 1 ? 1 : v * v * (3 - 2 * v));
// one thing's slabs across the light: g = { x, z, name, blades: [[x, z, half width, height, alone?, fill, base], ...] }
// (the makers' cast). A slab stands a metres along the light from the thing's middle, from s0 to s1 across it (in
// metres at the middle's distance from the lamp)
function shadeGroup(g, lamp) {
  const S = BAY.shade, dx = g.x - lamp.x, dz = g.z - lamp.z, D0 = Math.hypot(dx, dz) || 1, ux = dx / D0, uz = dz / D0, px = -uz, pz = ux;
  const rows = g.blades.map((b) => { const rx = b[0] - g.x, rz = b[1] - g.z, a = rx * ux + rz * uz, k = D0 / (D0 + a), s = (rx * px + rz * pz) * k, w = b[2] * k;
    return { s0: s - w, s1: s + w, a, h: b[3], alone: !!b[4], fill: b[5] === undefined ? 1 : b[5], base: b[6] || 0 }; });
  rows.sort((p, q) => (q.s1 - q.s0) - (p.s1 - p.s0));        // (the widest first: where one slab hides the lamp's whole round the law has its answer at once)
  const lo = Math.min(...rows.map((r) => r.s0)), hi = Math.max(...rows.map((r) => r.s1));
  // where its shade ends: where the lamp's whole round is seen clear over its tallest slab; a member that stands
  // alone, where its share is nothing; and the painted wall
  const aMin = Math.min(...rows.map((r) => r.a)), cu = g.x * ux + g.z * uz, cc = g.x * g.x + g.z * g.z, wall = -cu + Math.sqrt(Math.max(cu * cu - cc + SHELL.R * SHELL.R, 0));
  let far = 0;
  for (const r of rows) { const T = D0 + r.a, q = shadeRates(Math.hypot(T, lamp.y), lamp.y), free = lamp.y - q.kv * Math.hypot(T, lamp.y) - r.h;
    let t = free > 0.05 ? r.h * T / free : Infinity; if (r.alone) t = Math.min(t, r.fill * 0.5 * (r.s1 - r.s0) / (q.ka * S.least));
    far = Math.max(far, r.a + t); }
  // (Q: the slabs once more as plain numbers, six a slab: s0, s1, a, h, fill, base; R, E, P: the law's own slate)
  const Q = new Float64Array(rows.length * 6); rows.forEach((r, i) => Q.set([r.s0, r.s1, r.a, r.h, r.fill, r.base], i * 6));
  // (deps: the places along the light at which its slabs stand, nearest the lamp first)
  const deps = []; for (const a of rows.map((r) => r.a).sort((p, q) => p - q)) if (!deps.length || a - deps[deps.length - 1] > S.grain.edge / 2) deps.push(a);
  return { name: g.name, x: g.x, z: g.z, D0, ux, uz, px, pz, lo, hi, rows, Q, deps, R: new Float64Array(rows.length * 8), n: 0, most: 0, E: new Float64Array(rows.length * 4), P: new Float64Array(rows.length * 2),
    aMin, aMax: Math.max(...rows.map((r) => r.a)), aFar: Math.min(far * 1.08 + 2, wall), wall, hMax: Math.max(...rows.map((r) => r.h)) };
}
// THE MAP: a square of the bay's water that holds every thing and every shade (inside the dome's own square), N
// texels a side. data: the map as it is laid, two bytes a texel (from, to: the texels of each row that hold any);
// high: the tallest skin over a texel (at most BAY.shade.foot.top); stand: a skin stands in the water there, and
// how tall it counts; wet: the tiles in which one does; on: the layer's cells that carry any of the map (c0, c1:
// the cells a texel reaches; past: the first texel after it that reaches other cells). high and stand are kept TILE BY TILE (a tile: sixteen texels a side; tileAt: a
// texel's place in them), so that the build touches only the tiles in which a skin stands low.
const tileAt = (u, v, nt) => ((((v >> 4) * nt + (u >> 4)) << 8) | ((v & 15) << 4) | (u & 15));
function shadeMap(groups, lamp) {
  const S = BAY.shade, N = S.map, nt = Math.ceil(N / 16), G = groups.map((g) => shadeGroup(g, lamp)); let x0 = Infinity, x1 = -Infinity, z0 = Infinity, z1 = -Infinity;
  for (const g of G) for (const a of [g.aMin, g.aFar]) for (const s of [g.lo - 30, g.hi + 30]) { const k = 1 + a / g.D0, x = g.x + g.ux * a + g.px * s * k, z = g.z + g.uz * a + g.pz * s * k;
    x0 = Math.min(x0, x); x1 = Math.max(x1, x); z0 = Math.min(z0, z); z1 = Math.max(z1, z); }
  x0 = Math.max(x0, -SHELL.R); z0 = Math.max(z0, -SHELL.R); x1 = Math.min(x1, SHELL.R); z1 = Math.min(z1, SHELL.R);
  const side = Math.max(x1 - x0, z1 - z0, 1), texel = side / N, nc = Math.ceil(side / S.cell), reach = texel + S.broken, c0 = new Int16Array(N), c1 = new Int16Array(N), past = new Int16Array(N);
  // (a texel reaches past its own square: the map is read between texels, and at a place the ripples shift)
  for (let u = 0; u < N; u++) { const p = (u + 0.5) * texel; c0[u] = Math.max(Math.floor((p - reach) / S.cell), 0); c1[u] = Math.min(Math.floor((p + reach) / S.cell), nc - 1); }
  for (let u = N - 1; u >= 0; u--) past[u] = u + 1 < N && c0[u + 1] === c0[u] && c1[u + 1] === c1[u] ? past[u + 1] : u + 1;
  return { N, nt, x0: (x0 + x1 - side) / 2, z0: (z0 + z1 - side) / 2, side, texel, lamp: lamp.clone(), G, data: new Uint8Array(N * N * 2), from: new Int16Array(N).fill(N), to: new Int16Array(N).fill(-1),
    high: new Float32Array(nt * nt * 256), stand: new Float32Array(nt * nt * 256), wet: new Uint8Array(nt * nt), nc, c0, c1, past, on: new Uint8Array(nc * nc), slate: null };
}
// the skins of one stretch of a chunk of the bay (P: nine numbers a triangle, in the world; from number i0 to i1):
// where a skin covers a texel's middle its height is kept; where a skin stands in the water (its lowest corner
// BAY.shade.foot.low or lower, its highest over the water) the texel is marked, and so is the texel under each of
// its corners that is that low (a pile, a spar, a chain: thinner than a texel, its foot is that one texel). (Asked
// a short stretch at a time: see THE BUILD'S PACE at makeBay.)
function shadeSkins(M, P, i0, i1) {
  const F = BAY.shade.foot, N = M.N, nt = M.nt, inv = 1 / M.texel, x0 = M.x0, z0 = M.z0, top = F.top, low = F.low, stand = M.stand, high = M.high, wet = M.wet;
  for (let i = i0; i < i1; i += 9) {
    const ya = P[i + 1], yb = P[i + 4], yc = P[i + 7], lowY = ya < yb ? (ya < yc ? ya : yc) : (yb < yc ? yb : yc), topY = ya > yb ? (ya > yc ? ya : yc) : (yb > yc ? yb : yc);
    if (topY <= 0.02 || lowY > top) continue;
    const ax = (P[i] - x0) * inv, az = (P[i + 2] - z0) * inv, bx = (P[i + 3] - x0) * inv, bz = (P[i + 5] - z0) * inv, cx = (P[i + 6] - x0) * inv, cz = (P[i + 8] - z0) * inv;
    const stands = lowY <= low, h = topY < top ? topY : top, area = Math.abs((bx - ax) * (cz - az) - (cx - ax) * (bz - az)) / 2;
    if (stands) { const m = area < 0.5 ? 0.02 : h; let u, v, k;
      if (ya <= low) { u = Math.floor(ax); v = Math.floor(az); if (u >= 0 && v >= 0 && u < N && v < N && m > stand[k = tileAt(u, v, nt)]) { stand[k] = m; wet[k >> 8] = 1; } }
      if (yb <= low) { u = Math.floor(bx); v = Math.floor(bz); if (u >= 0 && v >= 0 && u < N && v < N && m > stand[k = tileAt(u, v, nt)]) { stand[k] = m; wet[k >> 8] = 1; } }
      if (yc <= low) { u = Math.floor(cx); v = Math.floor(cz); if (u >= 0 && v >= 0 && u < N && v < N && m > stand[k = tileAt(u, v, nt)]) { stand[k] = m; wet[k >> 8] = 1; } } }
    if (area < 1e-6) continue;
    let u0 = Math.floor(ax < bx ? (ax < cx ? ax : cx) : (bx < cx ? bx : cx)), u1 = Math.floor(ax > bx ? (ax > cx ? ax : cx) : (bx > cx ? bx : cx)), v0 = Math.floor(az < bz ? (az < cz ? az : cz) : (bz < cz ? bz : cz)), v1 = Math.floor(az > bz ? (az > cz ? az : cz) : (bz > cz ? bz : cz));
    if (u0 < 0) u0 = 0; if (v0 < 0) v0 = 0; if (u1 > N - 1) u1 = N - 1; if (v1 > N - 1) v1 = N - 1;
    for (let v = v0; v <= v1; v++) { const z = v + 0.5, tr = (v >> 4) * nt, lv = (v & 15) << 4;
      for (let u = u0; u <= u1; u++) { const x = u + 0.5;
        const e0 = (bx - ax) * (z - az) - (bz - az) * (x - ax), e1 = (cx - bx) * (z - bz) - (cz - bz) * (x - bx), e2 = (ax - cx) * (z - cz) - (az - cz) * (x - cx);
        if ((e0 < 0 || e1 < 0 || e2 < 0) && (e0 > 0 || e1 > 0 || e2 > 0)) continue;
        const k = ((tr + (u >> 4)) << 8) | lv | (u & 15); if (h > high[k]) high[k] = h; if (stands && h > stand[k]) { stand[k] = h; wet[k >> 8] = 1; } } }
  }
}
