    // the rain's station, read from the one source (the machines' homeRoute, by this very place), and two of the
    // three looks that go by the route's own marks (the part's rainLook and seamLook; the third, its shadowLook, is
    // made at the looks below: the proof counts the same)
    const rainStation = homeRoute({ path, length: LEN, B: LEG.B, C: LEG.C, beta: R.beta, rain: PLACES.rain.clone() }).station;
    const RL = rainLook(LEG.B, rainStation), SL = seamLook(LEG.E, LEN);
    await ctx.yield();

    // ---- OUR BOAT at its one station on the route, and our thin layer over the sea (its wake; its shade on the
