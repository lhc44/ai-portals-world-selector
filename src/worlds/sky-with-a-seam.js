    const boat = makeBoat(ctx); scene.add(boat.object);
    await ctx.yield();
    const layers = await makeLayers(ctx, ocean, { path, length: LEN, gapBearing: R.gapBearing, look, shadow: sky.shadow }); scene.add(layers.object);
