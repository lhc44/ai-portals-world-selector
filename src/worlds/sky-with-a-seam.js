    const bay = await makeBay(ctx, { path, length: LEN, look, sky, ocean, mouth: LEG.B, turn: LEG.C, detail: (ctx.quality && ctx.quality.detail) || 1 }); scene.add(bay.object);
    await ctx.yield();

    // ---- THE WEATHER MACHINES over the bay: the cloud boards, the rain rig with its rain and rainbow, the paddles
    const machines = await makeMachines(ctx, { look, path, length: LEN, B: LEG.B, bayTurn: M.bayTurn, C: LEG.C, D: LEG.D, beta: R.beta, rain: PLACES.rain, keep: bay.things, sky, sea: ocean, detail: (ctx.quality && ctx.quality.detail) || 1 }); scene.add(machines.object);
    await ctx.yield();

    // ---- THE GAZE: each look opens and closes by places on the route (metres), one pull each; every target is
    // worked out from u (and the clock) inside the look's own function
