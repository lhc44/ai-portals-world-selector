    await ctx.yield();
    const R = layRoute(), path = makePath(R.pts), LEN = path.length;
    await ctx.yield();
    scene.fog = new THREE.FogExp2(new THREE.Color(PT.haze), LK.fog);
    scene.background = new THREE.Color('#05070c');                 // the dark beyond the shell (seen only through the gap)

    // ---- the sky: the painted shell, its panels, the lamp-sun (the hero part)
    const beamAim = wallPoint(LAMP.looks[look].bearing - 180, 26, 0);
    const sky = await makeSky(ctx, { look, gapBearing: R.gapBearing, routeLength: LEN, beamAim, ...dealt });
    const lamp0 = sky.lampAt(0);                                    // (this sky's own lamp: its creep starts at the phase dealt in makeSky and held in the sky)
    scene.add(sky.object);
    await ctx.yield();

    // ---- the light rig: the dome's fill from above and below, the lamp-sun's key (two lights, never changed)
    const hemi = new THREE.HemisphereLight(new THREE.Color(PT.fill), new THREE.Color(LK.deep).lerp(new THREE.Color(PT.haze), 0.35), LK.hemi);
    const key = new THREE.DirectionalLight(new THREE.Color(LK.lampHex), LK.dir);
    key.position.copy(lamp0); key.target.position.set(0, 0, 0); scene.add(hemi, key, key.target);

    // ---- the sea: the part's own calm tank (nearly glass, mirroring the painted sky; a low regular swell runs out
    // from the paddles' wall, which stands in the north-north-east and north-east, along the wall leg and a
    // little past either end of it; the swell's own bearing is the part's SWELL.from, the middle of the wall LEG:
    // halfway between the leg's two ends' bearings, not the middle of the paddles' wider bank)
