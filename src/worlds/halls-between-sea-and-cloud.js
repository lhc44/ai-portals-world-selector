    // each vessel draws its own choice of makes; no figure stands beside or over its like
    const choice = V.map((v) => { const all = []; for (let k = 0; k < NK; k++) all.push(k); rStat[v.id].shuffle(all); return all.slice(0, 15 + rStat[v.id].int(0, 3)); });
    const rowLast = new Map(), bayHas = new Map(), fill = 0.82 + 0.13 * density, tops = [], boxes = [], holds = [], peds = new Geo(), inSea = [];
