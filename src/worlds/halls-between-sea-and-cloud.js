// The Halls Between Sea and Cloud (from the book named in the header below): a house of marble halls on three levels.
//
// A place that STANDS, made anew from the kind of place the prose gives: hall after hall of stone, statues tier on
// tier, the sea below, cloud above, birds between. No person, no name, no lettering; every statue is this world's
// own carving (working people, mothers, masons, sowers, musicians, sleepers, beasts, giants of our own subjects).
//
// THE LAYOUT, IN METRES (a = metres along the house's one spine; the way runs down -Z; +X is the seaward and window
// hand; the parts' housePlan deals the counts of bays by the seed, so the figures below are the bounds). SIX HALLS,
// and no two share a section, a measure, a floor, a light or a great thing:
//   1 the first hall  a porch (46 long, 36 wide, a lintel course at 12.8 m borne on the window hand by plain piers, on
//     WARM GOLD       the landward hand by plain piers and then by ONE RANK of three or four giants at the porch's
//                     far end: the rank's room begins where the first pier ends, with half a metre of air; each
//                     giant as broad as its share of that room and never under 0.85 of full (11.5 m tall where
//                     three stand; 0.93 of it on a higher plinth where four do; where the seed deals five, four
//                     stand; 0.3 m of air between two and more) and a NAVE 84 to 99 long, 34 wide, its
//                     barrel vault coffered (the only coffers of the house) to 44 m, four tiers of figures to 34 m;
//                     the sun comes in shafts through the high windows of the seaward hand ONLY and lies in bars on
//                     the pavement and the landward wall's foot. The only CHEQUERED pavement of the house. At the
//                     nave's far end, beside the door on the landward hand, a door warden 16 m tall: a ring-headed
//                     staff in the right hand, a nest of sticks in the crook of the left arm.
//   2 the flooded     28 wide, 96 to 109 long: a landing, a stair down 14 m in 38.4, then the flat with its pavement at
//     hall            -14 and the sea STANDING at -9: the lowest tier's figures stand in it to the waist and are
//     SEA GREEN       MIRRORED in it; the water's light lies as a slow net on the walls, the undersides and the
//                     figures, strong by the water and fainter with the height to the vault, and its green falls off with
//                     the height over the water, so the upper tiers and the vault stand greyer and dimmer and the
//                     figures white against them; the air is thin and the far door stands bright; weed and shells
//                     on the stone to the tide's mark. Plain worn flags. A colossus of 17 m wades on the seaward hand, both
//                     hands held out over the water. Its far door stands half in the sea.
//   3 the great       a hall of its own 84 wide and 72 long, the sea standing in it to either hand of a stair 28 wide
//     stair           that climbs out of the water in three flights with two landings; over it a cove and a round
//     WHITE           lantern 32 m across with a ring of twelve windows. THE WHITE HALL: its stone is white marble,
//                     a cool day fills it and the lantern's own white lies in twelve spokes, a wheel, on the treads,
//                     the terrace and up the walls they meet. On the top blocks of the stair's cheeks sit a pair of
//                     giants of dark bronze, 13 to 14 m as they sit: a boatman with an upright oar (to 17.7 m) and a
//                     nest in his lap, and one who holds a boat with mast and sail on the knees, a nest in its bow.
//                     THE WALL THAT FACES THE STAIR, over the terrace: three storeys of niches to its cornice, in
//                     its middle a great door 16 wide and 21 high on the next hall's blue, and in two great recesses,
//                     where a spoke of the wheel meets the wall to either hand, two more bronze colossi 15.6 m
//                     high on their plinths: one behind an anchor, one poised to dive. One figure in four is bronze.
//   4 the hall of     100 long, 30 wide, 36 high, a ribbed vault: its whole seaward side is eight tall open doors on
//     the sea doors   the sea (8.4 wide, 15.6 high), each with a wave on a round of its own on the world clock (no two
//     SEA BLUE        doors share a period, 5 to 8 s; a sheet never stands, it runs in and at once draws back). The
//                     pavement is dark and wet and gives back the doors' sky FLAG BY FLAG (the higher flags dry, the
//                     film rippled near the doors, the image in the sky's own colour and fading with the angle).
//                     THE LANDWARD WALL IS THIS HALL'S OWN: stepped buttresses at the bay lines and an arcade of
//                     archivolts about the lowest niches. Outside: a stair down to the open sea.
//   5 the cloud hall  a second stair up 18 m in 54, then the upper hall (pavement at 18, 28 wide, five tiers), its
//     PEARL, GOLD     vault BROKEN OPEN along its length from the fifth bay on (a rib WHOLE from pier to pier, a short
//     BEAMS           tapered STUB on its springing, or gone, by the crown's stream; every springing on an impost and
//                     a corbel; no piece of a rib without its springing). ITS WALLS ARE ITS OWN: engaged round
//                     columns storey over storey. Cloud lies in it as LOW MIST: six level strata between 10.5 and 21.2 m over the
//                     pavement (the upper tiers' height) and a deck over the walls' tops, drifting on the world
//                     clock; gold falls through the open crown on stone and mist. Veined peach slabs. Where the
//                     stair looks, a colossus of BLACK STONE, 17 m, holds a nest before the breast and stands out of
//                     the mist; one figure in four here is black stone (never a PERSON in the niches next to
//                     a door on the lowest two tiers: one dealt black there stands white). Further on the landward wall has fallen
//                     over three bays to stumps 0.8 to 3.6 m over the pavement; its two broken ends are ragged,
//                     course by course, through the wall's whole depth, and squared stones of it lie at its foot
//                     (nothing leans): the hall stands open to a sea of cloud 9 m
//                     under its pavement and to far halls of the house, the evening's sun coming in over the fall.
//   6 the last hall   90 long, 30 wide, its vault fallen, under the moon and the dusk (it keeps its own evening under
//     MOON BLUE,      every hour): the evening hand's wall stands 11.5 to 17.5 m with two breaches, the other 19 to
//     DUSK BAND       28.5 m; figures in the niches of both walls but for the last 24 m; a FALLEN GIANT of 18 m lies
//                     in pieces along the evening wall from 9 to 13 m inside the door (feet on their plinth, an arm,
//                     the body's drum, a hand, the head); rubble in ten to sixteen heaps (one under each breach; the
//                     others' drift ends 8 m before the end wall); worn flags, drifted sand, standing pools (uneven,
//                     by the flags' hollows; they mirror the sky and the wall). THE MOON'S LIGHT lies in a lane down
//                     the flags, and across it the shadows of the end piers and of the arch's haunches and the
//                     stepped shadow of the SEAWARD wall, bay by bay (the moon stands to the seaward hand);
//                     stones of the fallen vault lie strewn 6 m and more off the axis over the last 26 m (none in
//                     the ring's bay), dry grass in the joints; motes in the air of the whole hall and the evening's
//                     own, dusk gold, thick in the shafts of the two breaches and before the doorway, thinner with
//                     the distance from each; the rooks before the doorway stand only where a whole body has room. Beyond the
//                     breaches and the broken doorway the house goes on as far halls, rank behind rank, paled by the
//                     air. The ring (6.2 m radius) stands in the doorway, whose arch is broken; no figure stands at it.
//   THE ROUTE         a straight spine, the eye about 7 m over a pavement and 2.8 m over the flooded hall's highest
//                     swell, every great door on its axis; the knots are places of the plan (housePlan).
//
// WHAT IS DRIVEN BY WHAT. There is NO PACING (nothing is driven by the metres flown) and NO COMPANION.
//   By a place of the route: the film's pace and the pulls of the gaze (both between places of the plan), and the
//     ENGINE'S OWN reveal of the ring by the metres that remain (portal.revealDistance, 300 m: the site's own law,
//     the same in every world). Nothing else of this world: update() reads no u.
//   By place (standing, the same for every visitor at every moment): ONE LIGHT TO A HALL with its source (the high
//     windows, the water, the lantern, the sea doors, the open crown, the moon and the dusk), its shade, its air and
//     its stone, each giving way to the next inside the thickness of the wall between two halls; the bars of
//     daylight; the lantern's wheel; the dark of hollows; the figures' stone (white marble everywhere; bronze or
//     black by the stone's stream in two halls); the far tiers carved in fewer planes (the lowest tier fine, every
//     other tier plain: by the tier a figure stands in, never by the eye); backs against the wall not carved.
//   By the world clock (habits, right at any phase): each seaward door's wave, the swell, the water's net of light,
//     spray, weed afloat, crabs, birds on closed rounds (gulls, rooks, sparrows, one great white sea bird, three high
//     flocks, to each giant's nest two rooks that come to it once a round, or fewer where the rule of the place
//     refuses every try of a rook's round), the perched birds of the sea doors that
//     step out and lift with their door's wave, the drift of the mist and of the rifts of gold in it, the shade of
//     passing cloud (on the moon's lane too), dust, the motes' drift, the moon's glitter on the pools, the stir of
//     the dry grass, the perched rooks' shift of weight and preening, the far storm, the ring's light, stars.
//   By the eye: ten things, and nothing else. (1) The far air: a point's veil is the fog's law over the true
//     distance, its depth and colour the mean of the point's place and the eye's place on the spine (eyeFog, set in
//     update from the eye's place alone); the far halls' paling is the same kind of law. (2) The sky's dome is
//     carried with the eye; what it shows is by direction and the clock. (3) The MEDIA (beams, dust, mist, snow,
//     motes) keep one near law, 0.6 to 2.5 m of the lens; points are drawn at their true size up to a cap (dust and
//     motes 12 px, snow 10 px, spray 64 px). (4) A detail's fade: the stone's finest grain fades between 5 and 34 m
//     of the lens and a joint of stone (the walls' ashlar joint, the cloud hall's slab joint) is drawn as wide as
//     its size in the picture allows. (5) MIRROR OPTICS: glints
//     and the reflections of pavements, pools and the sea are by the eye's direction, as a mirror's are. (6) THE
//     MIST: a level stratum is as thick to the eye as the slant of the sight line through it (1 - exp(-depth /
//     |sine of the sight's pitch|)): a medium's law, the same from anywhere. (7) THE IMAGES IN THE STANDING SEA: each
//     mirrored point is drawn where the sight line to its image meets the water (a mirror's law), dimmer with its
//     height over the water. (8) THE DISTANCE HAZE OF THE TWO SEAS: the sea of cloud pales into the evening's far
//     air and the open sea beyond the doors into its hall's air, each by the air's law over the true distance from
//     the eye (as the far air of (1)). (9) THE NEAR FADE ON THE IMAGES IN THE SEA: an image in the standing sea
//     fades between 0.6 and 2.5 m of the lens, the media's own near law. (10) A LEVEL STRATUM OF MIST SEEN EDGE ON
//     thins out (it has no thickness to show from its own level: by the sight's pitch, gone under 0.6 degrees and
//     whole from 6; the deck over the walls' tops keeps its body). BODIES (birds, water, spray, statues) keep off
//     the line by place.
//   By the seed (once, for the whole visit): the counts of bays, the makes of the statues, the doors' periods, the
//     hour (the last hall keeps its own evening under every hour), the rare snow.
//   THE STREAMS (one to a thing, taken by name): layout, doors, gap, gapbay, crown, breach, hour, make<k>; a stream
//     to a hall for statues, stature, stone, perch and life ('statues:nave' and so on); a stream to a nest for its
//     rooks ('nestbirds:nave:0', 'nestbirds:stair:0', 'nestbirds:stair:1'); great, lintel,
//     rooks, crabs, wrack, weed, tide, entry, giants, nests, nest, colossi, wader, fallen, endwall, blocks, ribs,
//     fragments, far, beyond, ranks, storm, dust, mist, snow, motes; rookroom (the new places of the doorway's
//     rooks whose first place has no room for the body), strewn (the fallen vault's stones of the last hall's end),
//     grass (its dry grass), motesend (the evening's motes at its breaches and its doorway); gapstone (the broken
//     ends of the cloud hall's fallen wall, the stones left on its stumps and fallen at its foot).
