// NIGHT SCRATCHED WHITE (scratched-kalahari)
// A Kalahari winter night on scratchboard. Every surface is solid black and earns white strokes. We fly as a
// spotted eagle-owl down a dune street to a koppie of quiver trees, and the rising moon scratches a new line onto
