// The barn owl, facing +Z, built to be seen from in front and below as it flares toward us: a white body and
// underwing coverts, seven primaries and five secondaries a side as separate barred strokes, a fanned tail,
// dangling legs, and a head turned down by `tip` so that the heart-shaped face stays level while the body is
// pitched nose-up. Wings are flapped by the creature shader (bone kind 5).
function buildBarnOwl(seed, tip) {
  const S = new Cre(); S.seed = seed;
  const L = 0.36, bw = 0.085, hr = 0.115, s2 = 0.6, body = () => [1, 3];
  loft(S, [[0, 0, -L * 0.5, bw * 0.45, 0.012], [0, 0, -L * 0.3, bw * 0.75, bw * 0.55], [0, 0, 0, bw, bw * 0.95], [0, 0.01, L * 0.2, bw * 0.95, bw * 0.9],
    [0, 0.03, L * 0.34, hr * 0.75, hr * 0.75], [0, 0.03, L * 0.4, 0.01, 0.01]], 8, body);
  for (const sd of [-1, 1]) loft(S, [[sd * 0.035, -0.05, 0.0, 0.016, 0.016], [sd * 0.04, -0.12, 0.05, 0.012, 0.012], [sd * 0.042, -0.175, 0.1, 0.014, 0.01], [sd * 0.042, -0.18, 0.13, 0.004, 0.004]], 4, body);
  // head and face
  const fy = -Math.sin(tip), fz = Math.cos(tip), uy = Math.cos(tip), uz = Math.sin(tip), hc = [0, 0.055, L * 0.4];
  const at = (k) => [0, hc[1] + fy * hr * k, hc[2] + fz * hr * k];
  loft(S, [[...at(-0.95), 0.01, 0.01], [...at(-0.6), hr * 0.8, hr * 0.8], [...at(0), hr, hr], [...at(0.4), hr * 0.92, hr * 0.92], [...at(0.62), hr * 0.5, hr * 0.5]], 10, body);
  {
    const R = hr * 1.3, c = at(0.66), b = S.count;
    for (const [qx, qy] of [[-1, -1], [1, -1], [1, 1], [-1, 1]]) S.v(c[0] + qx * R, c[1] + qy * R * uy, c[2] + qy * R * uz, 0, fy, fz, qx, qy, 0, 0, 1, 7, 0, seed);
    S.tri(b, b + 1, b + 2); S.tri(b, b + 2, b + 3);
  }
  // one feather: a flat stroke from root along dir (in the XZ plane), rounded at the tip
  let fi = 0;
  const feather = (rx, ry, rz, dx, dz, len, hw, flap) => {
    const b = S.count, NS = 4, ax = dz, az = -dx; fi++;
    for (let k = 0; k <= NS; k++) {
      const v = k / NS, w = hw * Math.min(1, 0.5 + v * 2.5) * Math.sqrt(Math.max(0.03, 1 - v * v * v * v)), cx = rx + dx * len * v, cz = rz + dz * len * v;
      const cy = ry - 0.03 * v * v + (flap ? 0.22 * Math.max(0, Math.abs(cx) - 0.05) : 0);      // wings held in a shallow V
      for (const e of [-1, 1]) {
        const x = cx + ax * w * e, z = cz + az * w * e;
        S.B = flap ? [0.05, 0.03, 0, 5] : [0, 0, 0, 0]; S.C = [0, 0, 0, Math.min(1, Math.abs(x) / s2)];
        S.v(x, cy, z, 0, 1, 0, e, v, fi, 0, 1, 5, 0, seed);
      }
      if (k < NS) { const a = b + k * 2; S.tri(a, a + 1, a + 2); S.tri(a + 1, a + 3, a + 2); }
    }
  };
  for (const sd of [-1, 1]) {
    // the arm and its coverts: a thin slab from shoulder to wrist to hand
    S.B = [0.05, 0.03, 0, 5];
    loft(S, [[0.03, 0.03, 0.035, 0.085, 0.03], [0.15, 0.04, 0.065, 0.075, 0.024], [0.27, 0.04, 0.085, 0.06, 0.018], [0.38, 0.035, 0.075, 0.042, 0.012], [0.47, 0.03, 0.05, 0.02, 0.008]].map((r) => [sd * r[0], r[1] + 0.22 * Math.max(0, r[0] - 0.05), r[2], r[3], r[4]]),
      8, body, { sideZ: true, rings: true, girth: 0.05, ring: (i, p) => { S.C = [0, 0, 0, Math.abs(p[0]) / s2]; } });
    for (let i = 0; i < 5; i++) feather(sd * lerp(0.065, 0.25, i / 4), 0.03, 0.0, sd * 0.06 * (i / 4), -1, 0.3 + 0.02 * i, 0.03, true);              // secondaries
    for (let j = 0; j < 7; j++) {                                                                                                                  // primaries
      const th = lerp(0.3, 1.5, j / 6), len = 0.36 + 0.07 * Math.sin(Math.PI * Math.pow(j / 6, 0.8));
      feather(sd * (0.285 + 0.02 * j), 0.032, 0.03 + 0.008 * j, sd * Math.sin(th), -Math.cos(th), len, 0.032, true);
    }
  }
  for (let k = 0; k < 5; k++) { const th = (k - 2) * 0.3; feather(Math.sin(th) * 0.02, 0, -L * 0.42, Math.sin(th), -Math.cos(th), 0.2, 0.028, false); }
  S.B = [0, 0, 0, 0]; S.C = [0, 0, 0, 0];
  return { geo: S.build(), tris: S.i.length / 3, eye: [0, 0, 0], piv: [0, 0] };
}

