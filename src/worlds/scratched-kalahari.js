//                 of the herd's first mark, on a seeded side 2.8 to 5 m from the line, each turned its own way and
//                 hopping a round of its own, a pair of eyes before a body; two bound across our front under the
//                 second camelthorn (brief: u 0.16, trunk 12 m to the right).
//   Ostriches     two cocks stand in the trail and stride off to either side (kept from the live version).
//   Foxes         four bat-eared foxes listen on our left, strung along the street from abreast of the route's point
