// The Cape porcupine: a low body, and its quills as single long ruled strokes hinged at the root. Raised, they are a
// fan: a hundred and thirty quills radiating up, out and back from the hind half of the body, the longest over the
// rump, each one clear of the next, banded black and white by the quill shader. They are built lying back along the
// body, each turned down about its root by exactly the angle its own hinge raises it through (RAISE), so that with
// the hinge at RAISE every quill stands on its ray of the fan, and with the hinge low the fan is folded.
const QUILL_RAISE = 1.16;
function buildPorcupine(rng, seed) {
  const S = new Cre(); S.seed = seed;
  loft(S, [[0, 0.15, -0.42, 0.02, 0.02], [0, 0.2, -0.34, 0.15, 0.14], [0, 0.25, -0.1, 0.2, 0.2], [0, 0.235, 0.15, 0.17, 0.18], [0, 0.2, 0.32, 0.1, 0.11],
    [0, 0.17, 0.4, 0.075, 0.075], [0, 0.15, 0.47, 0.04, 0.04], [0, 0.145, 0.5, 0.01, 0.01]], 10, (t, c) => (c < -0.6 ? [0, 0.3] : t > 0.72 ? [0.9, 2.4] : [0.45, 1.9]));
  for (const sd of [-1, 1]) for (const z of [-0.2, 0.2]) loft(S, [[sd * 0.11, 0.16, z, 0.05, 0.06], [sd * 0.12, 0.05, z + 0.01, 0.035, 0.04], [sd * 0.12, 0, z + 0.03, 0.035, 0.05]], 5, () => [0.3, 1.6]);
  const Q = new Ribs(), queue = [], fed = () => queue.shift();
  const N = 130;
  for (let i = 0; i < N; i++) {
    // its ray: al round the body (0 is straight up), be back from the upright (0 square to the body, 1.2 nearly along it)
    const al = (((i * 0.61803) % 1) * 2 - 1) * 1.5, be = 0.12 + 1.1 * Math.pow((i + 0.5) / N, 0.8), ph = rng();
    const tx = Math.sin(al) * Math.cos(be), ty = Math.cos(al) * Math.cos(be), tz = -Math.sin(be);
    const z = lerp(0.02, -0.34, be / 1.22), rr = 0.19 * (1 - 0.5 * Math.abs(z + 0.08) ** 1.5 * 4) * 0.9, x = Math.sin(al) * rr, y = 0.235 + Math.cos(al) * rr * 0.95;
    const len = (0.66 - 0.2 * Math.abs(al) / 1.5 - 0.12 * Math.abs(be - 0.7)) * rng.range(0.88, 1.12);
    const a = -QUILL_RAISE * (0.75 + 0.5 * ph), c = Math.cos(a), sn = Math.sin(a), dy = ty * c - tz * sn, dz = ty * sn + tz * c;      // the same ray, folded back about the root
    queue.push(rng(), rng(), ph);
    Q.lance(x, y, z, x + tx * len, y + dy * len, z + dz * len, 0, 0, 0, 0.034, Math.sin(al) * 0.6, 0.8, -0.2, 1, 0.02, fed, 0.3);
  }
  for (let i = 0; i < 26; i++) {                 // the long white nape crest
    const z = rng.range(0.16, 0.4), x = rng.range(-0.05, 0.05), len = rng.range(0.25, 0.4);
    Q.lance(x, 0.36 - (z - 0.16) * 0.5, z, x * 3, 0.36 - (z - 0.16) * 0.5 + len * 0.45, z - len * 0.9, 0, 0, 0, 0.012, 0, 1, 0, 1, 0.05, rng, 0.4);
  }
  return { geo: S.build(), quills: Q.build(), tris: S.i.length / 3 + Q.i.length / 3, eye: [0.06, 0.2, 0.43] };
}

