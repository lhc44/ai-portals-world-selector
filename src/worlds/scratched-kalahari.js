//                 way (a seeded heading, any way round): eyes from far off, bodies and ears drawn in within 46 to
//                 34 m, heads down to the sand and cocked; only the head turns to us, and looks up at us as we
//                 come within 26 to 13 m.
//   Porcupine     7 m to the left of the route's point at u 0.22 (the brief's beat), its fan to its foe. The foe
//                 circles the porcupine: it paces an arc about the porcupine's own mark, on the side away from the
//                 street's line, 2.6 m from the mark and a quarter turn either way from straight out (the middle of its
//                 beat is 9.6 m from the line), by the clock at a walk, its legs stepping by the metres it has
//                 walked, turning at each end by way of facing the fan; it does not know where we are. The fan
