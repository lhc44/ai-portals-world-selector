//                 with one slow beat in 32 m, held while an animal stands within 16 m ahead. Both wings alike.
//   The barn owl  is in the air beside us from the first frame, on the nest tree's side: it rows across the trail in
//                 front of us and on down the street, a little faster than we fly, drawing away for the whole opening.
