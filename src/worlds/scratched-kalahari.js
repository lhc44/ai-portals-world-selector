// Creatures: lofted bodies with hatch coordinates, animated in the vertex shader.
//   aBone  = (pivot y, pivot z, walk phase offset, kind)   kind 0 body, 1 leg, 2 neck+head, 3 tail, 4 ear, 5 wing
//   aBone2 = (knee y, knee z, below the knee +1 (folds back) or below the hock -1 (folds forward), gallop phase offset | weight along tail, ear, wing)
//   aAnim  = per instance (phase in cycles, gait: -1 standing .. 0 walk .. 1 gallop | wing amplitude, head yaw, seed)
//   aAnim2 = per instance (pronk pose 0..1, dorsal fan open 0..1, head lowered to graze 0..1, unused); bone kind 6 is the fan
const CRE_VERT = /* glsl */`
attribute vec4 aHatch, aSurf, aBone, aBone2, aAnim, aAnim2;
varying vec4 vHatch; varying vec4 vSurf; varying vec3 vWPos; varying vec3 vWN; varying float vLY;
uniform mat4 uInvHero; uniform float uTime, uPx, uArch; uniform vec2 uPiv, uView; uniform vec4 uTilt, uTiltX; uniform vec3 uHill;
#include <common>
#include <fog_pars_vertex>
vec2 rot2(vec2 v, float a){ float c = cos(a), s = sin(a); return vec2(v.x * c - v.y * s, v.x * s + v.y * c); }
void main(){
  vHatch = aHatch; vSurf = aSurf;
  vec3 p = position; vec3 n = normal;
  float ph = aAnim.x * 6.2831853, sd = aAnim.w;
  float g = clamp(aAnim.y, 0., 1.), amp = clamp(aAnim.y + 1., 0., 1.);
  float kind = aBone.w, pk = aAnim2.x;
  if (kind > 5.5) {                               // the dorsal fan: shut in its fold along the spine, standing open in the leap
    p.y = aBone.x + (p.y - aBone.x) * aAnim2.y; p.x *= mix(.3, 1., aAnim2.y);
  } else if (kind > 4.5) {                        // wing: flap about the body axis at the shoulder
    float sx = position.x < 0. ? -1. : 1., w = aBone2.w;
    float a = aAnim.y * sin(ph - w * 1.1) * (.3 + .7 * w) + .1;
    vec2 q = rot2(vec2(abs(p.x) - aBone.x, p.y - aBone.y), a);
    p.x = sx * (q.x + aBone.x); p.y = q.y + aBone.y;
    amp = 0.;
  } else if (kind > 3.5 || (kind > 1.5 && kind < 2.5)) {   // neck and head (and ears)
    if (kind > 3.5) {
      float sx = position.x < 0. ? -1. : 1.;
      float fl = sin(uTime * (2.3 + sd * 2.) + sd * 40. + sx * 1.7) * smoothstep(.2, .9, sin(uTime * .9 + sd * 20. + sx * 2.));
      p.x += aBone2.w * .05 * fl; p.z -= aBone2.w * .04 * fl;
    }
    float idle = (1. - g) * .34 * smoothstep(.55, 1., sin(uTime * .45 + sd * 37.)) * (1. - smoothstep(.3, .9, abs(aAnim.z)));
    float nod = .07 * sin(ph * 2. + 1.) * (.4 + g) * amp + idle * (1. - aAnim2.z) + 1.5 * aAnim2.z * (1. - pk) + .5 * pk;      // grazing; held low in the leap
    p.yz = rot2(p.yz - aBone.xy, nod) + aBone.xy;
    vec2 q = rot2(vec2(p.x, p.z - aBone.y), aAnim.z); p.x = q.x; p.z = q.y + aBone.y;
    n.xz = rot2(n.xz, aAnim.z);
  } else if (kind > 2.5) {                        // tail: swishes at rest, streams out at the gallop
    float w = aBone2.w;
    p.x += w * (.11 * sin(uTime * 2.1 + sd * 30.) * (1. - g) + .05 * sin(ph * 2.) * g);
    p.yz = rot2(p.yz - aBone.xy, (g * 1.05 + .1 * sin(ph + 1.) * amp) * w) + aBone.xy;
  } else if (kind > .5) {                         // leg: swing at the hip, fold at the knee on the way forward
    float off = mix(aBone.z, aBone2.w, g) * 6.2831853;
    float A = mix(.4, .78, g) * amp * (1. - pk);      // in the pronk all four legs hang stiff and straight, the four hooves bunched together under the belly
    if (abs(aBone2.z) > .5) p.yz = rot2(p.yz - aBone2.xy, sign(aBone2.z) * amp * (1. - pk) * mix(.55, 1.15, g) * max(0., cos(ph + off))) + aBone2.xy;
    p.yz = rot2(p.yz - aBone.xy, -A * sin(ph + off) + pk * (aBone.y > 0. ? .46 : -.4)) + aBone.xy;
  }
  p.yz = rot2(p.yz - uPiv, amp * g * .06 * cos(ph + .3)) + uPiv;
  p.y += amp * mix(.012 * sin(ph * 2.), .07 * sin(ph + .8), g);
  p.y -= pk * uArch * min(p.z * p.z, .2);         // the arched back of the pronk: rump and breast drop, and the neck with them
  #ifdef USE_INSTANCING
  mat4 mm = modelMatrix * instanceMatrix;
  #else
  mat4 mm = modelMatrix;
  #endif
  vec4 wp = mm * vec4(p, 1.);
  vWN = mat3(mm) * n;
  if (aSurf.z > .0005) {                          // horns: never thinner than a bold stroke (aSurf.z = radius in metres)
    float cw = max((projectionMatrix * viewMatrix * wp).w, .05);
    float need = mix(2.2, .8, smoothstep(11., 30., cw)) * uPx * cw / (projectionMatrix[1][1] * uView.y * .5);
    wp.xyz += vWN / max(length(vWN), 1e-5) * max(0., need - aSurf.z * length(mm[0].xyz));
  }
  vec3 lp = (uInvHero * wp).xyz;
  vWPos = wp.xyz; vLY = lp.y + uTilt.x * (clamp(lp.z, uTilt.z, uTilt.w) - uTilt.y) + smoothstep(uTiltX.w, uTiltX.w + 16., lp.z) * (uTiltX.x * (lp.z - uTiltX.y) + uTiltX.z * lp.x) + (1. - smoothstep(uTiltX.w, uTiltX.w + 16., lp.z)) * (uHill.x * lp.x + uHill.y * (lp.z - 100.) + uHill.z);
  vec4 mvPosition = viewMatrix * wp;
  gl_Position = projectionMatrix * mvPosition;
  #include <fog_vertex>
}`;

// The street and the dunes: the scratch shade, with patches of bare sand where the animals stand (uBare = x, z,
// radius; each patch has a ragged edge and feathers into the strokes round it, keeping a few stray ones inside).
const DUNE_FRAG = /* glsl */`
varying vec4 vHatch; varying vec4 vSurf; varying vec3 vWPos; varying vec3 vWN; varying float vLY;
uniform float uS0, uLen, uNearTone, uBareTo, uMoonCap; uniform vec4 uBare[48]; uniform vec4 uTrail; uniform vec4 uRip;
#include <common>
#include <fog_pars_fragment>
${SCRATCH_GLSL}
void main(){
  vec3 N = vWN / max(length(vWN), 1e-5);
  vec3 Vv = cameraPosition - vWPos; vec3 V = Vv / max(length(Vv), 1e-5);
  float keep = 1., keepR = 1.;      // keepR: the ripples stop closer in, a step from each animal
  for (int i = 0; i < 48; i++) {
    vec2 d = vWPos.xz - uBare[i].xy; float r = max(uBare[i].z, .01), fi = float(i);
    float wob = 1. + .3 * sin(d.x * 1.9 + fi * 1.7) * sin(d.y * 1.4 + fi * 2.9) + .16 * sin(d.x * .7 - d.y * 1.1 + fi);
    keep *= smoothstep(r * .3, r * 1.7, length(d) * wob);
    keepR *= smoothstep(r * .3, r * .62, length(d) * wob);
  }
  // What stipple the street has is gathered into the game trail that wanders down it to the
  // hill (uTrail = phase, phase, tone, side trail's tone) and a fainter one that joins it from the right.
  float tz = vWPos.z, t1 = vWPos.x + 1.3 - 2.3 * sin(tz * .027 + uTrail.x) - 1. * sin(tz * .071 + uTrail.y);
  float t2 = vWPos.x - 5. - .17 * (tz - 262.) - 1.4 * sin(tz * .05 + uTrail.y);
  float wt = 1. + .35 * sin(tz * .41 + vWPos.x * .9) * sin(tz * .13);
  float trail = max(uTrail.z * (1. - smoothstep(.3 * wt, 1.05 * wt, abs(t1))), uTrail.w * (1. - smoothstep(.25 * wt, .8 * wt, abs(t2))) * smoothstep(262., 280., tz));
  trail *= smoothstep(118., 150., tz) * (1. - smoothstep(.2, 1.2, vWPos.y));
  vec4 sf = vSurf; sf.y = max(sf.y * (1. + uNearTone * (1. - smoothstep(5., 30., length(Vv)))), trail) * mix(uBareTo, 1., keep);      // the trail keeps under half its strokes at any distance: stipple, never a screen
  // where the moon has reached the flat sand it earns about three strokes in five, close to the eye: more than starlight gave it, never a ruled screen
  float lit = smoothstep(0., .5, (vLY - uPlane) / uSoft) * uMoonLvl;
  sf.y = mix(sf.y, min(sf.y, uMoonCap), lit);
  // The flat sand's strokes run down the street with the wind (short ticks near the eye, dots further off); on the
  // dunes they are the contours of the dune. The two meet in a soft bend at the dune's foot.
  float fl = 1. - smoothstep(.15, 1.3, vWPos.y), ndv = dot(N, V);
  vec2 fh = kFlatHatch(vWPos.xz);
  vec4 hatch = vHatch; hatch.xy = mix(vHatch.xy, fh, fl);
  float ink = kScratch(hatch, sf, vWPos, N, N, vLY, uS0, uLen) * smoothstep(.08, .3, ndv);
  // wind ripples close to the eye: broken ticks all over the flat sand, closing into loose patches of whole ripples;
  // none in the animals' bare patches or on the trail
  float rip = kRipple(vWPos.xz, mix(uRip.x, uRip.y, lit) * (.48 + .52 * kRipMask(vWPos.xz, uTrail.xy)) * fl * keepR * mix(1., smoothstep(.8, 2.2, abs(t1)), smoothstep(118., 150., tz)));
  ink = max(ink, rip * (1. - smoothstep(uRip.z * .55, uRip.z, length(Vv))) * smoothstep(.1, .3, ndv) * (1. - kOwlShadow(vWPos)));
  // A dune's crest against the stars is drawn with broken strokes that taper at both ends and follow its form
  // (one unbroken contour read as a wire across the sky): each 26 m of crest holds one stroke, of its own length, or none.
  float gw = max(length(vec2(dFdx(ndv), dFdy(ndv))), 1e-5);
  float ca = vWPos.z / 26. + .8 * sin(vWPos.z * .011 + vWPos.x * .02), cc = floor(ca), dn = floor(vWPos.x / 250. + .5);
  float cl = .45 + .5 * kh(vec2(cc * 1.7 + dn, 2.1)), ct = (ca - cc) / cl;
  float ctp = smoothstep(0., .25, ct) * (1. - smoothstep(.5, 1., ct)) * step(kh(vec2(cc, 5.3 + dn)), .74);
  float rim = (1. - smoothstep(uPx * 1.4 * ctp, uPx * 1.4 * ctp + 1.3, ndv / gw)) * smoothstep(.1, .3, ctp);
  float nm = dot(N, uMoonDir), rev = clamp((vLY - uPlane) / uSoft, 0., 1.);
  float gate = max(uStar * smoothstep(.15, .45, N.y), smoothstep(-.02, .16, nm) * smoothstep(0., .5, rev) * uMoonLvl) * (1. - fl) * uRip.w;
  ink = max(ink, rim * gate);
  gl_FragColor = vec4(vec3(uInk * clamp(ink, 0., 1.)), 1.);
  #include <fog_fragment>
}`;

