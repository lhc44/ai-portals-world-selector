  const yardY = (x) => yc + 0.05 * x, hs = half - 0.4, nb = 7, bw = 2 * hs / nb, linen = WOOD.linen.clone().multiplyScalar(0.94);
  limb(B, [-half, yardY(-half), z + 0.22], [half, yardY(half), z + 0.22], 0.085, 0.085, 5, WOOD.spar, 0);
