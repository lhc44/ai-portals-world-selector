// ---------------------------------------------------------------- reefs awash and their spray
// Low dark rocks at the places layPlace dealt; the kit's sea shoals and whitens round them (its depth map), and spray
// goes up on their windward side as each crest of the swell comes down on them from the north: a medium, by the clock.
async function buildReefs(B, P, seed, noise, yieldNow) {
  const rr = makeRng(hashSeed('pharos-reefshape:' + seed)), C = COL.rock;
  const lumpAt = (cx, cz, r, h) => {
    const seg = 9, rows = [[1.0, -1.2], [0.86, 0.05], [0.55, 0.62], [0.2, 0.95]], ring = [];
    for (const [fr, fy] of rows) { const o = []; for (let i = 0; i < seg; i++) { const a = (i / seg) * 6.2832, w = 0.72 + 0.5 * (0.5 + 0.5 * noise.n2(cx * 0.37 + Math.cos(a) * 1.7, cz * 0.37 + Math.sin(a) * 1.7 + fy));
      o.push([cx + Math.cos(a) * r * fr * w, fy < 0 ? fy : fy * h * (0.7 + 0.5 * w), cz + Math.sin(a) * r * fr * w]); } ring.push(o); }
    const ref = [cx, -6, cz];
    for (let j = 0; j < rows.length - 1; j++) for (let i = 0; i < seg; i++) { const k = (i + 1) % seg; B.quad(ring[j][i], ring[j][k], ring[j + 1][k], ring[j + 1][i], C, 3, ref); }
    const top = ring[rows.length - 1], tc = [cx, h * 1.05, cz]; for (let i = 0; i < seg; i++) B.tri(top[i], top[(i + 1) % seg], tc, C, 3, ref);
  };
  let nq = 0;
  for (const q of P.reefs) {
    if (++nq % 8 === 0) await yieldNow();
    lumpAt(q.x, q.z, q.r, q.h);
    const n = rr.int(1, 3);
    for (let i = 0; i < n; i++) { const a = rr.range(0, 6.28), d = q.r * rr.range(0.45, 0.8), r2 = q.r * rr.range(0.3, 0.5); lumpAt(q.x + Math.cos(a) * d, q.z + Math.sin(a) * d, r2, q.h * rr.range(0.5, 1.1)); }
  }
}
// spray: upright sheets of torn white that turn to face the eye, one or two to a reef and a row along the windward
// walls of the rock; each goes up when a crest of the DRAWN swell reaches its place (the kit's first wave, read from the
// ocean's own uniforms, plus a small lag dealt to each sheet) and falls back. A sheet rises where the swell breaks and
// nowhere else: on the north side of a reef (the side the swell comes down on) and in rows along the rock's north
// wall, the tongue's north wall and the rock's east wall north of the tongue (layPlace, P.spray). The reefs' grounds
// and those walls lie off the flown water: the nearest sheet rises 11.6 m from the flown line (the movers' count,
// forty visits).
function buildSpray(U, OU, P, detail) {
  const pos = [], uv = [], dat = [], idx = [];
  for (const e of P.spray) {
    // on a slow machine the second sheets are left out
    if (e.second && detail < 0.6) continue;
    const b = pos.length / 3;
    for (const [u, v] of [[-1, 0], [1, 0], [1, 1], [-1, 1]]) { pos.push(e.x, 0, e.z); uv.push(u, v); dat.push(e.w, e.h, e.ph, e.k); }
    idx.push(b, b + 1, b + 2, b, b + 2, b + 3);
  }
  const g = new THREE.BufferGeometry(); g.setAttribute('position', new THREE.Float32BufferAttribute(pos, 3)); g.setAttribute('uv', new THREE.Float32BufferAttribute(uv, 2));
  g.setAttribute('aD', new THREE.Float32BufferAttribute(dat, 4)); g.setIndex(idx);
  const m = new THREE.ShaderMaterial({
    uniforms: { ...THREE.UniformsUtils.clone(THREE.UniformsLib.fog), uTime: OU.uTime, uWA: OU.uWA, uWB: OU.uWB, uSkyCol: U.uSkyCol, uGlowCol: U.uGlowCol, uSunCol: U.uSunCol },
    transparent: true, depthWrite: false, fog: true,
    vertexShader: /* glsl */`attribute vec4 aD; uniform float uTime; uniform vec4 uWA[18], uWB[18]; varying vec2 vUv; varying vec2 vS;
      #include <fog_pars_vertex>
      void main(){ vUv = uv;
        // where this place stands in the first wave's cycle: 0 as its crest strikes
        float s = fract((uWA[0].w * uTime - uWA[0].z * dot(uWA[0].xy, position.xz) - uWB[0].z) / 6.2831853 + .25 + aD.z);
        float up = sqrt(clamp(s * 2.6, 0., 1.)), hgt = aD.y * (.25 + .75 * up) * (1. - .35 * smoothstep(.45, 1., s));
        vec3 c = position; vec3 side = normalize(vec3(cameraPosition.z - c.z, 0., c.x - cameraPosition.x) + vec3(1e-4, 0., 0.));
        vec3 p = c + side * uv.x * aD.x * (.7 + .5 * up) + vec3(0., uv.y * hgt - .3, 0.);
        vS = vec2(s, aD.w);
        vec4 mvPosition = viewMatrix * vec4(p, 1.); gl_Position = projectionMatrix * mvPosition;
        #include <fog_vertex>
      }`,
    fragmentShader: /* glsl */`uniform vec3 uSkyCol, uGlowCol, uSunCol; varying vec2 vUv; varying vec2 vS;
      #include <fog_pars_fragment>
      float h(vec2 p){ p = fract(p * vec2(123.34, 456.21)); p += dot(p, p + 45.32); return fract(p.x * p.y); }
      float n(vec2 p){ vec2 i = floor(p), f = fract(p); f = f * f * (3. - 2. * f); return mix(mix(h(i), h(i + vec2(1., 0.)), f.x), mix(h(i + vec2(0., 1.)), h(i + vec2(1., 1.)), f.x), f.y); }
      void main(){
        float s = vS.x, x = vUv.x, y = clamp(vUv.y, 0., 1.);
        vec2 q = vec2(x * 3.2 + vS.y, y * 5. - s * 3.5 + vS.y);
        float f = .6 * n(q) + .4 * n(q * 2.7 + 5.);
        // a fan: full at the foot, torn into drops toward the top and as it falls back
        float fan = (1. - x * x) * (1. - x * x) * smoothstep(1., .25, y + .25 * abs(x));
        float a = fan * smoothstep(.25 + .45 * y + .3 * s, .9, f + .45 * (1. - y)) * smoothstep(0., .08, s) * (1. - smoothstep(.5, 1., s)) * smoothstep(0., .06, y);
        vec3 col = vec3(.93, .95, .96) * (uSkyCol + uGlowCol * .7 + uSunCol * .35);
        gl_FragColor = vec4(col, a * .85);
        #include <fog_fragment>
      }`,
  });
  const mesh = new THREE.Mesh(g, m); mesh.name = 'spray'; mesh.renderOrder = 4; mesh.frustumCulled = false;
  return mesh;
}

// ---------------------------------------------------------------- people and the donkey strings (true size, on the world clock)
// One small shader for both: the parts of a figure are marked in aK (1 cloth or hide, tinted per figure; 2 and 3 a
// person's legs; 4 and 5 the arms; 6 and 7 a donkey's diagonal pairs of legs; 8 a load on the shoulder) and swing by
// the figure's own step phase. (r6) A WALKER WALKS: the legs swing from the hip and the shin folds back at the knee
// while its leg comes forward, the arms swing against the legs, the body leans a little into the step and lifts with
// it; about two walkers in five carry a sack on the shoulder (aLoad 1), the others a mantle only. A stander (phase
// 0) stands. aLoad is -1 on a donkey.
function walkerMaterial(U) {
  return new THREE.ShaderMaterial({
    uniforms: { ...THREE.UniformsUtils.clone(THREE.UniformsLib.fog), ...U }, fog: true, side: THREE.DoubleSide,
    vertexShader: /* glsl */`
      attribute vec3 aC, aTint; attribute float aK, aPh, aLoad; varying vec3 vW, vN, vC;
      #include <fog_pars_vertex>
      void main(){
        float k = floor(aK + .5), sw = sin(aPh), walk = step(.5, abs(aPh)), cw = cos(aPh); vec3 p = position, n = normal;
        // the knee: the shin folds back while its leg swings forward
        if ((k == 2. || k == 3.) && p.y < .43) { float kb = .85 * walk * max(0., k == 2. ? -cw : cw); vec2 q0 = vec2(p.y - .42, p.z); p.y = .42 + q0.x * cos(kb) - q0.y * sin(kb); p.z = q0.x * sin(kb) + q0.y * cos(kb); }
        // a walker without a load carries none (the sack folds away into the shoulder)
        if (k == 8.) p = mix(vec3(-.12, 1.42, 0.), p, step(.5, aLoad));
        float ang = k == 2. || k == 6. ? .5 * sw : k == 3. || k == 7. ? -.5 * sw : k == 4. ? -.38 * sw : k == 5. ? .38 * sw : 0.;
        float py = k == 4. || k == 5. ? 1.38 : .82, pz = k == 6. || k == 7. ? sign(p.z) * .42 : 0.;
        float c = cos(ang), s = sin(ang); vec2 q = vec2(p.y - py, p.z - pz);
        p.y = py + q.x * c - q.y * s; p.z = pz + q.x * s + q.y * c;
        // a little lift with every step, and a person leans a little into the walk
        p.y += .025 * abs(sw) * walk;
        if (aLoad > -.5) p.z += .075 * walk * max(p.y - .8, 0.);
        mat4 mm = modelMatrix * instanceMatrix; vec4 wp = mm * vec4(p, 1.); vW = wp.xyz; vN = normalize(mat3(mm) * n);
        vC = k == 1. || k == 6. || k == 7. ? aC * aTint : aC;
        vec4 mvPosition = viewMatrix * wp; gl_Position = projectionMatrix * mvPosition;
        #include <fog_vertex>
      }`,
    fragmentShader: /* glsl */`
      varying vec3 vW, vN, vC;
      ${LIT_PARS}
      #include <fog_pars_fragment>
      void main(){ gl_FragColor = vec4(phLight(vC, normalize(vN + vec3(0., 1e-6, 0.)), vW, 1.), 1.);
        #include <fog_fragment>
      }`,
  });
}
