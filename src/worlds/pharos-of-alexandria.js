// a lofted hull: len, beam, freeboard amidships, sheer rise at bow and stern, keel depth, fullness of the ends
function loftHull(B, o) {
  const NS = o.sections || 14, st = [], hl = o.len / 2;
  for (let i = 0; i <= NS; i++) {
    const s = i / NS, e = 2 * s - 1, hb = Math.max(0.04, (o.beam / 2) * Math.pow(Math.max(0, 1 - Math.pow(Math.abs(e), o.full || 2.4)), 0.6));
    const g = o.free + (e > 0 ? o.riseBow : o.riseStern) * e * e, d = o.keel * (1 - Math.pow(Math.abs(e), 3)), z = e * hl;
    st.push({ z, hb, g, pts: [[0, -d], [hb * 0.62, -d * 0.72], [hb * 0.95, -0.05], [hb * 0.975, g * 0.5], [hb * 0.965, g * 0.82], [hb, g * 0.84], [hb * 0.98, g]] });
  }
  // from the keel up: pitch, pitch, the side's paint, the upper band, the wale's under edge and the wale itself
  const wale = o.wale || WOOD.wale, cols = [WOOD.pitch, WOOD.pitch, o.paint || WOOD.ochre, o.strake || WOOD.oiled, wale, wale];
  for (let i = 0; i < NS; i++) {
    const A = st[i], Bn = st[i + 1], ref = [0, 0.3, (A.z + Bn.z) / 2];
    for (const sx of [1, -1]) for (let j = 0; j < 6; j++) {
      const a = A.pts[j], b = A.pts[j + 1], c = Bn.pts[j + 1], d = Bn.pts[j];
      B.quad([a[0] * sx, a[1], A.z], [b[0] * sx, b[1], A.z], [c[0] * sx, c[1], Bn.z], [d[0] * sx, d[1], Bn.z], cols[j], 0, ref);
    }
    // the deck (or the bottom boards of an open boat)
    const da = Math.min(o.deck, A.g - 0.15), db = Math.min(o.deck, Bn.g - 0.15);
    B.quad([A.hb * 0.9, da, A.z], [-A.hb * 0.9, da, A.z], [-Bn.hb * 0.9, db, Bn.z], [Bn.hb * 0.9, db, Bn.z], WOOD.deck, 0, [0, -3, 0]);
  }
  return st;
}
