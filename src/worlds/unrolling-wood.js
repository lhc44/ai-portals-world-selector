// climb early and high (21 m, above the plane of its tilted disc, so it reads as a spiral and not an edge-on
// band), drop in at its cut end and ride the lane level with the inner wall's top edge 4 m off, rise over the
// wall tops up the west side, swing wide round the high lip 18 m off the face of the disc with every turn, the
// wound heart and the gully below, dive down the east side, and when the heart lets go we are flung out along
// the straightening frond (which stands upright as it straightens and tapers to its tip), 17 m over its top edge and a
// little to its right, so the edge runs away as a line with the leaflet pairs springing open along it in perspective
// and the running roll, leaning back against its run, shows its wound top; then down to the last turn, a ring of whole loops
// at the tip, with the portal in it (one flat sheet of mist white until the next world shows).
//
// STYLE: paper quilling. One stuff (a strip on its edge), seven shapes, nine papers on cream card that is ground
// and sky alike. Everything is drawn with the part's strip program (quillBatch / quillShade); the line is the
// strip's lighter top edge; shadow is a lilac-grey stain on the card; distance is a paler tint. post.flat = 1:
// papers reach the screen as their hex, no tone map, no bloom, no lights, no fog.
//
// VARIATIONS by seed (ctx.vary.hour honoured): HOUR dawn after rain | overcast noon (no glow-through, short
// stains, twice the drops, thick mist) | late day (sun on the other side, far hills in half tint). COLOURWAY the
// five greens | bracken autumn (straw to russet, blue butterflies) | first frost (paler papers, white edges).
// CAST butterflies and lyrebird | mist-white moths and five snails on the king's edge | no birds, twice the fish.
// RARE (ctx.vary.rare): the day the butterflies rise, a cloud of forty scarlet ones coming up out of the side gully
// as we are flung out along the frond.
// THE ROADSIDE WINDS SHUT (polish round): the gully is entered fully unfurled and near crowns and fiddleheads roll
// up into pegs as we pass; only the king springs open, carries us and unrolls to the portal at its tip.
// POLISH ROUND 3 (what the picture gained; nothing was taken away):
// THE SKY HAS ITS OWN PAPER: a flat tinted sheet (duck-egg, greyer at noon, lilac late; cooler in frost and bracken) behind
// the cream card, six great cloud scrolls of mist-white strip standing proud of it, the card carried out to a level
// horizon, and along the upper terraces a band of closed coil-domes in the two deep greens with their stains: near, middle
// and far are three values and the horizon is a line. The far wood's coils are single loops tipped out over the gully, so
// the eye sees into them (card inside, lighter edge, a stain at the foot; one in four a teardrop, one in eight an S).
// THE STREAM LEG IS QUILLED: the forty fiddleheads are loose coils glued by their rims to slim stalks and turned to face the
// coming eye (spirals of light edge with the bank between the turns); each winds itself up as we come level and never
// closes to a drum. Moss pegs are tipped the same way. Every stream strip ends in a rolled scroll, two blues, a cool
// stain under the stream as its bed, more fish. Rain is small round pegs beaded along the fronds' top edges; one in five
// falls, and a crown that rolls up shakes its beads off.
// ON THE LIP AND UP THE FIRST OF THE LANE the eye rides the outer half of the lane, 8 m over the outer wall's edge, and looks
// OUTWARD: the lip with its leaflets is the foreground, the wood, the exit ring, the sky and a cloud scroll beyond.
// POLISH ROUND 5 (what the picture gained; nothing was taken away):
// THE LEAFLETS' WAVE: every leaflet on the king's turns leaps from a wound peg to an open teardrop as the route's own bearing
// about the hub (a function of u, tabled once from the path) comes within 24 m of it along its turn: it sets off from the
// near lip when the king has settled and runs ahead of us round every turn the route passes. OVER THE KING the gaze is drawn
// to a place (the air over the far side of the king's disc from where the route is, at the height of the hub), so the far
// turns, the gully, the dome band and the sky stand over the heart. The moths'
// five snails ride the outer turn's edge from the high lip on, a pitch of the roll apart, shells upright in the wall's own frame; every cast keeps its nine
// butterflies. The lyrebird stands 6 m tall on its log, a clear ring of 14 m round it, and all sixteen of its tail scrolls
// unroll. Distance tints are mixed
// as pigments (parts: quillTint), so a far green is green and a far bark brown. From the audit: a darker pool lies inside every tight coil; a bead under every ground coil and both ends of every strip cut
