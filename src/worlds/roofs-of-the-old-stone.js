// The Roofs of the Old Stone: a castle so vast that its roofs are a country, flown in FOUR ACTS under one low sun.
// ONE SUN, FOUR LIGHTS, by where one stands and which way one looks (nothing of the place changes by the metres
// flown): AGAINST the sun the castle is dark on a furnace sky, its windows lit; WITH the sun behind, every face
// ahead is gold with long shadows and the sky ahead is the violet east with its first stars and a pale moon; DOWN
// in the court, the gulf and the lane the stone is blue-green shade and the light is lamps and windows; at the end
// the ring's own gold lies on the tower and on what stands round it. By day the same places hold under a grey-gold
// afternoon; by night the moon does the sun's work on the sun's own bearing; at dawn the sun stands lower on that
// bearing, rose and pale gold through a thin mist, and few lamps are left burning.
// ACT ONE, against the sun: in over the clay dwellings heaped at the outer wall's foot and over the wall's walk
//   beside the gate, the finger tower highest ahead. ACT TWO, the sun behind: one long turn over the gate's ward on
//   to the field's own axis; over the forecourt, the gatehouse and the field of flagstones (dry gold flags, a few
//   pools, the rooks' parliament) toward THE KEEP, seen whole and crossed high, through its shoulder between two of
//   its towers. ACT THREE, in the shade: down behind the keep over the back court to the cliff, along it over the
//   slot's bridge, ONCE over the bole of the tree in the wall (the door, the roots, the trunk a walkway to the table
//   set for tea, the low sun on it through the rim's gap), past the cats' walk, into the lane and under its covered
//   bridge. ACT FOUR, against the sun again: out of the lane's mouth over the apron and the tower's round, up to the
//   ring in the finger tower's window arch.
// THE PLAN FIRST, THE LINE AFTER (part: roofPlan). The castle's plan is dealt whole, on its own streams, in the wall's
// frame (w along the cliff, t out of it, the tree's root at nought) before any point of the line exists: the frame,
// the hour and the sun; the places, each by its own measures (the lane and the finger tower with its round, the
// gate and the outer wall, the field with its forecourt, the keep and its back court, the gulf and its rim, the
// wards, which are measured from those places); the tree; the masses (the keep, the lane's ranges, the cats' hall,
// the field's ranges, the cliff, the rim, the slot's bridge, then the country by its wards and cells, then every
// tower by its cell or its place); the details (stacks, dormers, smoke, dwellings and their fires); the life
// (pools, perches, rooks, owls, cats, rags, washing, weeds, the parliament, the bats). THERE IS NO WAY: no street
// is laid for the line, no level is written by it, and no roof, tower, stack, plume or bird knows where it will
// be. THEN the line is laid over what stands; LAST the true clearance.
// WHAT READS THE LINE (all of it), and why:
//   1 layLine (part): the line itself. It reads the plan: of its courses (six bearings of entry, thirteen places to
//     cross the outer wall beside the gate, three places to come on to the field's axis; none whose arc is tighter
//     than 110 m) it takes the one that keeps farthest from every tower standing as high as it flies; from the wall
//     to the keep it climbs over the roofs and stacks as they stand; over the tree it flies clear of the tree as
//     dealt. The plan reads nothing of it.
//   2 clearLine (part): THE TRUE CLEARANCE, the line's only say over the plan: a thing whose nearest place would stand
//     within 2.5 m of the line, its own reach counted in (a flier's whole round within 2.8 m; a tower by its own
//     solid, the same 2.5 m: a round about its shaft up to its head's top, 1.1 of the radius, 1.3 for a square
//     shaft or four turrets, a lead cap's 1.14, and the smaller towers on it likewise), is left out after
//     its draws and counted by its kind (P.left): the lens must fly in clear air. (SINCE MENDING 4 THE LINE HAS ONE
//     SAY MORE, by the flown line's own place and on every seed: a bird that flies another of its ways than its
//     first, and would by it come within 15 m of the line and nearer than its first round came, keeps its seat
//     and sits; A ROOK OF THE TREE on any way but its first sits if that way comes within 15 m of the flown line
//     by the part's own reading (birdNear's walk; the reader's finer walk finds five such ways at 14.73 to 14.92 m,
//     14.7 m at the least: the reader's count), and beyond that a way may lie nearer the line than the first did;
//     the least distance of any flier from the line is unchanged by it, 2.801 m by the part's own reading (the
//     builder's count, seeds 1 to 300) and 2.764 m by the reader's finer walk (the reader's count), the same in
//     mendings 4 and 5.)
//     (MENDING 6: A BIRD THE MENDINGS MADE SIT IS ASKED WHETHER ITS SEAT IS CLEAR (part: seatSunk, in roofPlan after
//     the line's say): a rook made to sit on a quad's ridge, a roof, the parapet or the tree is left out, after its
//     draws, if any corner of its drawn body at rest stands more than 0.05 m inside slate, stone, paving or timber
//     of a building or more than 0.15 m inside the dead tree's own wood at rest: the two allowances (read by the
//     faces drawn about its seat: square behind one, or the nearest of them showing its back). No bird moves,
//     none is added; birds nobody made sit, every flier's rest, the flock, the field's and the ledge's rooks and
//     the owls (asked by their ball, now against the front's three openings too) are as they were.)
//     (MENDING 3, T: a cone's eave,
//     cut or whole, stands 0.06 of the radius outside that round, and the corners of a near flat head's merlons
//     and of a square head a little outside it: the solid is not the head as built. The fliers' test alone asks
//     the head as built since mending 3 (the part's towerBuilt); the line's clearance of every drawn triangle is
//     a count on seeds 1 to 300, not this law's.)
//   3 roofFilm (part): the pace and the five pulls of the gaze, keyed to the line's metres at the plan's places: a film
//     is told along its line. It moves nothing of the place.
//   4 the engine: the camera flies the line, and the portal stands at the line's end.
// Nothing else reads the line: nothing is placed, levelled, sized, turned, lit, made finer or thinned by its distance
// from the line or by the line's metres or height. How finely a thing is made is by its WARD (how deep in the castle
// it lies, measured from the places that stand: a range's zone, part: planMasses) or by its PART (a tower:
// towerLod), and the meshes are the wards'.
// WHAT READS THE EYE (all of it), and why:
//   1 the stone's shader (part: makeStoneMaterial): the eye's place gives the direction of sight for what a surface
//     gives back (the mirror of pools, wet slate and panes, the gold along sunward edges) and the depth of haze
//     between; THE FILTERS read the breadth of a point of the picture on the face (the uv's change from point to
//     point) for this alone: a pattern finer than a point is given as its own mean (rings and ripples on water, the
//     sun's glitter, bark), and fine marks (joints, courses, slates' edges, window dressings) fade to their face's tone.
//     A LIGHT IS NEVER FADED (mending 2): a lit window finer than a point gives its share of that point, and a far
//     wall the mean of its lit windows; no window is lit or put out by the eye's distance or the picture's size.
//   2 the shaders of the birds, the cats, the cloth and the smoke: the direction of sight for their light and the
//     depth of haze; a puff of smoke is a round card turned to the eye, as smoke has no side.
//   3 the kit: the sky and its light rig follow the camera (a sky is at no distance); the kit's fauna (the bats) is
//     handed the camera and u, as its own call asks.
//   4 ctx.quality.detail: thins the instances DRAWN (every kind of rook by the same share, cats, bats), never the plan.
// THE CLOCK: everything of the place runs on the world's clock (update sets uTime); nothing begins, turns or ends as
// the visitor comes. The rooks' lift (a rare visit) and every round, plume, lamp and window keep their own phases.
import * as THREE from 'three';
import { clamp } from '../kit/core.js';
import { makeSky, makeLightRig } from '../kit/sky.js';
import * as F from '../kit/fauna.js';
import {
  DURATION, M, HOURS, bounceOf, roofPlan, roofFilm, planFloor, makeAcc, makeLightUniforms, setCasters, setPools, setFires, setLane, setCourt, makeStoneMaterial, makeClothMaterial, makeClothAcc,
  rangeInto, towerInto, chimneysInto, dormersInto, hutsInto, yardsInto, firesInto, floorInto, fingerInto, outerWallInto, quadFloorInto, weedInto, clothThingsInto, catWallInto,
  makeBirds, birdDrawOrder, makeCats, makeSmoke, buildHero, towerLod, laneInto, courtsInto, keepGlassInto, keepDressInto, fieldEdgeInto, oldStonesInto, yardInto,
} from '../parts/roofs-of-the-old-stone.js';

export default {
  id: 'roofs-of-the-old-stone',
  name: 'The Roofs of the Old Stone',
  category: 'books', placeKind: 'city', book: 'Titus Groan', author: 'Mervyn Peake, 1911 to 1968', media: ['air', 'open'],
  weirdness: 0.55,
  async build(ctx) {
    const vary = ctx.vary || {}, detail = clamp((ctx.quality && ctx.quality.detail) || 1, 0.4, 1);
    const Y = ctx.yield.bind(ctx);
    // the plan of this visit: plain numbers, every stream forked inside it from the seed and a name; the castle's plan
    // whole, then the line through it, then what the line's true clearance leaves out
    const P = await roofPlan(ctx.seed, { hour: vary.hour, rare: vary.rare, density: vary.density }, Y);
    planFloor(P);
    const film = roofFilm(P), H = HOURS[P.hour], scene = new THREE.Scene(), dens = P.density;
    await Y();

    // ---- the sky of the hour, and the light the stone takes from it
    const sky = makeSky({ rng: P.R_.sky, ...H.sky(P, ctx) });
    await Y();
    scene.add(sky.object);
    const rig = makeLightRig(sky); scene.add(rig.object);
    await Y();
    const U = makeLightUniforms(), key = (sky.lightDirection || sky.sunDirection).clone().normalize();
    if (key.y < 0.07) { key.y = 0.07; key.normalize(); }
    const keyV = [key.x, key.y, key.z];
    U.uSunDir.value.copy(key);
    U.uSunCol.value.setRGB(H.sun[0], H.sun[1], H.sun[2]); U.uSkyCol.value.setRGB(H.air[0], H.air[1], H.air[2]); U.uGndCol.value.setRGB(H.gnd[0], H.gnd[1], H.gnd[2]);
    { const b = bounceOf(H); U.uBounce.value.setRGB(b[0], b[1], b[2]); }
    const _d = new THREE.Vector3(), hx = key.x / Math.hypot(key.x, key.z), hz = key.z / Math.hypot(key.x, key.z);
    sky.colorAt(_d.set(hx, 0.05, hz).normalize(), U.uHorSun.value); sky.colorAt(_d.set(-hx, 0.06, -hz).normalize(), U.uHorAway.value); sky.colorAt(_d.set(-hx * 0.2, 0.9, -hz * 0.2).normalize(), U.uZen.value);
    U.uCloudCol.value.setRGB(H.clouds[0], H.clouds[1], H.clouds[2]); U.uAfter.value.setRGB(H.after[0], H.after[1], H.after[2]);
    U.uFogSun.value.copy(U.uHorSun.value).multiplyScalar(0.8); U.uFogCol.value.copy(U.uHorAway.value).lerp(U.uZen.value, 0.25);
    // (at sunset the far haze away from the sun is half the sky's own colour there and half the air's blue)
    if (H.haze) U.uFogCol.value.lerp(new THREE.Color(H.haze[0], H.haze[1], H.haze[2]), 0.5);
    // (uRain: the strength of the rings of drops on the standing water: whole where it has just rained harder, four
    // tenths of that otherwise)
    U.uFogDen.value = H.fog; U.uWet.value = H.wet; U.uCloud.value = H.cloud; U.uWinGlow.value = H.glow; U.uRain.value = P.rain ? 1 : 0.4; U.uLit.value = H.lit;
    setCasters(U, P.casters);
    // the field's few pools, the wind's heading, the dwellings' fires, the courts' lamps and the lane's own frame,
    // for the stone's shader
    setPools(U, P.pools); U.uWind.value.set(P.wind[0], P.wind[1]); setFires(U, P.fires, H.fire); setCourt(U, [...P.lamps, ...P.glows], 3); setLane(U, P);
    U.uWall.value.set(P.T[0], P.T[1], P.root[0] * P.T[0] + P.root[1] * P.T[1], 0.28);
    // the deep places (the back court, the gulf to its rim, the lane's built length) and the hour's two shares
    U.uDeep.value.set(M.KEEP_W1, M.RIM_W1, 0, M.GULF_FAR + M.RIM_DEEP); U.uDeepW.value.set(P.W[0], P.W[1], P.root[0] * P.W[0] + P.root[1] * P.W[1]);
    U.uDeepTint.value.setRGB(H.deepTint[0], H.deepTint[1], H.deepTint[2]); U.uSil.value = H.sil;
    // the two lamps, each fixed in its place by its own thing's measures: the ring's own light, in the lane's air
    // 22 m before the tower's face at the ring's height (on the tower's face round the arch, its ivy, the round's
    // paving, the nearest roofs and the lane's mouth); and the painted room's light at its door, on the tree's root and the ledge
    { const e = P.laneAt(P.finger.rRing + 22, 0), door = P.heroToWorld(P.heroM.doorX, P.heroM.r0 * 0.7 + 4, 2.5), k = P.hour === 'night' ? 1.3 : 1;
      U.uLampP.value[0].set(e[0], M.RING_Y, e[1], 30); U.uLampC.value[0].setRGB(3.0 * k, 1.65 * k, 0.56 * k);
      U.uLampP.value[1].set(door[0], door[1], door[2], 7); U.uLampC.value[1].setRGB(3.2 * k, 2.2 * k, 1.2 * k); }
    scene.fog = new THREE.FogExp2(U.uFogCol.value.clone(), H.fog);
    const stoneMat = makeStoneMaterial(U), clothMat = makeClothMaterial(U);
    await Y();

    // ---- the castle, assembled from the plan by the part's makers into a few great meshes, each a WARD of the place
    // (the plan's own groups, by where a thing stands in the wall's frame: 0 the gate's ward, 1 the forecourt and the
    // field's near side, 2 the keep's ward, 3 the cliff and the gulf, 4 the lane's ward, 5 the tower's ward; the middle
    // ward and the far country are meshes of their own)
    const stone = (name, A) => { const m = new THREE.Mesh(A.toGeometry(), stoneMat); m.name = name; scene.add(m); return m; };
    // (every accumulator is made once at the size CAPS gives it at this file's end, which no mesh outgrows on seeds 1
    // to 300 at the highest density; a mesh that did outgrow it would be copied to twice the size, once for every
    // doubling, and counted: makeAcc.grows)
    const NS = 6, accs = (caps) => caps.map((c) => makeAcc(c));
    {
      const near = accs(CAPS.ranges), mid = makeAcc(CAPS.rangesMid), far = makeAcc(CAPS.rangesFar);
      await Y();
      for (const m of P.ranges) {
        if (m.part === 'massB' && m.isTree) {
          // the tree's own block begins 13.2 m behind the hero's face of it (the hero lays that face with its door and
          // merlons, the painted room behind the door, and the wall's head and returns over that depth)
          rangeInto(near[m.g], { ...m, x: m.x - P.T[0] * 6.6, z: m.z - P.T[1] * 6.6, hw: m.hw - 6.6 }, 1, dens, keyV);
        } else if (m.part !== 'bridge' && m.part !== 'sbridge') rangeInto(m.zone === 0 ? near[Math.min(m.g, NS - 1)] : m.zone === 1 ? mid : far, m, m.zone, dens, keyV);
        await Y();
      }
      await Y();
      keepGlassInto(near[2], P); await Y(); keepDressInto(near[2], P, keyV); await Y();
      for (let i = 0; i < NS; i++) { stone('ranges-' + i, near[i]); await Y(); }
      stone('ranges-mid', mid); await Y(); stone('ranges-far', far);
    }
    await Y();
    {
      const near = accs(CAPS.towers), mid = makeAcc(CAPS.towersMid), far = makeAcc(CAPS.towersFar);
      await Y();
      for (const t of P.towers) {
        const lod = towerLod(t);
        towerInto(lod === 2 ? far : lod === 1 ? mid : near[Math.min(t.g, NS - 1)], t, lod, dens);
        await Y();
      }
      for (let i = 0; i < NS; i++) { stone('towers-' + i, near[i]); await Y(); }
      stone('towers-mid', mid); await Y(); stone('towers-far', far);
    }
    await Y();
    {
      // chimneys and dormers, by the ward of the roof or tower each stands on
      const A = accs(CAPS.roofThings); let k = 0;
      await Y();
      for (const c of P.chimneys) { chimneysInto(A[Math.min(c.g, NS - 1)], [c]); if (++k % 4 === 0) await Y(); }
      for (const d of P.dormers) { dormersInto(A[Math.min(d.m.g, NS - 1)], [d]); if (++k % 4 === 0) await Y(); }
      for (let i = 0; i < NS; i++) { await Y(); stone('roof-things-' + i, A[i]); }
    }
    await Y();
    {
      // the outer wall, the clay dwellings on their mound with their yards and fires, the cats' walk
      const A = makeAcc(CAPS.wall), B = makeAcc(CAPS.huts); for (let i = -31; i < 31; i += 3) { outerWallInto(A, P, i, i + 3); await Y(); }
      stone('outer-wall', A); await Y();
      for (let i = 0; i < P.huts.length; i += 20) { hutsInto(B, P.huts.slice(i, i + 20)); await Y(); }
      yardsInto(B, P.yards); firesInto(B, P.fires); catWallInto(B, P);
      await Y(); stone('huts-and-cats-walk', B);
    }
    await Y();
    { const A = makeAcc(CAPS.ground); await floorInto(A, P); await Y(); stone('ground', A); }
    await Y();
    // the field of flagstones and its edges, the finger tower, the lane's court, the paved places (the forecourt,
    // the back court with the slot's bridge, the apron and the tower's round) and their lamps; the poles, the rope
    // and the weed tree's wood; and their cloth
    const CA = makeClothAcc();
    { const A = makeAcc(CAPS.field); quadFloorInto(A, P); await Y(); oldStonesInto(A, P, keyV); await Y(); yardInto(A, CA, P, keyV); await Y(); fieldEdgeInto(A, P); await Y(); fingerInto(A, P); await Y(); laneInto(A, P); await Y(); courtsInto(A, P); await Y(); clothThingsInto(A, CA, P); await Y(); if (P.weed) weedInto(A, CA, P); await Y(); for (const w of P.weeds) { weedInto(A, CA, P, w); await Y(); } stone('field-and-finger', A); }
    const cloth = new THREE.Mesh(CA.toGeometry(), clothMat); cloth.name = 'rags-and-washing'; scene.add(cloth);
    await Y();

    // ---- the hero: the tree in the wall, stood at its root in the wall's own frame
    const hero = await buildHero(ctx, { plan: P, U, mat: stoneMat, clothMat });
    hero.object.position.set(P.root[0], M.TREE_Y, P.root[1]); hero.object.rotation.y = P.heroYaw; hero.object.updateMatrixWorld(true);
    scene.add(hero.object);
    await Y();

    // ---- the life: rooks and owls (one draw), the shadows of the field's rooks on its flags (one draw), the cats
    // (one draw), the smoke (one draw), bats
    // (ctx.quality.detail thins the instances that are drawn, never the plan: every kind of rook by the same share, the
    // owls drawn whole at every detail)
    const order = birdDrawOrder(P.birds, detail), birds = makeBirds(order.list, U); birds.mesh.geometry.instanceCount = order.count; scene.add(birds.mesh);
    // (the flock's lift: whether this visit has one, and where its 44 s round stands at the clock's nought; both fixed for the visit)
    birds.uniforms.uLift.value = P.rare ? 1 : 0; birds.uniforms.uLiftPh.value = P.liftPhase;
    await Y();
    { const q = P.quad, fieldBirds = order.list.slice(0, order.count).filter((b) => b.on === 'field');
      if (fieldBirds.length) {
        const sh = makeBirds(fieldBirds, U, { y: q.y, W: P.W, T: P.T, box: [q.w0, q.w1, q.t0, q.t1], alpha: H.shadow });
        sh.uniforms.uLift = birds.uniforms.uLift; sh.uniforms.uLiftPh = birds.uniforms.uLiftPh; sh.mesh.material.uniforms.uLift = birds.uniforms.uLift; sh.mesh.material.uniforms.uLiftPh = birds.uniforms.uLiftPh;
        sh.mesh.name = 'rook-shadows'; sh.mesh.renderOrder = 1; scene.add(sh.mesh);
      } }
    await Y();
    const cats = makeCats(P, U); cats.mesh.geometry.instanceCount = Math.max(1, Math.floor(P.cats.list.length * detail)); scene.add(cats.mesh);
    await Y();
    const smoke = makeSmoke(P.plumes, U, P.wind); scene.add(smoke.mesh);
    await Y();
    const fauna = F.makeFauna(scene, { light: F.lightFrom(scene) });
    // THE BATS' STREAM, every measure of it written out here: its course (a loop of P.bats.radius about the plan's
    // place for it), its scatter about the course (spread: a bell curve of 2.5 m across and 2 m up and down, every
    // draw held within three scatters by maxSigma) and its wander (3.5, 2.5 and 2.5 m, the species' own measure,
    // which swings a bat 5.25 m across and 2.5 m up and down and along at the most). No keepClear: the course lies
    // far off the line by its own numbers. THE BOUND, counted on seeds 1 to 300: the flown line comes no nearer
    // than 25.4 m to the box a bat can be in (the course, three scatters across and up and down, the wander's whole
    // swing on each axis), which is 24.4 m when a ball of 0.95 m is taken off for the bat itself
    if (P.bats) fauna.add(F.makeFlock({ rng: P.R_.bats, species: 'bats', count: Math.round(70 * dens * detail), center: [P.bats.x, P.bats.y, P.bats.z], radius: P.bats.radius, spread: [5, 4, 30], wander: [3.5, 2.5, 2.5, 1.6], maxSigma: 3 }));
    await Y();

    await sky.prewarm(ctx.renderer, null, scene);
    return {
      scene, path: P.path, duration: DURATION,
      pace: film.pace,
      pois: film.pois,
      camera: { fov: 62, near: 0.3, far: 7000, lookAhead: 30, sway: 0.5, bank: 0 },
      portal: { shape: 'circle', radius: M.RING_R, color: H.portal, glow: 1.25, revealDistance: 320 },
      post: {
        exposure: H.exposure, bloom: { strength: 0.5, radius: 0.7, threshold: 0.92 },
        grade: { saturation: 1.06, contrast: 1.06, tint: '#fbf6f2', shadowTint: '#0e161d', vignette: 0.34, grain: 0.03, aberration: 0 },
      },
      update(dt, time, camera, u) {
        // (everything of the place runs on the world's clock; u goes to the kit's fauna alone, as its own call asks)
        U.uTime.value = time;
        sky.update(dt, time, camera); rig.update(dt, time, camera);
        fauna.update(dt, time, camera, u);
      },
      dispose() { hero.dispose(); sky.dispose?.(); },
    };
  },
};
// the sizes the accumulators are made at (places of corners), by the ward: a fifth and more over the greatest count
// met on seeds 1 to 300 at the highest density (the least margin of any: 1.2 times the greatest count, the middle
// ward's towers, whose broken heads are rings of standing teeth since mending 2; every other has a quarter and
// more: the least of them 1.256 times, the keep's towers; counted again at mending 3)
const CAPS = {
  ranges: [10240, 65536, 67584, 94208, 67584, 131072], rangesMid: 28672, rangesFar: 8192,
  towers: [47104, 49152, 32768, 32768, 30720, 63488], towersMid: 47104, towersFar: 16384,
  roofThings: [8192, 65536, 38912, 86016, 67584, 143360], wall: 81920, huts: 184320, ground: 53248, field: 90112,
};
