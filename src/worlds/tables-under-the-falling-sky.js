import * as THREE from 'three';
import { clamp, lerp, smoothstep } from '../kit/core.js';
import { buildHero, planRoom, DIM } from '../parts/tables-under-the-falling-sky.js';

export { planRoom };

// The seconds the flight is laid to take, and the speeds it is laid for by place (metres a second; the engine scales the
// whole table by one factor so that the flight lasts FILM_S).
const FILM_S = 45;
const SPEED = { plain: 20, door: 13.5, low: 10.4, round: 10.6, top: 10, turned: 9.6, leg: 12.6, pier: 12.2 };
const GAZE_W = 0.8, DEG = Math.PI / 180;
// THE TABLE'S NUMBER (round t1): the small brass plate on the party's table with the numerals 4 and 2, THE ONLY WRITING
// IN THE WORLD. Set this one word to false and nothing of the plate is built (no stem, no plate, no numeral).
const TABLE_NUMBER = true;
// THE DRIFT OF OLD SHOES (round t1): the heap and the scatter of worn shoes on the broken ground beside the causeway.
// They are small in the picture (the line passes 7 m and more from them). Set this one word to false and no shoe is built.
const OLD_SHOES = true;
// THE LOOK TO THE PARTY'S TABLE (round t1): one gentle second row of the gaze, a weight of 0.3 at the most, from 34 m of
// the line before the table's nearest place to 10 m past it (route metres, by the plan's own party.near; the engine
// eases its ends over three tenths of its length, so it is whole from 20.8 m to 3.2 m before the nearest place, 0.26
// at that place and gone 10 m past it). The line, the pace and the pull to the fountain are as they were.
const PARTY_LOOK = { before: 34, past: 10, weight: 0.3 };

// THE FILM'S LAW: places of the flown line by metres from its start, the pace between them, and the gaze's one pull.
// A pure function of the route.
export function layFilm(route, floor, party = null) {
  const path = route.path, L = route.L, v = new THREE.Vector3(), w = new THREE.Vector3(), out = new THREE.Vector3();
  const S = { ...route.S };
  for (let s = 0; s <= L; s += 0.5) { path.posAtDist(s, v); if (Math.hypot(v.x, v.z) <= DIM.RD) { S.door = s; break; } }
  S.straight = L - 60;
  // the pace: brisk over the causeway, eased to the door, steady and low among the tables, unhurried round the fountain
  // and through the level turn at the top (slowest where that turn runs out), then along the leg and the pier to the ring
  const K = [[0, SPEED.plain], [S.door - 45, SPEED.plain], [S.door, SPEED.door], [S.arc0 + 10, SPEED.low], [S.rise0, SPEED.low], [S.rise0 + 25, SPEED.round],
    [S.rise1 - 20, SPEED.round], [S.rise1 + 15, SPEED.top], [S.top1 - 32, SPEED.turned], [S.top1 + 10, SPEED.turned], [S.top1 + 45, SPEED.leg], [S.straight, SPEED.pier], [L, SPEED.pier]];
  const speedAt = (s) => {
    let i = 0;
    while (i < K.length - 2 && s > K[i + 1][0]) i++;
    return lerp(K[i][1], K[i + 1][1], smoothstep(K[i][0], K[i + 1][0], s));
  };
  const pace = (u) => speedAt(clamp(u, 0, 1) * L) / 15;
  // THE GAZE'S ONE PULL, TO THE GREAT FOUNTAIN (it begins 12 m of the line before the door, where the fountain stands in
  // the opening, and has its share 2 m past the door; nothing before that, nothing on the leg). share(s): how much of the angle
  // between the way ahead and the fountain the lens takes: 0.66 of it from the door on (so the lens keeps the fountain
  // while the way bends off down the arc, and goes round with it; the gaze stays under 75 degrees off the line's own
  // heading for both cameras), 0.78 at the top of the rise (the fountain between the suns of the far rim). It is let go by the line's own shape: from the place in the level turn
  // at the top where the lens has come round to the leg's own heading, the lens keeps that heading (it looks down the
  // leg to the ring while the line comes round under it), so the pull runs out to nothing where the leg begins.
  const KG = [[S.door - 12, 0], [S.door + 2, 0.66], [S.rise1 - 25, 0.66], [S.rise1 + 25, 0.78]];
  const share = (s) => {
    if (s <= KG[0][0] || s >= S.top1) return 0;
    let i = 0;
    while (i < KG.length - 2 && s > KG[i + 1][0]) i++;
    return lerp(KG[i][1], KG[i + 1][1], smoothstep(KG[i][0], KG[i + 1][0], s));
  };
  const wrap = (a) => { while (a > Math.PI) a -= 2 * Math.PI; while (a < -Math.PI) a += 2 * Math.PI; return a; };
  path.posAtDist(S.top1 + 20, v); path.posAtDist(S.top1 + 50, w);
  const yawLeg = Math.atan2(w.x - v.x, w.z - v.z);
  // the lens's pitch wanted while the pull is on: 2 degrees up when low among the tables, half a degree down (level) from
  // the top of the rise (by the lens's own height)
  const wanted = (s) => {
    path.posAtDist(clamp(s, 0, L), v); path.posAtDist(clamp(s + 12, 0, L), w);
    const fx = w.x - v.x, fy = w.y - v.y, fz = w.z - v.z, fh = Math.hypot(fx, fz) || 1e-6, yawF = Math.atan2(fx, fz), pitchF = Math.atan2(fy, fh);
    const A = wrap(Math.atan2(-v.x, -v.z) - yawF);
    let k = share(s);
    if (s > S.rise1 && k > 0) k = clamp(Math.min(k, Math.abs(A) > 0.02 ? wrap(yawLeg - yawF) / A : 0), 0, 1);
    const pitchW = lerp(pitchF, lerp(2 * DEG, -0.5 * DEG, smoothstep(DIM.YLOW + 1, DIM.YHIGH - 3, v.y)), Math.min(1, k / 0.5));
    return { eye: v, yawF, pitchF, A, k, yaw: yawF + k * A, pitch: pitchW };
  };
  const gazeAt = (time, u) => {
    const g = wanted(clamp(u, 0, 1) * L), yaw = g.yawF + g.k * g.A / GAZE_W, pitch = g.pitchF + (g.pitch - g.pitchF) / GAZE_W, D = 60;
    return out.set(g.eye.x + Math.sin(yaw) * D, g.eye.y + Math.tan(clamp(pitch, -0.6, 0.6)) * D, g.eye.z + Math.cos(yaw) * D);
  };
  // the pull's window runs from 35 m to 40 m down the leg. THE ENGINE EASES A WINDOW'S ENDS over three tenths of its
  // length (about 121 m here), so what the lens truly takes is LESS than share(s) from the door's 79 m to 156 m (the
  // door and the first of the arc) and from 317 m to the level turn's end at 398 m; between 156 m and 317 m it is
  // share(s) whole. (Before 79 m and after 398 m the point given is the way ahead itself.)
  const u0 = 35 / L, u1 = (S.top1 + 40) / L, pois = [{ at: gazeAt, from: u0, to: u1, weight: GAZE_W, arc: true, steady: true }];
  // the second row: toward the middle of the party's table while the lens passes it (steady: true as the first has it, so
  // that the steady camera finds the table too; mixed along the angle as the first is)
  if (party) pois.push({ at: [party.x, party.y + 0.9, party.z], from: Math.max(0, party.near - PARTY_LOOK.before) / L, to: Math.min(L, party.near + PARTY_LOOK.past) / L, weight: PARTY_LOOK.weight, arc: true, steady: true });
  return { S, K, KG, speedAt, pace, share, wanted, gazeAt, pois };
}

export default {
  id: 'tables-under-the-falling-sky',
  name: 'Tables Under the Falling Sky',
  category: 'books',
  placeKind: 'interior',
  book: 'The Restaurant at the End of the Universe',
  author: 'Douglas Adams, 1952 to 2001',
  media: ['air'],
  weirdness: 0.8,

  async build(ctx) {
    const scene = new THREE.Scene();
    scene.background = new THREE.Color(0x030203);
    // the whole place is the part's: the plan (the seed alone), the sky, the room, the glass, the small lights
    // the visit's hints, read here by name and handed on (the hour is not read: the place stands at one hour)
    const vary = ctx.vary || {}, quality = ctx.quality || {};
    const hero = await buildHero(ctx, { vary: { rare: vary.rare, density: vary.density, mood: vary.mood }, detail: quality.detail, tableNumber: TABLE_NUMBER, oldShoes: OLD_SHOES });
    scene.add(hero.object);
    await ctx.yield();
    const plan = hero.plan, route = plan.route, film = layFilm(route, plan.F, plan.party);
    return {
      scene,
      path: route.path,
      duration: FILM_S,
      pace: film.pace,
      // no bank: the horizon stays level through every turn (A6)
      camera: { fov: 66, near: 0.5, far: 6000, lookAhead: 12, bank: 0 },
      pois: film.pois,
      portal: { shape: 'circle', radius: DIM.RING, color: '#ffdca8', glow: 1, revealDistance: 260 },
      post: {
        exposure: 1.0,
        bloom: { strength: 0.38, radius: 0.55, threshold: 0.92 },
        grade: { saturation: 1.1, contrast: 1.0, tint: '#ffffff', shadowTint: '#000000', vignette: 0.28, grain: 0.02, aberration: 0 },
      },
      plan, film, hero, ringAt: route.E,
      update(dt, time) { hero.update(dt, time); },
      dispose() { hero.dispose(); },
    };
  },
};
