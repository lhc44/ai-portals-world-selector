//
// THE FILM (layFilm below): the places of the line are the line's own joints (the door found on it; the arc, the
// promenade, the rise, the top turn, the leg as the plan laid them); the pace is laid between those places in metres a
// second and the gaze's one pull, to the great fountain, comes on and goes off between them. No number here is a share
// of the flight. The pull keeps its whole weight for the steady camera too (steady: true): the fountain is the room's
