// THE GOLDEN CITY AND ITS BRIDGE. The realm of the gods of the film, by night: gold, starlight and rainbow light. Drawn in our own
// hand from a description in words; we fly our own line through the place.
// THE PLACE (typed places: src/parts/asgard-bridge-of-light-plan.js; x east, y up, z south, the rim to the north):
//  THE CITY on a steep rock island 380 m in radius about (0, 400): four terraces, pale gold buildings with warm lights in their walls, tall slender
//   golden spires, falls of water from the terraces to the sea; on the top terrace THE PALACE, a rank of round golden tubes stepping
//   up from both sides to 250 m in the middle (its top 390 m over the sea), its front toward the bridge. The city's falls stand at
//   typed bearings (about 0.55 and 1.05 rad either side of the gate), so that they are seen from the bridge on every seed; the
//   city's scatter keeps an open axis: nothing within 14 m of x 0, nothing within 44 m of x 0 north of z 112.
//  THE BRIDGE from the city's gate (z 26) straight north to the gate house (z -1378): a slab of crystal 14 m wide, its top 6 m over
//   the sea, fine threads of every colour racing along inside it toward the rim; its light lies on the water either side.
//  THE SEA: one glass-still dark sheet holding the stars, the star clouds, the moons, the city's gold and the bridge's colours.
//  THE BAY OF THE FALL: the sea's edge is cut back round the bridge in a long bay, its apex on the bridge's line at z -700, its two
//   arms running out to (-300, -1409) and (300, -1409) and on east and west as the old rim. Along the whole edge the sea bends over
//   a smooth lip with a bright rim of foam and falls as white streaked water, shut for its top 60 m and opening lower into streamers,
//   spray and mist that sink among the stars (the sea part's head has it all). Inside the bay there is no sea:
//   the bridge's far half and the gate house stand over open space, stars above and below.
//  THE GATE HOUSE at the bridge's far end (0, -1420): a golden globe 60 m across on a round stepped base with a keel under it, a
//   doorway toward the bridge, a spike 65 m long from its north-east shoulder (the beam's nozzle); from the spike's point THE BEAM runs out into space.
//  THE RING stands free in the city on its own round platform (0, 88), deck 77 m up, before the second terrace's brow, under the palace.
//  THE SKY: thick stars above and below the sea's level, three small moons in the southern half and ONE GREAT PALE MOON (typed:
//   16 degrees east of south, 24 degrees up, beside the palace's top as seen from the bridge); THE RICHEST STAR CLOUDS and the
//   galaxy's arm stand in the SOUTH, over and behind the city, on every seed: the arm rises from the south-east and passes over the
//   city 20 degrees up, its heart 14 degrees west of south and 27 degrees up (typed),
//   the clouds of star-gas by one typed number of the kit's cloud field. No daylight.
// THE FLIGHT (1,982 m in 65 s; THE TOUR), from the gate house to the city by way of the open sea: in over the stars 300 m beyond
// the gate house on its north-west side, 52 m up, flying south-south-east; past the globe's west side (97 m from its middle);
// down the bay in one long gentle S, sinking from 36 to 15 m over the slab's level: west of the bridge, over it in mid bay,
// 30 m east of it before the apex, so the bridge passes from the left hand under us to the right hand and the two arms of the
// fall open on either side in turn. THE CROSSING (583 m): out of the bay over its east arm, level, 20 m up (the flight never
// goes down the fall), then low over the still sea, 15.5 m up, nearly straight south-south-east between the city's TWO
// OUTWORKS in the sea (the city part's typed places (207, -524) and (210, -275)), each one's middle 58 m off, the first on the
// left hand, the second on the right; past the first it rises to 28 m, so that the eye looks over the second one's bastion to
// the city and the ring. THE TURN ROUND OUTWORK TWO (155 m): one right turn of 100 m, level at 28 m, the outwork on the right
// hand falling behind as the city swings in from the right. THE STRAIGHT (222 m): 60 degrees west of south toward the gate,
// the city's north-east front with its falls on the left hand, the gate towers ahead, climbing to 44 m. THE HOOK'S END (63 m):
// 60 degrees of left turn of 60 m onto the bridge's own line before the gate, climbing to 61 m; then straight (97 m, rising
// 15.4 degrees) over the gate's gable, between its two towers, to the ring. The plan part has every place.
// BEHIND THE ENTRY there is open space only (the beam runs out north-east, 250 m east of it).
// PACE (typed, by places of the route in metres flown; the engine keeps the whole at 65 s): half as fast again over the middle
// of the crossing (full from 110 m before the first outwork is nearest to 170 m before the second); 0.88 from the second
// outwork round the turn and along the straight (27 m a second); 0.58 round the hook's end, so that the last turn swings the
// eye under 10 degrees a second; back to 1 over the first 35 m of the last straight; 1 over the last 62 m.
// THE WAY OUT: the last 100 m lie on the bridge's own line (the last 97 m on one slope). From the last third's beginning (on
// the crossing, between the outworks) the ring is in the picture: far off over the first wall to the right of the line, in
// the picture's middle as the turn ends, between the gate towers round the hook. Two things cross it for a moment: outwork
// two's spire before the turn, and the east gate tower near the straight's end.
// THE LOOKS (two; each on one fixed place, one plain weight, between named places of the route in metres flown):
//  1 THE GATE HOUSE'S GLOBE, its middle: weight 0.45, from the entry to the place where the globe is abeam (260 m), ramps of
//    100 m, so it is full until 100 m before abeam and has let go by abeam. Why: the globe is the first large near thing; the
//    eye holds it as it grows, and is already on the bay and the city as the globe passes out of the picture.
//  2 THE PALACE'S FRONT, half way up its tallest tube: weight 0.5, from the place where the globe is abeam to the end, ramps of
//    200 m. Why: the city is the flight's goal; on the crossing the look turns the eye half way from the line to the city, so
//    the city and its image fill the right of the picture while the outworks pass; on the straight toward the gate it turns
//    the eye half way to the left, up the city's north-east front, and the ring stands near the picture's middle; round the
//    hook it comes back onto the line as the palace comes ahead. The palace is never more than 60 degrees off the line.
// LIFE: three flocks of the kit's pale birds, on the clock alone, each wheeling about a typed place (the plan's FLOCKS): 66 over the
// first terrace before the ring, about (0, 100, 58), 17 m round, above the flown line; 34 round each outwork's spire, about
// (207, 58, -524) and (210, 58, -275), 32 m round (4 to 51 m from the spire's axis), 49 to 67 m up. They take the sky's violet
// from above and the city's gold from below. Each keeps 8 m of clear air from the flown line by place (the outworks' flocks
// stand 22 m and more from it).
// NOTHING else is keyed to metres flown; everything that moves goes by the clock: the bridge's threads, the sea's glints, the
// veil's threads and the mist sinking from it, the city's falls, the globe's bands, the beam's swell (12.6 s) and the waves of light along it, the stars' twinkle.
// A SEED DEALS: ctx.vary.hour 'dawn' the MIST NIGHT (more mist under the veil, a paler horizon), every other hour the CLEAR NIGHT;
// ctx.vary.rare a fourth small moon; ctx.vary.density the count of buildings, spires and falls; the small moons' places (southern
// half); each bird's place in its flock (streams birds-terrace, birds-outwork-one, birds-outwork-two).
import * as THREE from 'three';
import { makePath, makeRng, hashSeed, clamp } from '../kit/core.js';
import { makeSky, makeLightRig } from '../kit/sky.js';
import { makeFlockAsync } from '../kit/fauna.js';
import { ROUTE, ABEAM, LEAVE, OUTONE, OUTTWO, HOOK, ONLINE, PALACE, HOUSE, RING, FLOCKS, FLOCK_COMMON } from '../parts/asgard-bridge-of-light-plan.js';
import { makeShared } from '../parts/asgard-bridge-of-light-mat.js';
import { buildSea } from '../parts/asgard-bridge-of-light-sea.js';
import { buildCity } from '../parts/asgard-bridge-of-light-city.js';
import { buildGate } from '../parts/asgard-bridge-of-light-gate.js';

const V3 = (x, y, z) => new THREE.Vector3(x, y, z);
const CLOUD_FIELD = 23.5;      // the one typed number of the kit's field of star-gas: with it the richest clouds stand in the south on every seed

export default {
  id: 'asgard-bridge-of-light', name: 'The Golden City and Its Bridge', category: 'screen', placeKind: 'ocean', screen: 'Thor', screenYear: '2011', screenKind: 'film',
  weirdness: 0.5, media: ['air'],
  async build(ctx) {
    const scene = new THREE.Scene();
    const vary = ctx.vary || {}, mist = vary.hour === 'dawn', rare = !!vary.rare, dens = clamp(vary.density ?? 1, 0.7, 1.3), detail = ctx.quality ? ctx.quality.detail : 1;
    const stream = (name) => makeRng(hashSeed('asgard-bridge-of-light:' + name + ':' + ctx.seed));

    // ---------------- the sky: thick stars, the galaxy's arm and the star clouds in the south, small moons dealt within the southern half (azimuth 180 is due south)
    const mr = stream('moons'), moons = [];
    const great = { elevation: 24, azimuth: 164, size: 4.4, phase: 0.84, intensity: 0.85, glow: 0.12 };      // the one great pale moon, typed
    for (let i = 0; i < 4; i++) moons.push({ elevation: mr.range(18, 52), azimuth: mr.range(105, 255), size: mr.range(0.5, 1.2), phase: mr.range(0.55, 0.95), intensity: 0.8, glow: 0.1 });
    const sky = makeSky({ rng: stream('sky'), preset: 'night', bodies: [great, ...moons.slice(0, rare ? 4 : 3)], key: 'sun', clouds: false, clouds2: false, horizonFade: 0,
      zenith: '#050920', mid: '#0c1a48', horizon: mist ? '#2a4378' : '#1e3568', ground: '#1e3568', horizonPow: 2.6,
      stars: 1.3, starDensity: 0.65, twinkle: 0.85, milkyWay: 0.4, milkyAxis: [0.51, 0.81, -0.294], milkyAngle: -50, milkyColor: '#5f58c2', milkyCore: '#dba0bc',
      nebula: 0.6, nebulaColors: ['#5a2cb4', '#b8407c', '#a8641e'], nebulaScale: 1.3, nebulaCoverage: 0.56, nebulaSeed: CLOUD_FIELD,
      sunDirection: [-0.418, 0.518, -0.746], sunIntensity: 0, sunGlow: 0,
      lightColor: '#ffd9a0', lightIntensity: 1.6, ambientColor: '#5676c4', groundLight: '#2c3c6c', ambientIntensity: 2.4, lightElevationMin: 30,
      bake: true, renderer: ctx.renderer });
    scene.add(sky.object);
    scene.fog = new THREE.FogExp2(new THREE.Color(mist ? '#22386a' : '#182c5c'), mist ? 0.00042 : 0.0003);      // far things sink a little into the sky's own colour at the horizon
    const rig = makeLightRig(sky, { bounce: 0.3 }); scene.add(rig.object);
    const shared = makeShared(scene.fog);
    await ctx.yield();

    // ---------------- the sea with its bay, the veil and its mist, the stars under the sea's level; the city; the bridge, the gate house, the beam
    const sea = buildSea(ctx, shared, sky, { mist, detail }); scene.add(sea.object);
    await ctx.yield();
    const city = await buildCity(ctx, shared, { density: dens }); scene.add(city.object, city.image);
    await ctx.yield();
    const gate = await buildGate(ctx, shared); scene.add(gate.object, gate.image);
    await ctx.yield();

    // ---------------- the route and its named place, in metres flown; the two looks (see the head)
    const path = makePath(ROUTE), L = path.length, U = (m) => m / L, M = (p) => path.nearestXZ(p[0], p[2]).u * L;
    const mAbeam = M(ABEAM);      // where the globe's middle is due east of the line
    const look = (at, from, to, ramp, weight) => ({ at, from: U(from), to: U(to), fade: ramp / (to - from), weight });      // the engine's fade is the ramp's share of the span
    const pois = [
      look(V3(HOUSE.x, HOUSE.y, HOUSE.z), 0, mAbeam, 100, 0.45),
      look(V3(PALACE.x, PALACE.y + PALACE.tall / 2, PALACE.z), mAbeam, L, 200, 0.5),
    ];
    // ---------------- the pace (see the head): by places of the route in metres flown, smooth, a pure function of u
    const mLeave = M(LEAVE), mOne = M(OUTONE), mTwo = M(OUTTWO), mHook = M(HOOK), mOn = M(ONLINE), ease = (a, b, x) => { const t = clamp((x - a) / (b - a), 0, 1); return t * t * (3 - 2 * t); };
    const pace = (u) => { const m = u * L, out = 1 - ease(mOn - 25, mOn + 35, m); return 1 + 0.5 * ease(mLeave + 60, mOne - 110, m) * (1 - ease(mTwo - 170, mTwo - 20, m)) - 0.12 * ease(mTwo - 120, mTwo, m) * out - 0.3 * ease(mHook - 70, mHook, m) * out; };
    // ---------------- life: the kit's flocks of pale birds, each on the clock alone about its typed place, each kept clear of the flown line by place
    const flocks = [];
    for (const f of FLOCKS) {      // each flock's clearing is handed back to the page in slices of 6 birds
      flocks.push(await makeFlockAsync({ rng: stream(f.name), species: FLOCK_COMMON.species, center: f.center, radius: f.radius, wobble: f.wobble, height: FLOCK_COMMON.height, count: f.count, size: f.size,
        spread: f.spread, wander: FLOCK_COMMON.wander, maxSigma: FLOCK_COMMON.maxSigma, light: FLOCK_COMMON.light, keepClear: { path, dist: FLOCK_COMMON.clear } }, () => ctx.yield(), 6));
      await ctx.yield();
    }
    for (const f of flocks) scene.add(f.object);
    await ctx.yield();
    await sky.prewarm(ctx.renderer, null, scene);
    return {
      scene, path, duration: 65, pace, title: 'The Golden City and Its Bridge',      // 1,978 m; 30.4 m a second on the average
      camera: { fov: 70, near: 0.5, far: 9000, lookAhead: 30, sway: 0.4, bank: 0.25 },
      pois,
      portal: { shape: 'circle', radius: RING.r, color: '#ffe9c2', glow: 1.25, tilt: true },
      post: { exposure: 1.4, bloom: { strength: 0.28, radius: 0.32, threshold: 0.94 },
        grade: { saturation: 1.12, contrast: 1.05, tint: '#fff6ee', shadowTint: '#070b1c', vignette: 0.28, grain: 0.02, aberration: 0 } },
      update(dt, time, camera) {
        shared.uTime.value = time;
        sky.update(dt, time, camera); rig.update(dt, time, camera); gate.update(dt, time);
        for (const f of flocks) f.update(dt, time, camera);
      },
      dispose() {
        // each thing once: a part that frees its own is asked to; the sky frees its own (the sea's mirror and the stars under the
        // level only borrow its uniforms); everything else the scene holds (geometries, materials, textures) is freed here
        const own = new Set([sky.object]), done = new Set();
        for (const part of [sea, city, gate]) if (part && typeof part.dispose === 'function') { part.dispose(); for (const o of [part.object, part.image]) if (o) own.add(o); }
        for (const k in sky.uniforms) { const v = sky.uniforms[k] && sky.uniforms[k].value; if (v && v.isTexture) done.add(v); }
        const free = (o) => { if (o && typeof o.dispose === 'function' && !done.has(o)) { done.add(o); o.dispose(); } };
        const walk = (o) => {
          if (own.has(o)) return;
          free(o.geometry);
          for (const m of (Array.isArray(o.material) ? o.material : o.material ? [o.material] : [])) {
            for (const k in m) if (m[k] && m[k].isTexture) free(m[k]);
            if (m.uniforms) for (const k in m.uniforms) { const v = m.uniforms[k] && m.uniforms[k].value; if (v && v.isTexture) free(v); }
            free(m);
          }
          for (const ch of o.children) walk(ch);
        };
        walk(scene);
        if (typeof rig.dispose === 'function') rig.dispose();
        sky.dispose();
      },
    };
  },
};
